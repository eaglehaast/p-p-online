#!/usr/bin/env node
'use strict';

// Smoke test: файлы карт читаются через кэш браузера, а не мимо него.
//
// В maps.js стояло fetch(path, { cache: 'no-store' }). Это значит: манифест и все сорок
// одну карту браузер качает заново при КАЖДОМ запуске игры, всегда, даже если ничего не
// менялось. Замер на 600 кбит/с с задержкой 300 мс, ПОВТОРНЫЙ заход:
//
//   было:  42 запроса, 360 КБ, карты готовы через 18.6 с
//   стало: 42 ответа из кэша, 0 КБ, карты готовы через 0.17 с
//
// Проверялся и промежуточный вариант no-cache (всегда спрашивать, но тело не качать) —
// он не дал ничего: браузер всё равно получал полные ответы, время осталось прежним.
//
// Опасение, ради которого no-store обычно и ставят, — что игрок останется на старой карте
// после обновления, а в онлайне это разошлось бы с соперником. Здесь оно не работает:
// script.js, стили и все картинки кэшируются ровно так же. Игрок со старым кэшем держит
// старым ВСЁ, согласованно; исключение для одних только карт не защищало бы от
// расхождения, а наоборот делало бы карты рассинхронизированными с кодом.

const fs = require('fs');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const maps = fs.readFileSync('maps.js', 'utf8');
const server = fs.readFileSync('worker/local-server.js', 'utf8');

// === 1. ГЛАВНОЕ: карты больше не просят мимо кэша ===
{
  // В самом maps.js no-store назван в объяснении, почему его там больше нет. Ищем
  // настоящий вызов, а не рассказ о нём.
  const code = maps.replace(/\/\/.*$/gm, '');

  assert(!/cache:\s*['"]no-store['"]/.test(code),
    '1: карты снова читаются с cache: no-store — это 360 КБ и 42 запроса на каждый '
    + 'запуск игры, всегда');
  assert(/const response = await fetch\(path\);/.test(maps),
    '1b: запрос карт больше не обычный fetch — проверь, что именно ему передали');
}

// === 2. Ошибки по-прежнему видны ===
//
// Без этого пункт 1 прошёл бы и на варианте, где заодно выкинули проверку ответа, и
// битый JSON молча стал бы «картой без карты».
{
  const fn = /async function fetchJson\(path\)\{[\s\S]*?\n\}/.exec(maps);
  assert(fn, '2: fetchJson не найдена');
  assert(/if\(!response\.ok\)\{[\s\S]*?throw new Error/.test(fn[0]),
    '2b: неуспешный ответ больше не превращается в ошибку — карта пропадёт молча');
  assert(/return response\.json\(\);/.test(fn[0]),
    '2c: ответ перестал разбираться как JSON');
}

// === 3. Редактору карт это не мешает ===
//
// На своём компьютере правка карты должна быть видна сразу после перезагрузки, без
// хитростей. Это обеспечивает сервер, а не флаг в fetch: он отдаёт всё с no-cache.
{
  assert(/"cache-control": "no-cache"/.test(server),
    '3: локальный сервер перестал отдавать no-cache — теперь правка карты в редакторе '
    + 'не будет видна сразу, и придётся возвращать no-store в игру');
}

console.log('smoke-maps-use-http-cache: OK');
