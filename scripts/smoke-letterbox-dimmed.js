#!/usr/bin/env node
'use strict';

// Smoke test: подложка вокруг кадра приглушена — и только приглушена.
//
// Картинка подложки почти белая: средняя яркость 221 из 255. Рядом с доской (около 200)
// она не читалась фоном — два светлых пятна спорили друг с другом, а на планшете, где
// экран крупнее и ярче, это резало глаза. Поверх фона лёг затемняющий слой: замерено в
// игре, полоса вокруг кадра стала 128 вместо 197.
//
// Слой на всю страницу — вещь опасная ровно одним: он накрывает собой всё. Поэтому
// проверяется не «стало темнее» (это вкус), а то, что ломается молча: слой не ест
// нажатия, лежит под игрой, и у тела остался тёмный цвет на то время, пока картинка
// подложки ещё едет.

const fs = require('fs');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const styles = fs.readFileSync('styles.css', 'utf8');

const слой = /body::after\s*\{([^}]*)\}/.exec(styles);
assert(слой, '1: затемняющего слоя под подложкой нет');
const тело = слой[1];

// === 2. Слой не ест нажатия ===
//
// Без этого он накрывает игру целиком: доска перестаёт отвечать на касания, и выглядит
// это как «игра зависла», а не как «виноват фон».
assert(/pointer-events:\s*none/.test(тело),
  '2: слой перехватывает нажатия — доска перестанет отвечать на касания');

// === 3. Слой лежит ПОД игрой ===
assert(/z-index:\s*-1/.test(тело),
  '3: слой всплыл над страницей — затемнит не подложку, а всю игру');

// === 4. Он покрывает весь экран и не ездит при прокрутке ===
assert(/position:\s*fixed/.test(тело) && /inset:\s*0/.test(тело),
  '4: слой не прибит к экрану — подложка затемнится кусками');

// === 5. Затемнение заметное, но не чёрная заливка ===
//
// Числа подобраны по снимкам: при 0.4 полоса вокруг кадра выходит на 128 при доске
// около 205. Ниже 0.15 разницы не видно вовсе, выше 0.75 от бумажной подложки остаётся
// чёрный прямоугольник, и рамка перестаёт быть частью картинки.
const краска = /background:\s*rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/.exec(тело);
assert(краска, '5: затемнение задано не rgba — степень не прочитать');
const прозрачность = Number(краска[4]);
assert(прозрачность >= 0.15 && прозрачность <= 0.75,
  `5b: затемнение ${прозрачность} — вне рабочего предела 0.15..0.75`);
const яркостьКраски = (Number(краска[1]) + Number(краска[2]) + Number(краска[3])) / 3;
assert(яркостьКраски <= 60,
  `5c: затемняют светлой краской (яркость ${яркостьКраски}) — подложка посереет, а не потемнеет`);

// === 6. У тела остался тёмный цвет на время загрузки картинки ===
//
// Подложка весит 117 КБ, и пока она едет, виден именно он. Это и есть причина, по
// которой затемнение сделано слоем, а не background-blend-mode: при блендинге цветом
// фона становится множитель, и на это время экран стал бы светло-серым.
// Правило ищется по самой подложке, а не по селектору «body»: правил с этим селектором
// в файле несколько, и первое же из них — общий html, body с одной высотой.
const подложка = styles.lastIndexOf('letterbox2.webp');
assert(подложка !== -1, '6: подложка letterbox2.webp больше ниоткуда не берётся');
const правилоТела = styles.slice(styles.lastIndexOf('{', подложка), styles.indexOf('}', подложка));
assert(правилоТела.includes('background-image'), '6b: не найдено правило с подложкой');
assert(/background-color:\s*#101010/.test(правилоТела),
  '6c: у тела пропал тёмный цвет — пока грузится подложка, экран будет светлым');
assert(!/background-blend-mode/.test(правилоТела),
  '6d: затемнение вернулось в background-blend-mode — цветом фона станет множитель');

console.log('smoke-letterbox-dimmed: OK');
