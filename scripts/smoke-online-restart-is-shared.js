#!/usr/bin/env node
'use strict';

// Smoke test: перезагрузил страницу один — партия начинается заново у обоих, и обоим
// сказано почему.
//
// Комната теперь переживает партию, и у каждого есть свой адрес, по которому он в неё
// возвращается. Из-за этого перезагрузка страницы посреди игры перестала быть «я выпал и
// вернулся» и стала «у меня партия началась заново»: своего состояния вернувшийся не
// помнит, а комната хранит только последний снимок.
//
// Замерено на стенде ДО правки, обе стороны:
//
//   перезагрузился гость  — он навсегда остаётся в лобби (режим null), хозяин доигрывает
//                           четвёртый раунд один, ходы ездят на доску, которой уже нет;
//   перезагрузился хозяин — он начинает новую партию, а гость остаётся в старой: «start»
//                           до этой правки отбрасывался, если партия уже шла.
//
// Ни одна из сторон при этом ничего не сообщает. Человек видит, что «что-то криво
// обновляется», и винит игру целиком.
//
// Решение — то, о котором договорились: состояние не догоняем, а начинаем заново ОБА, и
// говорим об этом. Держится оно на трёх вещах:
//
//   1. Севший за стол заново объявляет об этом пакетом «rejoin». Моргнувший интернет
//      такого пакета не шлёт: там сессия та же, и перезапускаться не из-за чего.
//   2. Хозяин, получив его посреди партии, зовёт начинать заново обоих.
//   3. Кто получает «start», уже играя, — сбрасывает доску и показывает, что это не его
//      рук дело.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const source = fs.readFileSync('script.js', 'utf8');

function extractFunctionSource(text, name){
  const start = text.indexOf(`function ${name}(`);
  if(start === -1) throw new Error(`Не найдена функция ${name}`);
  let глубина = 0;
  let i = text.indexOf('(', start);
  for(; i < text.length; i += 1){
    if(text[i] === '(') глубина += 1;
    if(text[i] === ')'){ глубина -= 1; if(глубина === 0) break; }
  }
  const bodyStart = text.indexOf('{', i);
  let depth = 0;
  for(let j = bodyStart; j < text.length; j += 1){
    if(text[j] === '{') depth += 1;
    if(text[j] === '}') depth -= 1;
    if(depth === 0) return text.slice(start, j + 1);
  }
  throw new Error(`Не найден конец функции ${name}`);
}

// Стенд: настоящие решения, поддельные последствия.
function стенд({ хозяин = true, вПартии = true, заСтоломДвое = true } = {}){
  const sandbox = {
    Object, Boolean, String,
    console: { log: () => {}, warn: () => {} },
    отправлено: [],
    события: [],
    gameMode: вПартии ? 'online' : null,
    onlinePresence: { blue: true, green: заСтоломДвое },
    onlineInbox: [{ type: 'state' }],
    onlineSession: { seat: 'blue', host: хозяин, hostSeat: хозяин ? 'blue' : 'green' },
    postOnlineEnvelope: (тип) => { sandbox.отправлено.push(тип); return true; },
    applyOnlineMenuState: () => { sandbox.события.push('меню'); },
    handlePlayStart: () => { sandbox.события.push('начать'); return true; },
    resetGame: (опции) => { sandbox.события.push(`сброс:${JSON.stringify(опции)}`); },
  };
  vm.createContext(sandbox);
  vm.runInContext([
    source.match(/const TRANSFER_OPPONENT_RESTART_TEXT = "[^"]*";/)[0],
    'let чужойПерезапускНаПлашке = false;',
    extractFunctionSource(source, 'пометитьЧужойПерезапуск'),
    extractFunctionSource(source, 'взятьПометкуЧужогоПерезапуска'),
    extractFunctionSource(source, 'перезапуститьсяЗаСоперником'),
    extractFunctionSource(source, 'забытьПриехавшееДоНачала'),
    extractFunctionSource(source, 'isOnlineHost'),
    extractFunctionSource(source, 'isOnlineTableFull'),
    extractFunctionSource(source, 'startOnlineMatchAsHost'),
    extractFunctionSource(source, 'receiveOnlineStart'),
    extractFunctionSource(source, 'receiveOnlineRejoin'),
    'this.api = {',
    '  сел: receiveOnlineRejoin, начать: receiveOnlineStart,',
    '  начатьСамому: startOnlineMatchAsHost,',
    '  пометка: взятьПометкуЧужогоПерезапуска,',
    '  очередь: () => onlineInbox.length,',
    '};',
  ].join('\n'), sandbox);
  return { api: sandbox.api, стенд: sandbox };
}

// === 1. ГЛАВНОЕ: сел за стол заново — партия начинается заново у обоих ===
{
  const х = стенд({ хозяин: true, вПартии: true });
  assert(х.api.сел() === true,
    '1: хозяин не отозвался на «я сел заново» — соперник начнёт новую партию один, а его '
    + 'ходы поедут на доску, которой у нас уже нет');
  assert(х.стенд.отправлено.includes('start'),
    '1b: соперника не позвали начинать — он так и останется ждать в лобби навсегда');
  assert(х.стенд.события.some((с) => с.startsWith('сброс:')),
    '1c: сами мы не сбросились — продолжим доигрывать партию, которой у соперника нет');
  assert(х.api.пометка() === 'OPPONENT RESTARTED',
    '1d: доска сброшена молча — человек видит пустое поле и не знает почему');
}

// === 2. Сбрасываемся РОВНО ОДИН раз ===
//
// resetGame с forceGameScreen сам поднимает первый раунд. handlePlayStart рядом с ним
// поднимает его второй раз: замерено — у остававшегося в партии выходил раунд 2 против
// раунда 1 у вернувшегося, а следом расходился и первый ход, он считается от номера
// раунда.
{
  const х = стенд({ хозяин: true, вПартии: true });
  х.api.сел();
  const сбросы = х.стенд.события.filter((с) => с.startsWith('сброс:'));
  assert(сбросы.length === 1, `2: сбросов ${сбросы.length}, а нужен один`);
  assert(/forceGameScreen":true/.test(сбросы[0]),
    `2b: сброс уводит в меню («${сбросы[0]}») — а мы продолжаем играть, просто с начала`);
  assert(!х.стенд.события.includes('начать'),
    '2c: после сброса зовут ещё и начало партии — раунд начнётся дважды, и доски разойдутся');
}

// === 3. Решает хозяин, и только посреди партии ===
{
  const гость = стенд({ хозяин: false, вПартии: true });
  assert(гость.api.сел() === false,
    '3: гость тоже взялся перезапускать партию — решать должен кто-то один');
  assert(гость.стенд.отправлено.length === 0, '3b: и он же разослал «start»');

  const вЛобби = стенд({ хозяин: true, вПартии: false });
  assert(вЛобби.api.сел() === false,
    '3c: хозяин перезапускает партию, которой нет — обычный путь начнёт её сам, по приходу '
    + 'соперника за стол');
}

// === 4. «start» посреди партии больше не отбрасывается ===
//
// Это и есть вторая половина поломки: хозяин перезагрузился, начал заново и позвал
// гостя, а тот пакет выбросил и остался в старой партии.
{
  const г = стенд({ хозяин: false, вПартии: true });
  assert(г.api.начать() === true, '4: «start» посреди партии снова отброшен');
  assert(г.стенд.события.some((с) => с.startsWith('сброс:')),
    '4b: доска не сброшена — старая партия продолжится поверх новой');
  assert(г.api.пометка() === 'OPPONENT RESTARTED', '4c: и снова молча');
  assert(г.api.очередь() === 0,
    '4d: очередь приехавшего не вычищена — снимок старой партии ляжет на новую доску');
}

// === 5. Обычное начало партии ничего не объясняет ===
//
// Плашка «OPPONENT RESTARTED» на первой же партии была бы ложью.
{
  const г = стенд({ хозяин: false, вПартии: false });
  assert(г.api.начать() === true, '5: обычный «start» в лобби перестал начинать партию');
  assert(г.стенд.события.includes('начать'), '5b: партия не началась');
  assert(!г.стенд.события.some((с) => с.startsWith('сброс:')),
    '5c: в лобби сбрасывать нечего, а сброс всё равно зовут');
  assert(г.api.пометка() === '',
    '5d: первая же партия объявлена чужим перезапуском — это неправда');
}

// === 6. Пометка одноразовая ===
//
// Забытая взведённой, она объясняла бы чужим перезапуском каждый следующий раунд.
{
  const х = стенд({ хозяин: true, вПартии: true });
  х.api.сел();
  assert(х.api.пометка() === 'OPPONENT RESTARTED', '6: подготовка не удалась');
  assert(х.api.пометка() === '', '6b: пометка осталась взведённой — так подпишется и следующий раунд');
}

// === 7. Объявление о посадке шлёт тот, кто сел, и только он ===
//
// Отличие от моргнувшего интернета держится ровно на этом: при обрыве связи сессия та же,
// провод переподключается молча, и пакета нет. Начни его слать переподключение — партия
// перезапускалась бы на каждом чихе связи.
{
  const посадка = extractFunctionSource(source, 'startOnlineSession');
  assert(/postOnlineEnvelope\("rejoin"/.test(посадка),
    '7: севший за стол больше не объявляет об этом — хозяин не узнает, что соперник начал '
    + 'заново, и доски разойдутся молча');

  const провод = extractFunctionSource(source, 'createWebSocketTransport');
  assert(!/"rejoin"/.test(провод),
    '7b: «rejoin» шлёт провод — тогда он поедет и при переподключении, и партия будет '
    + 'перезапускаться на каждом обрыве связи');

  // И пакет этот ходит как все остальные: у комнаты он ничем не особенный.
  const приём = extractFunctionSource(source, 'receiveOnlineEnvelope');
  assert(/envelope\.t === "rejoin"/.test(приём), '7c: пакет некому разобрать');
  const комната = fs.readFileSync('worker/room.js', 'utf8');
  assert(!/rejoin/.test(комната),
    '7d: комната узнала про «rejoin» — ей знать про игру незачем, она пересылает');
}

// === 8. Плашка начала раунда показывает эту пометку ===
{
  const начало = source.slice(source.indexOf('const roundStartTurnTexts ='));
  const кусок = начало.slice(0, начало.indexOf('autoHideMs'));
  assert(/взятьПометкуЧужогоПерезапуска\(\)/.test(кусок),
    '8: плашка начала раунда не спрашивает про чужой перезапуск — сказать об этом больше негде');
  assert(/topText: верхняяСтрока/.test(кусок),
    '8b: посчитанная строка в плашку не попадает');
}

console.log('smoke-online-restart-is-shared: OK');
