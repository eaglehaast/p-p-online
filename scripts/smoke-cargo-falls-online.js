#!/usr/bin/env node
'use strict';

// Smoke test: ящик падает у обоих, а не только у ходившего.
//
// Жалоба с живой игры: «грузы, которые падают во время хода противника, появляются без
// анимации — в свой ход они падают как надо, а в ход противника просто ящики появляются».
//
// Причина не в анимации, а в снимке. Место ящика выбирается ОБЩИМИ костями (раунд и номер
// хода), поэтому у обоих он возникает в одной точке, и падение начинают оба. Но следом за
// ходом приезжает снимок партии, и список грузов заменялся целиком — ящиками «уже
// лежащими». Своё падение, начавшееся мгновением раньше, обрывалось почти сразу.
//
// Теперь падающий ящик на том же месте снимок не трогает. Всё остальное про грузы снимок
// по-прежнему решает сам: где они, сколько их, какие собраны.
//
// Проверяется именно граница между «своё» и «общее». Ошибиться тут можно в обе стороны, и
// вторая хуже первой: оставить своим слишком много — и ящик у двоих окажется в разных
// местах, то есть один полетит подбирать то, чего у другого нет.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const source = fs.readFileSync('script.js', 'utf8');

function extractFunctionSource(text, name){
  const start = text.indexOf(`function ${name}(`);
  if(start === -1) throw new Error(`Не найдена функция ${name}`);
  const bodyStart = text.indexOf('{', start);
  let depth = 0;
  for(let i = bodyStart; i < text.length; i += 1){
    if(text[i] === '{') depth += 1;
    if(text[i] === '}') depth -= 1;
    if(depth === 0) return text.slice(start, i + 1);
  }
  throw new Error(`Не найден конец функции ${name}`);
}

// Стенд: настоящая функция, поддельный список грузов.
function стенд(своиГрузы){
  const sandbox = {
    Array, Number, Math, Object,
    cargoState: своиГрузы.map((г) => ({ ...г })),
  };
  vm.createContext(sandbox);
  vm.runInContext([
    source.match(/const CARGO_SAME_SPOT_EPS = [\d.]+;/)[0],
    extractFunctionSource(source, 'применитьГрузИзСнимка'),
    'this.api = { применитьГрузИзСнимка, грузы: () => cargoState };',
  ].join('\n'), sandbox);
  return sandbox.api;
}

const ПАДАЕТ = {
  x: 100, y: 200, state: 'animating',
  animStartedAt: 12345, animDurationMs: 700, readyAtSim: 42, pickedAt: null,
};

// === 1. ГЛАВНОЕ: своё падение снимок не обрывает ===
{
  const стол = стенд([ПАДАЕТ]);
  стол.применитьГрузИзСнимка([{ x: 100, y: 200, state: 'ready' }]);
  const [ящик] = стол.грузы();
  assert(ящик.state === 'animating',
    '1: снимок положил ящик лежащим поверх своего падающего — в ход соперника ящик снова '
    + 'будет просто возникать');
  assert(ящик.animStartedAt === ПАДАЕТ.animStartedAt && ящик.readyAtSim === ПАДАЕТ.readyAtSim,
    '1b: падение подменили новым — оно начнётся заново и кончится позже, чем у соперника');
}

// === 2. Чужой ящик, которого у нас нет, кладётся как есть ===
//
// Переподключился посреди партии, пропустил ход, не видел ни одного падения. Снимок —
// единственное, откуда про этот ящик вообще известно.
{
  const стол = стенд([]);
  стол.применитьГрузИзСнимка([{ x: 300, y: 400, state: 'ready' }]);
  const [ящик] = стол.грузы();
  assert(ящик && ящик.state === 'ready' && ящик.x === 300 && ящик.y === 400,
    '2: ящик из снимка не появился — вернувшийся не увидит его вовсе');
  assert(ящик.readyAtSim === -Infinity,
    '2b: ящику из снимка назначен срок готовности — он станет недоступен без причины');
}

// === 3. Падающий В ДРУГОМ МЕСТЕ за свой не считается ===
//
// Это та ошибка, которая хуже исходной: ящик остался бы у двоих в разных местах, и один
// полетел бы подбирать то, чего у второго нет.
{
  const стол = стенд([{ ...ПАДАЕТ, x: 100, y: 200 }]);
  стол.применитьГрузИзСнимка([{ x: 180, y: 200, state: 'ready' }]);
  const грузы = стол.грузы();
  assert(грузы.length === 1, '3: грузов стало не столько, сколько в снимке');
  assert(грузы[0].x === 180 && грузы[0].state === 'ready',
    '3b: своё падение приняли за ящик из снимка, хотя они в разных местах — у двоих '
    + 'ящик окажется в разных точках поля');
}

// === 4. Снимок решает всё остальное ===
{
  // Собранный ящик остаётся собранным, даже если у нас он почему-то падает.
  const собран = стенд([ПАДАЕТ]);
  собран.применитьГрузИзСнимка([{ x: 100, y: 200, state: 'collected' }]);
  assert(собран.грузы()[0].state === 'collected',
    '4: соперник подобрал ящик, а у нас он продолжает падать');

  // Ящика нет в снимке — нет и у нас.
  const пусто = стенд([ПАДАЕТ]);
  пусто.применитьГрузИзСнимка([]);
  assert(пусто.грузы().length === 0,
    '4b: ящик, которого в снимке нет, остался на поле — он будет мерещиться одному из двоих');

  // И обратное: у нас ящик подобран, а в снимке он лежит. Прав снимок — подобрал его
  // соперник или не подобрал, решает тот, кто ходил. Оставить своё значит стереть с поля
  // ящик, который там есть.
  const воскрес = стенд([{ ...ПАДАЕТ, state: 'collected' }]);
  воскрес.применитьГрузИзСнимка([{ x: 100, y: 200, state: 'ready' }]);
  assert(воскрес.грузы()[0].state === 'ready',
    '4b2: у нас ящик числится собранным, в снимке он лежит — и мы оставили своё. Ящик '
    + 'есть на поле, но для нас его нет');

  // Количество и порядок — из снимка.
  const трое = стенд([ПАДАЕТ]);
  трое.применитьГрузИзСнимка([
    { x: 10, y: 20, state: 'ready' },
    { x: 100, y: 200, state: 'ready' },
    { x: 30, y: 40, state: 'collected' },
  ]);
  const грузы = трое.грузы();
  assert(грузы.length === 3, '4c: число ящиков берётся не из снимка');
  assert(грузы[1].state === 'animating', '4d: своё падение потерялось среди прочих');
  assert(грузы[0].x === 10 && грузы[2].x === 30, '4e: порядок ящиков разъехался со снимком');
}

// === 5. Допуск на совпадение места — строгий ===
//
// Координаты в снимке округлены до сотых, поэтому ноль не годится. Но и большим он быть не
// может: два ящика рядом — это два разных ящика.
{
  const округлён = стенд([{ ...ПАДАЕТ, x: 100.004, y: 199.998 }]);
  округлён.применитьГрузИзСнимка([{ x: 100, y: 200, state: 'ready' }]);
  assert(округлён.грузы()[0].state === 'animating',
    '5: округление координат в снимке разводит ящик с самим собой');

  const допуск = Number(/const CARGO_SAME_SPOT_EPS = ([\d.]+);/.exec(source)[1]);
  assert(допуск > 0 && допуск <= 4,
    `5b: допуск ${допуск} — либо не переживёт округления, либо склеит соседние ящики`);
}

// === 6. Снимок зовёт именно эту функцию ===
//
// Иначе проверки выше проверяют код, который никто не вызывает.
{
  const применение = extractFunctionSource(source, 'applyMatchState');
  assert(/применитьГрузИзСнимка\(state\.cargo\)/.test(применение),
    '6: применение снимка больше не зовёт разбор грузов — падение опять будет обрываться');

  // И отправитель по-прежнему пишет падающий ящик лежащим: решать, падает он или нет,
  // должен получатель, а не отправитель.
  const запись = extractFunctionSource(source, 'serializeMatchState');
  assert(/state:\s*cargo\?\.state === "animating" \? "ready"/.test(запись),
    '6b: в снимок уехало состояние «падает» — у получателя оно начнёт жить своей жизнью, '
    + 'и момент готовности разойдётся');
}

console.log('smoke-cargo-falls-online: OK');
