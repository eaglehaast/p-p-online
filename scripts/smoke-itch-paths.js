#!/usr/bin/env node
'use strict';

// Smoke test: игра не привязана к одному адресу.
//
// На github.io страница лежит в каталоге /p-p-online/, на itch — в корне архива, в
// телеграме открывается третьим способом. Абсолютный путь вида «/p-p-online/...»
// работает ровно на первом из них, а на остальных молча даёт 404: картинка не
// показывается, шрифт не подхватывается, и понять, что случилось, по экрану нельзя.
//
// Так и попался значок вкладки: сборка для itch отдавала 404 на /p-p-online/favicon.ico,
// и видно это было только в журнале сервера.
//
// Проверяется два разных обещания:
//
//   1. В разметке нет путей от корня сайта. Это и есть правило, которое нарушили.
//   2. Сборщик архива кладёт index.html в корень и не тащит туда лишнего: itch ищет
//      index.html именно в корне, а проверки и ретранслятор на чужой площадке не нужны.

const fs = require('fs');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const markup = fs.readFileSync('index.html', 'utf8');
const settingsMarkup = fs.existsSync('settings.html')
  ? fs.readFileSync('settings.html', 'utf8')
  : '';
const builder = fs.readFileSync('scripts/build-itch.js', 'utf8');

// === 1. ГЛАВНОЕ: в разметке нет путей от корня сайта ===
//
// Ищем src="/..." и href="/..." — но не «//» (это другой домен целиком) и не внешние
// адреса: ссылка на github.com в подписи автора совершенно законна.
{
  for(const [имя, текст] of [['index.html', markup], ['settings.html', settingsMarkup]]){
    if(!текст) continue;
    const найдено = [...текст.matchAll(/(?:src|href)="(\/[^\/"][^"]*)"/g)].map((м) => м[1]);
    assert(найдено.length === 0,
      `1: в ${имя} путь от корня сайта: ${найдено.join(', ')} — он работает только на `
      + 'github.io, а на itch и в телеграме молча даёт 404');
  }
}

// === 2. Значок вкладки — именно тот случай, на котором это поймали ===
{
  const значок = /<link[^>]+rel="icon"[^>]*>/.exec(markup);
  assert(значок, '2: ссылки на значок вкладки нет вовсе');
  assert(/href="favicon\.ico"/.test(значок[0]),
    `2b: значок снова взят по абсолютному пути (${значок[0]}) — на itch его не будет`);
}

// === 3. Сборщик кладёт index.html в корень архива ===
//
// itch ищет его именно там. Окажется в подпапке — страница не откроется вовсе.
{
  assert(/'index\.html',/.test(builder), '3: сборщик не кладёт index.html в архив');
  assert(/index\.html.*itch требует его в корне|itch требует его в корне/.test(builder),
    '3b: в сборщике не сказано, почему index.html обязателен — следующий решит, что это один из файлов');
  assert(/не в корне сборки/.test(builder),
    '3c: сборщик не проверяет, что index.html оказался в корне');
}

// === 4. Лишнего в архив не кладём ===
//
// Проверки и ретранслятор на чужой площадке не нужны: ретранслятор живёт в облаке, а
// тесты — это полтора мегабайта чужому человеку в браузер.
{
  const список = builder.slice(builder.indexOf('const НУЖНОЕ'), builder.indexOf('];', builder.indexOf('const НУЖНОЕ')));
  for(const лишнее of ['scripts', 'worker', 'docs', '.github']){
    assert(!new RegExp(`'${лишнее.replace('.', '\\.')}'`).test(список),
      `4: в архив кладут «${лишнее}» — на itch этому делать нечего`);
  }
  // А нужное — на месте: без карт игра не начнётся вовсе.
  for(const нужное of ['script.js', 'styles.css', 'maps.js', 'ui_gamescreen', 'fonts']){
    assert(список.includes(`'${нужное}'`),
      `4b: в архиве не будет «${нужное}» — игра на itch не откроется`);
  }
}

console.log('smoke-itch-paths: OK');
