#!/usr/bin/env node
'use strict';

// Smoke test: окошко со ссылками автора за подписью внизу меню.
//
// Крестика у окошка нет нарочно: закрывается оно нажатием мимо. Значит вся конструкция
// держится на затемнении — оно растянуто на кадр, ловит нажатие и заодно закрывает собой
// кнопки меню. Стоит ему уехать по слоям под кнопки, и получится худшее из возможного:
// окошко открыто, а нажатие проваливается в «Play» под ним.
//
// Второе, что тут легко потерять: строка без адреса. Пустой href — это ссылка в никуда,
// на вид рабочая. Она обязана не показываться вовсе.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const script = fs.readFileSync('script.js', 'utf8');
const styles = fs.readFileSync('styles.css', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');

// === 1. Разметка: подпись — кнопка, окошко и затемнение спрятаны ===
{
  const кнопка = /<button id="menuSignature"[\s\S]*?<\/button>/.exec(html);
  assert(кнопка, '1: подпись перестала быть кнопкой — окошко открывать нечем');
  assert(/aria-expanded="false"/.test(кнопка[0]) && /aria-controls="authorLinks"/.test(кнопка[0]),
    '1b: у подписи нет aria-expanded / aria-controls — читалка не узнает, что за ней окошко');

  assert(/<div id="authorLinksBackdrop"[^>]*\shidden\b/.test(html),
    '1c: затемнение не спрятано в разметке — меню откроется уже затемнённым');
  assert(!/authorLinksTitle/.test(html),
    '1d0: на листе снова прозвище автора — оно уже стоит на кнопке, которой лист и '
    + 'открывают, и повторять его нечем');
  assert(/<div id="authorLinks"[^>]*\shidden\b/.test(html),
    '1d: окошко не спрятано в разметке');

  // Ссылки уводят наружу, в новую вкладку. rel обязателен: без него открытая страница
  // получает доступ к окну игры через window.opener.
  const строки = html.match(/<a class="author-links__row"[\s\S]*?<\/a>/g) || [];
  assert(строки.length >= 1, '1e: в окошке не осталось ни одной строки');
  for(const строка of строки){
    assert(/target="_blank"/.test(строка), '1f: строка ссылок открывается не в новой вкладке');
    assert(/rel="noopener noreferrer"/.test(строка),
      '1g: у строки ссылок нет rel="noopener noreferrer" — чужая страница получит окно игры');

    // Адрес обязан быть полным и внешним. Относительный путь уведёт не наружу, а внутрь
    // github.io/p-p-online/ — ссылка будет рабочей на вид и приведёт на 404.
    const адрес = (/href="([^"]*)"/.exec(строка) || [])[1];
    assert(/^https:\/\/\S+$/.test(адрес),
      `1f1: адрес строки ссылок не абсолютный https: "${адрес}"`);
  }
}

// === 1h. Лист нарисован целиком, и коробка под него подогнана ===
//
// Лист — не текстура, а картинка вместе с обрывом по всем четырём краям. Из этого растут
// три условия, и каждое ломается молча, одними глазами на живом экране:
//
//   — коробка обязана повторять пропорцию картинки, потому что растянута она 100% 100%.
//     Перекос превратит нарисованную клетку в прямоугольники;
//   — ни заливки, ни рамки, ни box-shadow: любой прямоугольник подрисует обрыву ровный
//     край, и лист станет панелью с рваной картинкой внутри;
//   — поля должны быть глубже обрыва, иначе строка полезет на рваньё.
//
// Картинка лежит в WebP, а читалка альфы в проекте понимает только png. Поэтому глубина
// обрыва снята один раз и записана здесь числом, а сам файл запечатан размером: подменят
// лист — тест упадёт и потребует перемерить. Размер холста при этом читается по-настоящему,
// из заголовка VP8X.
const ОБРЫВ_ПО_КРАЯМ = 39;     // точек исходника, p99 без самых углов; по краям 38-39
const ЗАПЕЧАТАН = 138276;      // байт mm_links_paper.webp, на котором снято число выше

// Холст WebP. Расширенный формат (а он тут расширенный — в картинке есть альфа) держит
// размеры в чанке VP8X: по три байта на сторону, младшим вперёд, минус единица.
function холстWebp(путь){
  const b = fs.readFileSync(путь);
  assert(b.slice(0, 4).toString('latin1') === 'RIFF' && b.slice(8, 12).toString('latin1') === 'WEBP',
    `1h3: ${путь} не WebP — внутри что-то другое`);
  assert(b.slice(12, 16).toString('latin1') === 'VP8X',
    `1h4: у ${путь} нет чанка VP8X — картинка пересохранена без альфы, и обрыв стал белым`);
  return { width: b.readUIntLE(24, 3) + 1, height: b.readUIntLE(27, 3) + 1 };
}

const правилоЛиста = /#menuLayer #modeMenu \.author-links\s*\{([^}]*)\}/.exec(styles);
assert(правилоЛиста, '1j: не найдено правило окошка');
const ЛИСТ = правилоЛиста[1];
const ШИРИНА = Number(/width:\s*(\d+)px/.exec(ЛИСТ)[1]);

// Поля теперь не у самого листа, а у блока со строками, и заданы долями — по клетке.
//
// Проценты в полях считаются от РОДИТЕЛЯ, а у листа есть max-width: на узком экране он уже
// родителя, и собственные поля в процентах разъехались бы с его же клеткой. Ширина и поля
// внутреннего блока считаются от листа.
const правилоБлока = /#menuLayer #modeMenu \.author-links__sheet\s*\{([^}]*)\}/.exec(styles);
assert(правилоБлока, '1h0: не найден блок со строками — полей, привязанных к клетке, больше нет');
const БЛОК = правилоБлока[1];
const доля = (где, имя) => {
  const m = new RegExp(`${имя}:\\s*([\\d.]+)%`).exec(где);
  assert(m, `1h0b: у блока нет ${имя} в долях — к клетке его больше ничто не привязывает`);
  return Number(m[1]);
};
const поле = { слева: доля(БЛОК, 'margin-left'), ширина: доля(БЛОК, 'width') };

// Холст картинки нужен и ниже, за пределами того блока, где он проверяется.
const бумагаПуть = /--author-links-paper:\s*url\("([^"]+)"\)/.exec(styles);
assert(бумагаПуть, '1h: у окошка ссылок нет бумаги — оно снова просто панель');
const { width: Ш, height: В } = холстWebp(бумагаПуть[1]);

{
  const бумага = /--author-links-paper:\s*url\("([^"]+)"\)/.exec(styles);
  assert(бумага, '1h: у окошка ссылок нет бумаги — оно снова просто панель');
  assert(fs.existsSync(бумага[1]), `1h1: бумаги нет на месте: ${бумага[1]}`);
  assert(/var\(--author-links-paper\)/.test(ЛИСТ),
    '1k1: окошко перестало брать бумагу из своих токенов');
  assert(/background-repeat:\s*no-repeat/.test(ЛИСТ),
    '1k2: бумага замостилась — обрыв нарисован по краям картинки и пойдёт полосами');
  assert(/background-size:\s*100%\s+100%/.test(ЛИСТ),
    '1k3: лист перестал растягиваться на коробку — обрыв обрежется её гранью');

  assert(fs.statSync(бумага[1]).size === ЗАПЕЧАТАН,
    `1h5: лист подменили (${fs.statSync(бумага[1]).size} байт вместо ${ЗАПЕЧАТАН}). Глубина `
    + 'обрыва в этом тесте снята с прежнего файла — перемерь её по новому и поправь '
    + 'ОБРЫВ_ПО_КРАЯМ вместе с этой печатью');

  // Пропорция. Коробке её задаёт aspect-ratio, и она обязана совпасть с холстом картинки.
  const отношение = /aspect-ratio:\s*(\d+)\s*\/\s*(\d+)/.exec(ЛИСТ);
  assert(отношение, '1m: у листа нет aspect-ratio — высота поедет за текстом, и лист с ней');
  const коробка = Number(отношение[1]) / Number(отношение[2]);
  assert(Math.abs(коробка - Ш / В) < 0.005,
    `1m1: коробка идёт ${коробка.toFixed(3)}, а холст листа — ${(Ш / В).toFixed(3)}: `
    + 'нарисованная клетка растянется в прямоугольники');

  // Ни одного прямоугольника поверх обрыва.
  for(const [свойство, чем] of [
    ['background-color', 'заливка'], ['box-shadow', 'тень коробки'], ['border-radius', 'скругление']
  ]){
    assert(!new RegExp(`(^|;)\\s*${свойство}:`).test(ЛИСТ),
      `1n: у листа снова ${чем} (${свойство}) — она обведёт рваный край ровной рамкой`);
  }
  assert(!/(^|;)\s*border:\s*(?!none)/.test(ЛИСТ),
    '1n1: у листа снова рамка — прямоугольник поверх обрыва');
  assert(/filter:\s*drop-shadow\(/.test(ЛИСТ),
    '1n2: тень листа перестала быть drop-shadow — по силуэту её больше не видно');

  // Поля глубже обрыва. Обрыв съедает у листа край, и поле должно начинаться уже за ним,
  // иначе строка ляжет на рваньё. Теперь всё в долях листа, поэтому и порог в долях.
  const надоДоля = ОБРЫВ_ПО_КРАЯМ / Ш * 100;
  const справа = 100 - поле.слева - поле.ширина;
  for(const [имя, есть] of [['слева', поле.слева], ['справа', справа]]){
    assert(есть >= надоДоля,
      `1o: поле ${имя} — ${есть.toFixed(2)}%, а обрыв на картинке съедает `
      + `${надоДоля.toFixed(2)}%: строка ляжет на рваный край`);
  }
}

// === 1p. Написанное влезает в лист ===
//
// Высота у листа своя, от текста не зависит: она посчитана из ширины по пропорции картинки.
// Значит строки не раздвинут лист, а просто вылезут за него — на доску, мимо бумаги.
// Появится четвёртая строка или вырастет шрифт — здесь и должно грохнуть.
{
  const правилоСтроки = /#menuLayer #modeMenu \.author-links__row\s*\{([^}]*)\}/.exec(styles);
  assert(правилоСтроки, '1p: не найдено правило строки');
  const высотаСтроки = доля(правилоСтроки[1], 'height');
  const строк = (html.match(/<a class="author-links__row"/g) || []).length;

  const занято = строк * высотаСтроки;
  const свободно = 100 - 2 * (ОБРЫВ_ПО_КРАЯМ / В * 100);
  assert(занято <= свободно,
    `1p1: ${строк} строк занимают ${занято.toFixed(1)}% высоты листа, а до рваных краёв `
    + `свободно ${свободно.toFixed(1)}%: строки вылезут на доску, мимо бумаги`);
}

// === 1q. Написанное стоит по клетке листа ===
//
// Это и была жалоба: «тексты как-то на клетку некрасиво слева наезжают». Клетка — главный
// признак тетрадного листа, и надпись, стоящая поперёк неё, читается как случайно
// брошенная.
//
// Шаг клетки замерен по самой картинке: по горизонтали линии идут от 87.5 с шагом 72.86,
// по вертикали от 68.5 с шагом 71.06. Подмену картинки ловит печать 1h5 выше, поэтому
// числа здесь можно держать константами.
{
  const ПЕРВАЯ_X = 87.5, ШАГ_X = 72.86;
  const ШАГ_Y = 71.06;
  const наЛинии = (процент, первая, шаг, размер) => {
    const точка = процент / 100 * размер;
    const k = Math.round((точка - первая) / шаг);
    return Math.abs(первая + k * шаг - точка) / размер * 100;
  };

  const промахСлева = наЛинии(поле.слева, ПЕРВАЯ_X, ШАГ_X, Ш);
  assert(промахСлева < 0.3,
    `1q: левое поле ${поле.слева}% мимо линии клетки на ${промахСлева.toFixed(2)}% — текст `
    + 'встанет поперёк разлиновки');
  const промахСправа = наЛинии(поле.слева + поле.ширина, ПЕРВАЯ_X, ШАГ_X, Ш);
  assert(промахСправа < 0.3,
    `1q2: правый край блока мимо линии на ${промахСправа.toFixed(2)}% — адреса справа `
    + 'повиснут между линейками');

  // Высота строки — целое число клеток. Тогда строки стоят ПО линейкам, и остаются по ним
  // при любом их числе: спрятанная строка сдвигает столбик тоже на целые клетки.
  const правилоСтроки = /#menuLayer #modeMenu \.author-links__row\s*\{([^}]*)\}/.exec(styles);
  const высотаСтроки = доля(правилоСтроки[1], 'height') / 100 * В;
  const клеток = высотаСтроки / ШАГ_Y;
  assert(Math.abs(клеток - Math.round(клеток)) < 0.03 && Math.round(клеток) >= 1,
    `1q3: строка высотой ${клеток.toFixed(2)} клетки — она не ляжет на линейки, и со `
    + 'спрятанной строкой столбик съедет на половину клетки');
}

// === 1l. В строке только то, что видно ===
//
// Пустое место под значок отсюда убрано: картинок так и не появилось, а невидимая коробка
