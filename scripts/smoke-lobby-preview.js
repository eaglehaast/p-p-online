#!/usr/bin/env node
'use strict';

// Smoke test: режим предпросмотра лобби (?lobby=preview).
//
// Лобби нельзя посмотреть просто так: кнопка «Online» выключена без ретранслятора, а
// экран гостя вдобавок требует живого хозяина. Режим показывает оба без сети — на нём
// держится вся работа над этим экраном.
//
// Ломается он двумя способами, и оба тихие.
//
// Первый: режим протечёт в обычный запуск. Он трогает классы меню и гасит «Play», то есть
// без флага обязан не делать ВООБЩЕ ничего — иначе игрок получит лобби посреди меню.
//
// Второй: виды разойдутся с игрой. Классы, которыми режим переключает экраны, — те же
// самые, что ставит сама игра. Переименуют их в одном месте, забудут в другом — и
// предпросмотр начнёт показывать пустое меню, а понять это можно будет только глазами.

const fs = require('fs');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const script = fs.readFileSync('script.js', 'utf8');
const styles = fs.readFileSync('styles.css', 'utf8');

const кусок = /\(function предпросмотрЛобби\(\)\{[\s\S]*?\n\}\)\(\);/.exec(script);
assert(кусок, '0: режим предпросмотра лобби не найден в script.js');
const РЕЖИМ = кусок[0];

// === 1. Без флага режим не просыпается ===
//
// Проверяется первым же выражением: выход стоит ДО всего остального. Условие, уехавшее
// ниже, оставило бы побочные действия в обычном запуске.
{
  assert(/lobby.*!==\s*["']preview["']\)\s*return;/.test(РЕЖИМ),
    '1: режим больше не проверяет ?lobby=preview первым делом');

  const первыйReturn = РЕЖИМ.indexOf('return;');
  for(const опасное of ['classList', 'appendChild', 'disabled']){
    const где = РЕЖИМ.indexOf(опасное);
    assert(где === -1 || где > первыйReturn,
      `1b: «${опасное}» стоит ДО выхода по флагу — режим протечёт в обычный запуск`);
  }
}

// === 2. Ничего не создаётся и не запоминается ===
//
// Предпросмотр — картинка, а не игра. Комнату он создавать не должен (иначе на живом сайте
// пойдут попытки подключения), и режим в localStorage писать тоже.
{
  for(const [что, зачем] of [
    ['createOnlineRoom', 'создаёт комнату'],
    ['startOnlineSession', 'заводит сессию'],
    ['setStoredGameMode', 'пишет режим в localStorage'],
    ['WebSocket', 'открывает сокет']
  ]){
    assert(!РЕЖИМ.includes(что),
      `2: предпросмотр ${зачем} (${что}) — он обязан быть без сети и без следов`);
  }
}

// === 3. Экраны у предпросмотра те же, что у игры ===
//
// Оба состояния лобби держатся на двух классах, и ставят их в двух местах: игра — в
// applyOnlineMenuState, предпросмотр — у себя. Разъедутся имена, и предпросмотр покажет
// пустое меню, а стили останутся без хозяина.
{
  const КЛАССЫ = ['is-online-host', 'is-online-guest'];
  const игра = /function applyOnlineMenuState\(\)\{[\s\S]*?\n\}/.exec(script);
  assert(игра, '3: applyOnlineMenuState не найдена');

  for(const класс of КЛАССЫ){
    assert(игра[0].includes(класс), `3b: игра больше не ставит класс ${класс}`);
    assert(РЕЖИМ.includes(класс), `3c: предпросмотр больше не показывает ${класс}`);
    assert(styles.includes(`.${класс}`), `3d: у класса ${класс} нет стилей`);
  }

  // Видов должно быть больше одного, иначе переключать нечего.
  const виды = [...РЕЖИМ.matchAll(/имя:\s*"([^"]+)"/g)].map((m) => m[1]);
  assert(виды.length >= 3,
    `3e: в режиме всего ${виды.length} видов — показывать почти нечего`);
  assert(виды.some((имя) => /мен/i.test(имя)),
    '3f: из предпросмотра нельзя вернуться в обычное меню — а сравнивать надо с ним');
}

// === 4. «Play» переключается руками ===
//
// Это единственный указатель на то, что соперник пришёл: строки состояния больше нет.
// Значит показать надо ОБА его вида — и погасший, и загоревшийся, — иначе половину
// экрана хозяина нарисуют вслепую.
{
  assert(/playBtn/.test(РЕЖИМ),
    '4: предпросмотр не трогает «Play» — а весь экран хозяина держится на ней');
  const состояния = [...РЕЖИМ.matchAll(/play:\s*(true|false)/g)].map((m) => m[1] === 'true');
  assert(состояния.some(Boolean) && состояния.some((v) => !v),
    '4b: показан только один вид «Play» — второй нарисуют вслепую');
}

// === 5. Полоса переключателя не лезет в кадр ===
//
// Её задача — не мешать смотреть. Кадр прижимает пункты лобби к середине и низу, поэтому
// полоса живёт сверху и вне #uiFrame.
{
  assert(/document\.body\.appendChild\(полоса\)/.test(РЕЖИМ),
    '5: полоса переключателя больше не вне кадра — она попадёт в то, что оценивают');
  assert(/position:fixed[^"]*top:0/.test(РЕЖИМ),
    '5b: полоса уехала с верхней грани — снизу она накроет нижние пункты');
}

console.log('smoke-lobby-preview: OK');
