#!/usr/bin/env node
'use strict';

// Smoke test: режим предпросмотра лобби (?lobby=preview).
//
// Лобби нельзя посмотреть просто так: кнопка «Online» выключена без ретранслятора, а
// половина текста на панели появляется только при живом сопернике. Режим показывает её
// без сети и переключает состояния руками — тем и держится рисование этого экрана.
//
// Ломается он двумя способами, и оба тихие.
//
// Первый: список состояний разойдётся с игрой. Тексты в режиме повторены, а не взяты у
// getOnlineLobbyStatusText() — без сессии та вернёт пустую строку. Поправят строку в игре,
// забудут здесь — и рисовать будут по надписи, которой игрок никогда не увидит. Поэтому
// каждая строка режима ищется в самой игре, и наоборот: каждая строка игры — в режиме.
//
// Второй: режим протечёт в обычный запуск. Он трогает selectedMode и показывает панель,
// то есть без флага обязан не делать ВООБЩЕ ничего — иначе игрок получит лобби посреди
// меню и режим «online», которого не выбирал.

const fs = require('fs');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const script = fs.readFileSync('script.js', 'utf8');

const кусок = /\(function предпросмотрЛобби\(\)\{[\s\S]*?\n\}\)\(\);/.exec(script);
assert(кусок, '0: режим предпросмотра лобби не найден в script.js');
const РЕЖИМ = кусок[0];

// === 1. Без флага режим не просыпается ===
//
// Проверяется первым же выражением: выход из функции стоит ДО всего остального, включая
// возню с selectedMode. Условие, уехавшее ниже, оставило бы побочные действия в обычном
// запуске.
{
  assert(/lobby.*!==\s*["']preview["']\)\s*return;/.test(РЕЖИМ),
    '1: режим больше не проверяет ?lobby=preview первым делом');

  const первыйReturn = РЕЖИМ.indexOf('return;');
  for(const опасное of ['selectedMode', 'updateModeSelection', 'appendChild', 'hidden = false']){
    const где = РЕЖИМ.indexOf(опасное);
    assert(где === -1 || где > первыйReturn,
      `1b: «${опасное}» стоит ДО выхода по флагу — режим протечёт в обычный запуск`);
  }
}

// === 2. Ничего не создаётся и не запоминается ===
//
// Предпросмотр — это картинка, а не игра. Комнату он создавать не должен (иначе на живом
// сайте пойдут попытки подключения), и режим «online» в localStorage писать тоже: игрок
// потом откроет игру и получит выбранным то, чего не выбирал.
{
  for(const [что, зачем] of [
    ['createOnlineRoom', 'создаёт комнату'],
    ['startOnlineSession', 'заводит сессию'],
    ['setStoredGameMode', 'пишет режим в localStorage'],
    ['WebSocket', 'открывает сокет']
  ]){
    assert(!РЕЖИМ.includes(что),
      `2: предпросмотр ${зачем} (${что}) — он обязан быть без сети и без следов`);
  }
}

// === 3. Состояния режима и состояния игры — один и тот же список ===
//
// Тексты игрок читает целиком, и рисуют экран по самой длинной строке. Разойдись списки —
// и раскладку подгонят под надпись, которой в игре нет.
{
  const изРежима = [...РЕЖИМ.matchAll(/текст:\s*"([^"]+)"/g)].map((m) => m[1]);
  assert(изРежима.length >= 8,
    `3: в режиме всего ${изРежима.length} состояний — список обеднел`);

  // Откуда игра берёт эти строки: сама функция состояния плюс ответ на неудачный вход.
  const начало = script.indexOf('function getOnlineLobbyStatusText(');
  assert(начало > 0, '3b: getOnlineLobbyStatusText не найдена');
  const функция = script.slice(начало, script.indexOf('\n}\n', начало));

  const начатьВход = script.indexOf('if(onlineLobbyJoinBtn instanceof HTMLElement){');
  assert(начатьВход > 0, '3c: обработчик кнопки Join не найден');
  const вход = script.slice(начатьВход, script.indexOf('\n}\n', начатьВход));

  const изИгры = [...(функция + вход).matchAll(/"([A-Z][^"\\]{9,})"/g)]
    .map((m) => m[1])
    .filter((s) => /[.…]$/.test(s));
  assert(изИгры.length >= 8, `3d: из игры вычитано всего ${изИгры.length} строк — тест ослеп`);

  for(const текст of изРежима){
    assert(изИгры.includes(текст),
      `3e: состояние «${текст}» есть в предпросмотре, но не в игре — рисовать будут по `
      + 'надписи, которой игрок не увидит');
  }
  for(const текст of изИгры){
    assert(изРежима.includes(текст),
      `3f: игра показывает «${текст}», а в предпросмотре такого состояния нет — этот экран `
      + 'нарисуют вслепую');
  }
}

// === 4. Признак «соперник на месте» переключается вместе с текстом ===
//
// Класс is-ready красит состояние в зелёное и утолщает шрифт. Забыть его — значит рисовать
// все состояния одинаковыми, а в игре одно из них выглядит иначе.
{
  assert(/classList\.toggle\("is-ready"/.test(РЕЖИМ),
    '4: предпросмотр не переключает is-ready — «соперник на месте» будет неотличим');

  const готовых = [...РЕЖИМ.matchAll(/готово:\s*(true|false)/g)].map((m) => m[1] === 'true');
  assert(готовых.some(Boolean) && готовых.some((v) => !v),
    '4b: в списке состояний нет обоих видов is-ready — половина оформления не показывается');
}

// === 5. Полоса переключателя не лезет в кадр ===
//
// Её задача — не мешать смотреть. Кадр прижимает лобби к нижней грани, поэтому полоса
// живёт сверху и вне #uiFrame; уедет вниз — накроет ровно ту строку, ради которой всё.
{
  assert(/document\.body\.appendChild\(полоса\)/.test(РЕЖИМ),
    '5: полоса переключателя больше не вне кадра — она попадёт в то, что оценивают');
  assert(/position:fixed[^"]*top:0/.test(РЕЖИМ),
    '5b: полоса уехала с верхней грани — снизу она накроет нижнюю строку лобби');
}

console.log('smoke-lobby-preview: OK');
