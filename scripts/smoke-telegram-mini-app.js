#!/usr/bin/env node
'use strict';

// Smoke test: игра внутри телеграма.
//
// В мини-приложении страницей распоряжается не только браузер, но и сам телеграм, и одно
// его правило делает игру неиграбельной: перетаскивание пальцем вниз он считает жестом
// «свернуть приложение». А перетаскивание пальцем — это у нас прицеливание. Поймано на
// живом айфоне: тянешь самолёт назад, и вместо прицела уезжает вниз всё окно.
//
// Выключается это его же вызовом disableVerticalSwipes (Bot API 7.7). Отсюда три вещи,
// каждая из которых ломается тихо:
//
//   1. Снаружи телеграма его скрипт грузить нельзя. Игра живёт ещё на github.io и на
//      итче; лишний запрос к чужому домену там не нужен никому, а на итче его могут и
//      не пустить.
//   2. Внутри — просить надо всё: ready (иначе телеграм считает, что мы не загрузились),
//      expand (иначе игра открывается половинкой экрана) и disableVerticalSwipes.
//   3. Старый клиент. До 7.7 метода нет вовсе, и обращение к нему в лоб уронило бы всю
//      загрузку — игра не открылась бы совсем там, где она просто игралась бы хуже.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const source = fs.readFileSync('script.js', 'utf8');

function extractFunctionSource(text, name){
  const start = text.indexOf(`function ${name}(`);
  if(start === -1) throw new Error(`Не найдена функция ${name}`);
  let глубина = 0;
  let i = text.indexOf('(', start);
  for(; i < text.length; i += 1){
    if(text[i] === '(') глубина += 1;
    if(text[i] === ')'){ глубина -= 1; if(глубина === 0) break; }
  }
  const bodyStart = text.indexOf('{', i);
  let depth = 0;
  for(let j = bodyStart; j < text.length; j += 1){
    if(text[j] === '{') depth += 1;
    if(text[j] === '}') depth -= 1;
    if(depth === 0) return text.slice(start, j + 1);
  }
  throw new Error(`Не найден конец функции ${name}`);
}

// Стенд: настоящие решения, поддельные телеграм и страница.
function стенд({ адрес = "", мост = false, умеетГасить = true, естьWebApp = true } = {}){
  const вызовы = [];
  const скрипты = [];
  const sandbox = {
    console: { log: () => {}, warn: () => {} },
    вызовы, скрипты,
    window: {
      location: { hash: адрес, search: "" },
      TelegramWebviewProxy: мост ? {} : undefined,
      Telegram: естьWebApp ? { WebApp: {
        version: "7.10",
        ready(){ вызовы.push("ready"); },
        expand(){ вызовы.push("expand"); },
        ...(умеетГасить ? { disableVerticalSwipes(){ вызовы.push("disableVerticalSwipes"); } } : {}),
      } } : {},
    },
    document: {
      head: { appendChild: (узел) => { скрипты.push(узел); } },
      createElement: () => ({
        src: "", async: false, слушатели: {},
        addEventListener(имя, фн){ this.слушатели[имя] = фн; },
      }),
    },
  };
  vm.createContext(sandbox);
  vm.runInContext([
    source.match(/const TELEGRAM_SDK_URL = "[^"]*";/)[0],
    extractFunctionSource(source, 'похожеНаТелеграм'),
    extractFunctionSource(source, 'наладитьТелеграм'),
    extractFunctionSource(source, 'подключитьТелеграм'),
    'this.api = { похоже: похожеНаТелеграм, наладить: наладитьТелеграм,',
    '  подключить: подключитьТелеграм, адресСкрипта: () => TELEGRAM_SDK_URL };',
  ].join('\n'), sandbox);
  return { api: sandbox.api, вызовы, скрипты };
}

// === 1. ГЛАВНОЕ: прицеливание не сворачивает окно ===
//
// Ради этого всё и затеяно. Вызов один, и забыть его — значит вернуть игру в состояние
// «пальцем играть нельзя».
{
  const т = стенд({ адрес: "#tgWebAppData=abc" });
  assert(т.api.наладить() === true, '1: телеграм не налажен');
  assert(т.вызовы.includes("disableVerticalSwipes"),
    '1b: вертикальные свайпы не выключены — перетаскивание по доске снова будет сворачивать '
    + 'окно, и прицелиться пальцем станет нельзя');
  assert(т.вызовы.includes("expand"),
    '1c: окно не раскрыто — игра откроется половинкой экрана');
  assert(т.вызовы.includes("ready"),
    '1d: телеграму не сказано, что мы загрузились');
}

// === 2. Старый клиент не роняет игру ===
//
// До Bot API 7.7 метода нет. Обращение в лоб — исключение на самой загрузке: игра не
// открылась бы вовсе там, где она просто играется хуже.
{
  const старый = стенд({ адрес: "#tgWebAppData=abc", умеетГасить: false });
  let упало = null;
  try { старый.api.наладить(); } catch(ошибка){ упало = String(ошибка); }
  assert(упало === null, `2: на клиенте без disableVerticalSwipes игра падает: ${упало}`);
  assert(старый.вызовы.join(",") === "ready,expand",
    `2b: попрошено «${старый.вызовы.join(",")}» — остальное клиент не умеет`);
}

// === 3. Снаружи телеграма его скрипт не грузится ===
//
// Игра лежит ещё на github.io и на итче. Там этот запрос не нужен никому, а внутри чужой
// рамки на итче его могут и не пустить.
{
  const браузер = стенд({ адрес: "" });
  assert(браузер.api.похоже() === false, '3: обычный браузер принят за телеграм');
  assert(браузер.api.подключить() === false, '3b: в обычном браузере полезли за чужим скриптом');
  assert(браузер.скрипты.length === 0, '3c: и добавили его на страницу');
}

// === 4. Телеграм узнаётся двумя способами ===
//
// На десктопе он открывает страницу со своими параметрами в адресе, на телефоне кладёт в
// окно свой мост. Признака хватает любого: пропадёт один — останется второй.
{
  assert(стенд({ адрес: "#tgWebAppVersion=7.10" }).api.похоже() === true,
    '4: параметры телеграма в адресе не узнаются');
  assert(стенд({ адрес: "", мост: true }).api.похоже() === true,
    '4b: мост телеграма в окне не узнаётся');
}

// === 5. Скрипт берётся у самого телеграма и ровно один раз ===
{
  assert(/^https:\/\/telegram\.org\//.test(стенд({}).api.адресСкрипта()),
    '5: скрипт мини-приложения берут не у телеграма — это мост в его клиент, чужая копия '
    + 'тут не работает');

  // Если он уже в окне (телеграм иногда вставляет его сам) — второй раз не тянем.
  const сГотовым = стенд({ адрес: "#tgWebAppData=abc" });
  assert(сГотовым.api.подключить() === true, '5b: готовый телеграм не признан');
  assert(сГотовым.скрипты.length === 0, '5c: скрипт тянут второй раз, хотя он уже в окне');

  // А если его нет — тянем, с указанным адресом и не блокируя страницу.
  const безГотового = стенд({ адрес: "#tgWebAppData=abc", естьWebApp: false });
  assert(безГотового.api.подключить() === true, '5d: внутри телеграма скрипт не запрошен');
  assert(безГотового.скрипты.length === 1,
    `5e: скриптов добавлено ${безГотового.скрипты.length}, а нужен один`);
  assert(безГотового.скрипты[0].src === безГотового.api.адресСкрипта(), '5f: запрошен не тот адрес');
  assert(безГотового.скрипты[0].async === true,
    '5g: скрипт грузится блокирующе — игра будет ждать чужой домен, прежде чем показаться');
  assert(typeof безГотового.скрипты[0].слушатели.load === "function",
    '5h: приезд скрипта никто не ждёт — всё, ради чего он нужен, не случится');
  assert(typeof безГотового.скрипты[0].слушатели.error === "function",
    '5i: не загрузившийся скрипт обрабатывать некому');
}

console.log('smoke-telegram-mini-app: OK');
