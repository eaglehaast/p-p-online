#!/usr/bin/env node
'use strict';

// Smoke test: в комнате доска развёрнута под МЕСТО ЗА СТОЛОМ, а не под выбор в меню.
//
// Разворот доски в игре был и до этого — его сделали под выбор края в меню, и живёт он в
// преобразовании холста, во вводе и в раскладке HUD. Не было одного: в онлайне им никто не
// пользовался. Место в комнате раздаёт комната (создатель синий, гость зелёный), а вид
// оставался на том, что игрок выбрал в меню, — и синий игрок видел свои самолёты НАВЕРХУ,
// там, где во всех остальных режимах сидит соперник.
//
// Это и есть та жалоба, с которой начался весь разговор про онлайн: «неочевидно даже мне,
// что ходит оппонент — светится рожа, пытаешься сходить».
//
// Ломается это тихо, поэтому проверок тут три сорта:
//
//   1. Вход в комнату берёт вид под своё место, выход — возвращает игроку его выбор.
//   2. Выбор игрока НЕ пишется в хранилище. Записанный, он переставил бы край навсегда:
//      одна партия в гостях — и все следующие игры против компьютера идут с другой
//      стороны. Хранилище к тому же общее у вкладок, а место за столом у каждой своё.
//   3. Онлайн по-прежнему решает раньше компьютера. Теперь это стало нести вес: с видом,
//      идущим за местом, getAiPlayerColor() называет цвет ЖИВОГО соперника — и пропусти
//      онлайн свою очередь, компьютер начал бы ходить за друга.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const source = fs.readFileSync('script.js', 'utf8');

function extractFunctionSource(text, name){
  const start = text.indexOf(`function ${name}(`);
  if(start === -1) throw new Error(`Не найдена функция ${name}`);
  // Тело ищем ПОСЛЕ списка параметров: у функции с параметром по умолчанию наивный поиск
  // первой же фигурной скобки принимал за всё тело пустые скобки из списка аргументов, и
  // проверка не падала, а тихо не находила ничего.
  let глубина = 0;
  let i = text.indexOf('(', start);
  for(; i < text.length; i += 1){
    if(text[i] === '(') глубина += 1;
    if(text[i] === ')'){ глубина -= 1; if(глубина === 0) break; }
  }
  const bodyStart = text.indexOf('{', i);
  let depth = 0;
  for(let j = bodyStart; j < text.length; j += 1){
    if(text[j] === '{') depth += 1;
    if(text[j] === '}') depth -= 1;
    if(depth === 0) return text.slice(start, j + 1);
  }
  throw new Error(`Не найден конец функции ${name}`);
}

// Стенд: настоящие функции края, подставной setBoardViewSeat. Настоящий трогает DOM и
// хранилище, но нам важно другое — С КАКИМИ ПРАВАМИ его позвали, поэтому он записывает
// каждый вызов целиком, вместе с options.
function стенд(выборИгрока){
  const sandbox = {
    ONLINE_SEAT_COLORS: Object.freeze(['blue', 'green']),
    boardViewSeat: выборИгрока,
    вызовы: [],
  };
  vm.createContext(sandbox);
  vm.runInContext([
    extractFunctionSource(source, 'getBoardViewSeat'),
    'function setBoardViewSeat(seat, options){',
    '  вызовы.push({ вид: seat, права: options });',
    '  boardViewSeat = seat;',
    '}',
    'function syncMenuPlaneSides(){ вызовы.push({ меню: true }); }',
    'let boardViewSeatBeforeOnline = null;',
    extractFunctionSource(source, 'takeBoardViewForOnlineSeat'),
    extractFunctionSource(source, 'releaseBoardViewAfterOnline'),
    'this.взять = takeBoardViewForOnlineSeat;',
    'this.вернуть = releaseBoardViewAfterOnline;',
    'this.край = () => getBoardViewSeat();',
  ].join('\n'), sandbox);
  return sandbox;
}

function развороты(стенд){
  return стенд.вызовы.filter((з) => з.вид !== undefined);
}

// === 1. ГЛАВНОЕ: вход в комнату разворачивает доску под своё место ===
{
  // Создатель комнаты — синий (ONLINE_HOST_SEAT), а в меню у него по умолчанию зелёный
  // край. Именно в этой паре жалоба и жила.
  const хозяин = стенд('green');
  assert(хозяин.взять('blue') === true, '1: вход в комнату не взял вид под своё место');
  assert(хозяин.край() === 'blue',
    `1b: доска осталась краем «${хозяин.край()}» — синий игрок снова смотрит на свои `
    + 'самолёты как на чужие');

  // Гость зелёный. Если игрок до этого выбрал синий край, вид обязан съехать к зелёному:
  // доска разворачивается под место, а не под привычку.
  const гость = стенд('blue');
  assert(гость.взять('green') === true, '1c: гость не взял вид под своё место');
  assert(гость.край() === 'green',
    `1d: у зелёного гостя доска стоит краем «${гость.край()}»`);
}

// === 2. Выход из комнаты возвращает игроку его выбор ===
//
// Место было решением комнаты, а не игрока. Забыть вернуть край — значит молча
// переставить человеку сторону в его собственных играх против компьютера.
{
  const с = стенд('green');
  с.взять('blue');
  assert(с.вернуть() === true, '2: выход из комнаты не вернул край');
  assert(с.край() === 'green',
    `2b: после выхода край остался «${с.край()}» вместо выбранного игроком «green»`);

  // Второй вход не должен запомнить ОНЛАЙНОВЫЙ край как «выбор игрока»: иначе выбор
  // затирается при первом же переподключении, и возвращать станет нечего.
  const дважды = стенд('green');
  дважды.взять('blue');
  дважды.взять('blue');
  дважды.вернуть();
  assert(дважды.край() === 'green',
    `2c: после двух входов вернулся край «${дважды.край()}» — выбор игрока затёрт самим `
    + 'же онлайном');

  // Возврат без входа ничего не трогает: иначе он сам стал бы разворотом.
  const пустой = стенд('blue');
  assert(пустой.вернуть() === false, '2d: возврат сработал там, где вида никто не брал');
  assert(развороты(пустой).length === 0,
    '2e: возврат без входа всё равно развернул доску');
  assert(пустой.край() === 'blue', '2f: возврат без входа сменил край');

  // Мусорное место игнорируется целиком. Место приезжает из адреса (?seat=...), то есть
  // это чужой ввод.
  const мусор = стенд('green');
  assert(мусор.взять('red') === false, '2g: место «red» принято за своё');
  assert(мусор.край() === 'green', '2h: мусорное место развернуло доску');
  assert(мусор.вернуть() === false,
    '2i: после отказа возврат считает, что вид был взят — вернёт он не тот край');
}

// === 3. КРИТИЧНОЕ: край из комнаты не пишется в хранилище ===
//
// Ошибка на одно слово (persist по умолчанию true), и одна партия в гостях переставляет
// игроку сторону НАВСЕГДА — во всех следующих играх против компьютера. Заметить это можно
// только тем, что «после онлайна игра идёт не с той стороны», а связать с онлайном уже
// нельзя.
{
  const с = стенд('green');
  с.взять('blue');
  с.вернуть();
  const все = развороты(с);
  assert(все.length === 2, `3: разворотов оказалось ${все.length}, а не два (вход и выход)`);
  for(const звонок of все){
    assert(звонок.права && звонок.права.persist === false,
      `3b: край «${звонок.вид}» выставлен с правами ${JSON.stringify(звонок.права)} — `
      + 'запись в хранилище переставит игроку сторону навсегда');
  }
}

// === 4. Самолётики в меню уезжают вместе с краем ===
//
// Они показывают «мой» и «чужой» в двух местах меню. Оставшись на месте, они стали бы
// показывать ровно наоборот — и это единственная подсказка, по которой игрок понимает, за
// кого он играет, ДО начала партии.
{
  const с = стенд('green');
  с.взять('blue');
  assert(с.вызовы.some((з) => з.меню === true),
    '4: вход в комнату не пересобрал самолётики в меню — они покажут чужой цвет своим');
  const послеВхода = с.вызовы.length;
  с.вернуть();
  assert(с.вызовы.slice(послеВхода).some((з) => з.меню === true),
    '4b: выход из комнаты не пересобрал самолётики в меню');
}

// === 5. Вызовы стоят там, где начинается и кончается комната ===
{
  const вход = extractFunctionSource(source, 'startOnlineSession');
  assert(/takeBoardViewForOnlineSeat\(onlineSession\.seat\)/.test(вход),
    '5: вход в комнату больше не разворачивает доску под место — всё остальное в этом '
    + 'файле проверяет функцию, которую никто не зовёт');

  const выход = extractFunctionSource(source, 'stopOnlineSession');
  assert(/releaseBoardViewAfterOnline\(\)/.test(выход),
    '5b: выход из комнаты не возвращает край игроку');
}

// === 6. Онлайн решает раньше компьютера ===
//
// До этой правки вид в онлайне стоял зелёным вниз у обоих, и getAiPlayerColor() называл
// синего. Теперь он называет цвет того, кто НАПРОТИВ, — то есть живого соперника. Пока
// онлайн в getColorController спрашивается первым, это неважно; стоит порядку сломаться —
// и компьютер начнёт ходить за друга, по-настоящему, его самолётами.
{
  const контроллер = extractFunctionSource(source, 'getColorController');
  const место = контроллер.indexOf('getOnlineSeatColor()');
  const компьютер = контроллер.indexOf('gameMode === "computer"');
  assert(место !== -1, '6: getColorController больше не спрашивает про место за столом');
  assert(компьютер !== -1, '6b: в getColorController не нашлось ветки игры с компьютером');
  assert(место < компьютер,
    '6c: компьютер решает раньше места за столом — за живого соперника начнёт ходить ИИ');

  // Сторона ИИ по-прежнему считается от края, а не пишется цветом: это и делает проверку
  // выше осмысленной.
  const цветИИ = extractFunctionSource(source, 'getAiPlayerColor');
  assert(/getOpposingSeat\(\)/.test(цветИИ),
    '6d: сторона ИИ больше не следует за краем доски');
}

console.log('smoke-online-board-side: OK');
