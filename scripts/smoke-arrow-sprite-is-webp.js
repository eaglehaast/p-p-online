#!/usr/bin/env node
'use strict';

// Smoke test: атлас стрелки прицела лежит в WebP БЕЗ ПОТЕРЬ и прежнего размера.
//
// Это была последняя крупная PNG в проекте — 60 КБ, и она грузится при каждом запуске.
// Перекодирование без потерь снимает почти половину:
//
//   sprite_ copy.png   60.3 КБ  →  sprite_ copy.webp   32.0 КБ   −47%
//
// Взято именно БЕЗ потерь, хотя q88 дал бы 19.7 КБ. Причины две. Во-первых, разница между
// вариантами — 12 КБ, на медленном канале это доли секунды, торговаться не о чем.
// Во-вторых, стрелка — не текстура: три её куска рисуются на холсте с поворотом и
// растяжением древка под длину броска, поверх ещё накладывается blur(0.2px). Вносить в
// такую картинку артефакты сжатия ради двенадцати килобайт незачем.
//
// Сверка старого и нового ФАЙЛА по сохранённым точкам:
//
//   различается прозрачность           0
//   различается видимая точка          0
//   различается RGB под alpha=0   155242   на экране не видно никогда
//
// То есть в самом файле всё, что рисуется, осталось прежним до последнего значения.
// Отличаются только цвета под полностью прозрачными точками — их libwebp имеет право
// переписать, потому что показать их нельзя.
//
// А вот через БРАУЗЕР разница есть, и заявлять «то же самое побитово» было бы неправдой.
// Холст хранит цвет умноженным на прозрачность, и обратное деление округляется у декодера
// PNG и декодера WebP по-разному:
//
//   точек с другим цветом      861 из 1 572 864
//   отличие прозрачности         0
//   худший вклад в картинку   1.98 из 255   (отклонение, взвешенное прозрачностью)
//
// Меньше одного процента на восьмистах точках из полутора миллионов — это округление, а не
// артефакт сжатия, и появилось бы оно при любой смене формата.
//
// РАЗМЕР ХОЛСТА МЕНЯТЬ НЕЛЬЗЯ. Игра не рисует атлас целиком: она вырезает из него три
// куска по жёстко прописанным координатам (голова, древко, хвост). Сдвинется холст —
// поедут все три, причём молча: стрелка просто станет рисоваться обрезком соседнего куска.
// Поэтому тест сверяет координаты в коде с настоящими размерами файла.

const fs = require('fs');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const script = fs.readFileSync('script.js', 'utf8');
const FILE = 'sprite_ copy.webp';

// Разбор заголовка WebP своими руками: тест не должен зависеть от того, что стоит на машине.
function readWebp(file){
  const b = fs.readFileSync(file);
  assert(b.toString('latin1', 0, 4) === 'RIFF' && b.toString('latin1', 8, 12) === 'WEBP',
    `${file} не WebP — внутри что-то другое`);

  const kind = b.toString('latin1', 12, 16);
  if(kind === 'VP8L'){
    // Формат без потерь: после подписи 0x2F идут четырнадцать бит ширины и столько же высоты,
    // в обоих случаях «минус один».
    assert(b[20] === 0x2f, `${file}: испорчена подпись блока без потерь`);
    const bits = b.readUInt32LE(21);
    return { lossless: true, width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 };
  }
  if(kind === 'VP8X'){
    return { lossless: false,
      width: 1 + (b[24] | (b[25] << 8) | (b[26] << 16)),
      height: 1 + (b[27] | (b[28] << 8) | (b[29] << 16)) };
  }
  return { lossless: false, width: b.readUInt16LE(26) & 0x3fff, height: b.readUInt16LE(28) & 0x3fff };
}

// === 1. ГЛАВНОЕ: холст ровно тот, из которого код вырезает куски ===
{
  assert(fs.existsSync(FILE), `1: нет файла ${FILE} — стрелка прицела не нарисуется`);
  const img = readWebp(FILE);

  const num = name => {
    const m = new RegExp(`const ${name}\\s*=\\s*(\\d+);`).exec(script);
    assert(m, `1b: в коде не найдена координата ${name} — проверка устарела`);
    return Number(m[1]);
  };
  const ARROW_Y = num('ARROW_Y'), PART_H = num('PART_H');
  const parts = [
    ['голова', num('HEAD_X'), num('HEAD_W')],
    ['древко', num('SHAFT_X'), num('SHAFT_W')],
    ['хвост', num('TAIL_X'), num('TAIL_W')],
  ];

  for(const [label, x, w] of parts){
    assert(x + w <= img.width,
      `1c: ${label} стрелки вырезают до ${x + w} точки по ширине, а холст ${img.width}. `
      + 'Атлас режут по жёстко прописанным координатам — стрелка станет обрезком соседнего куска');
  }
  assert(ARROW_Y + PART_H <= img.height,
    `1d: куски стрелки вырезают до ${ARROW_Y + PART_H} точки по высоте, а холст ${img.height}`);

  // И наоборот: холст не должен раздуться впустую.
  assert(img.width <= 1536 && img.height <= 1024,
    `1e: холст вырос до ${img.width}x${img.height} — это лишний вес на каждом запуске`);
}

// === 2. Именно без потерь ===
//
// Стрелку поворачивают, растягивают древко под длину броска и накладывают blur. Артефакты
// сжатия в такой картинке видны там, где в текстуре были бы незаметны.
{
  const img = readWebp(FILE);
  assert(img.lossless,
    '2: атлас стрелки пересжали с потерями. Разница с вариантом без потерь — двенадцать '
    + 'килобайт, а стрелка рисуется с поворотом, растяжением и размытием');

  const size = fs.statSync(FILE).size;
  assert(size < 45 * 1024,
    `2b: ${FILE} весит ${Math.round(size / 1024)} КБ вместо примерно 32 — проверь, чем пересобирали`);
  assert(size > 10 * 1024, `2c: ${FILE} подозрительно мал (${size} байт)`);
}

// === 3. PNG не осталось ни на диске, ни в ссылках ===
{
  assert(!fs.existsSync('sprite_ copy.png'),
    '3: sprite_ copy.png вернулся — держать оба набора значит не выиграть ничего');
  assert(!script.includes('sprite_ copy.png'),
    '3b: на sprite_ copy.png снова есть ссылка — файла нет, стрелка не появится');

  assert(/loadImageAsset\("sprite_ copy\.webp"/.test(script),
    '3c: атлас стрелки больше не загружается');
  assert(script.includes('"sprite_ copy.webp"'),
    '3d: sprite_ copy.webp выпал из списка предзагрузки — поедет в момент первого прицеливания');
}

console.log('smoke-arrow-sprite-is-webp: OK');
