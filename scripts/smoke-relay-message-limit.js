#!/usr/bin/env node
'use strict';

// Smoke test: ретранслятор не принимает пакет больше предела.
//
// Придержанные типы — settings и state — уходят в хранилище Durable Object, а там предел
// 128 КиБ на значение. Проверки не было никакой: слишком большой снимок ронял бы put
// ВНУТРИ await, ловить его было некому, и пакет не уехал бы сопернику — а комната молча
// осталась бы с прежним снимком. Плюс любой, кто знает код комнаты, мог гнать туда
// мегабайты, и за каждую запись платит владелец.
//
// Предел взят от НАСТОЯЩЕГО снимка, а не на глаз. Замер в живой партии:
//
//   в начале партии                        3434 байта
//   после десяти ходов                     3447 байт
//   нарочно раздутый до пределов правил    7997 байт
//
// 64 КиБ — восьмикратный запас к худшему разумному случаю и вдвое меньше предела
// хранилища. Расти снимку есть куда, а мусору уже нет.
//
// Слишком большой пакет ЗАКРЫВАЕТ соединение, а не отбрасывается молча. Молча — худшее из
// возможного: снимок не доехал бы, доска у соперника осталась прежней, и оба продолжали бы
// играть в разные партии, ничего не заметив. Обрыв соперник видит, и клиент умеет
// переподключаться.
//
// Проверено на живом ретрансляторе, двумя настоящими сокетами:
//
//   обычный пакет 3401 байт      доехал сопернику
//   пакет 71781 байт             не доехал; отправителя закрыли с кодом 4009
//                                message_too_large, соперник остался на связи

const fs = require('fs');
const room = require('../worker/room.js');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const workerSource = fs.readFileSync('worker/index.js', 'utf8');
const localSource = fs.readFileSync('worker/local-server.js', 'utf8');

// === 1. ГЛАВНОЕ: предел есть, и он между настоящим снимком и пределом хранилища ===
{
  const limit = room.RELAY_MAX_MESSAGE_BYTES;
  assert(Number.isInteger(limit), '1: предела на размер пакета нет');

  // Настоящий снимок с запасом — 8 КБ. Предел ниже этого сделал бы игру неиграбельной.
  assert(limit >= 16 * 1024,
    `1b: предел ${limit} байт слишком мал. Настоящий снимок партии — 3.4 КБ, раздутый до `
    + 'пределов правил — 8 КБ, и запас нужен: снимку есть куда расти');
  // Cloudflare не примет в хранилище значение больше 128 КиБ.
  assert(limit <= 96 * 1024,
    `1c: предел ${limit} байт не меньше предела хранилища Durable Object (128 КиБ) — тогда `
    + 'проверка ничего не ловит, put упадёт первым');
}

// === 2. Считаются БАЙТЫ, а не символы ===
//
// Кириллица в названии карты занимает по два байта, эмодзи по четыре. Предел, посчитанный
// по символам, врал бы в большую сторону — то есть пропускал бы ровно то, что должен ловить.
{
  assert(room.measureMessageBytes('abc') === 3, '2: латиница считается неверно');
  assert(room.measureMessageBytes('абв') === 6,
    '2b: кириллица посчитана по символам, а не по байтам — предел станет вдвое больше '
    + 'заявленного');
  assert(room.measureMessageBytes('🙂') === 4, '2c: эмодзи посчитано неверно');
  assert(room.measureMessageBytes(null) === 0 && room.measureMessageBytes(undefined) === 0,
    '2d: пустого ввода бояться не надо — сюда приходит что угодно из сети');
}

// === 3. Граница ровно там, где объявлена ===
{
  const limit = room.RELAY_MAX_MESSAGE_BYTES;
  assert(room.isMessageTooLarge('a'.repeat(limit)) === false,
    '3: пакет ровно в предел уже отвергается — предел должен быть включающим');
  assert(room.isMessageTooLarge('a'.repeat(limit + 1)) === true,
    '3b: пакет на байт больше предела проходит');

  // И то же самое на многобайтовых символах: там счёт символов и счёт байтов расходятся.
  assert(room.isMessageTooLarge('я'.repeat(Math.floor(limit / 2) + 1)) === true,
    '3c: кириллица за пределом проходит — значит где-то считают символы');
}

// === 4. Оба сервера пользуются одним и тем же пределом ===
//
// Иначе на своей машине всё работает, а в облаке рвётся — и ровно на том пакете, который
// потом не воспроизвести.
{
  for(const [name, source] of [['worker/index.js', workerSource], ['worker/local-server.js', localSource]]){
    // Именно ВЫЗОВ в условии, а не просто упоминание: импорт остаётся на месте и когда
    // проверку обезвредили, а `if(false)` на её месте выглядит точно так же издалека.
    assert(/if\(isMessageTooLarge\(/.test(source),
      `4: ${name} не проверяет размер пакета`);
    assert(/from "\.\/room\.js"|from "\.\/room\.js";/.test(source) || /room\.js/.test(source),
      `4b: ${name} берёт правило не из room.js — правил станет два`);
    assert(/close\(4009, RELAY_ERRORS\.TOO_LARGE\)/.test(source),
      `4c: ${name} отбрасывает слишком большой пакет молча. Тогда снимок не доедет, доска у `
      + 'соперника останется прежней, и оба будут играть в разные партии');
  }

  assert(room.RELAY_ERRORS.TOO_LARGE === 'message_too_large',
    '4d: у отказа пропало имя — по коду 4009 без него не понять, что случилось');
}

// === 5. Отказ хранилища не уносит с собой пересылку ===
//
// Придержанная копия нужна тому, кто вернётся после обрыва. Соперник, который ждёт пакет
// СЕЙЧАС, к этой копии отношения не имеет и страдать за неё не должен.
{
  const put = /await this\.state\.storage\.put\(envelope\.t, envelope\);/.exec(workerSource);
  assert(put, '5: запись придержанного пакета не найдена — проверка устарела');

  const around = workerSource.slice(Math.max(0, put.index - 400), put.index + 300);
  assert(/try \{[\s\S]*?await this\.state\.storage\.put[\s\S]*?\} catch\(error\)\{/.test(around),
    '5b: запись в хранилище снова без try/catch. Отказ внутри await не поймает никто, и '
    + 'пакет не уедет сопернику');

  const after = workerSource.slice(put.index);
  assert(/routed\.connection\.send\(message\)/.test(after),
    '5c: после записи пакет больше не пересылается');
}

console.log('smoke-relay-message-limit: OK');
