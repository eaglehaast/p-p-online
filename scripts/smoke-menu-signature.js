#!/usr/bin/env node
'use strict';

// Smoke test: раскладка главного меню и подпись автора под ней.
//
// Меню разложено голыми числами в стилях: у каждого пункта своя коробка в кадре 460x800.
// Числа эти двигают руками, и увидеть, что после сдвига пункт налез на соседа или уехал
// за грань, можно только глазами — на живом экране. Здесь то же самое считается.
//
// Подпись появилась последней и ради неё нижний блок подняли. Поэтому у неё своя проверка:
// она обязана уместиться в освободившуюся полосу целиком, а не лечь на Advanced Settings и
// не сползти на деревянную раму.

const fs = require('fs');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const styles = fs.readFileSync('styles.css', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');

const КАДР = { w: 460, h: 800 };
// Край зелёного поля. Ниже начинается деревянная рама, и всё, что туда заедет, будет
// читаться как брак вёрстки. Число снято с картинки меню.
const ПОЛЕ_НИЗ = 758;

function коробка(селектор){
  const m = new RegExp(`#menuLayer #modeMenu \\.${селектор}\\s*\\{([^}]*)\\}`).exec(styles);
  assert(m, `1: не найдено правило места для .${селектор}`);
  const чис = (имя) => {
    const v = new RegExp(`${имя}:\\s*(-?\\d+(?:\\.\\d+)?)px`).exec(m[1]);
    assert(v, `1: у .${селектор} нет ${имя}`);
    return Number(v[1]);
  };
  return { имя: селектор, x: чис('left'), y: чис('top'), w: чис('width'), h: чис('height') };
}

const ПУНКТЫ = [
  'mode-menu__btn--hotseat',
  'mode-menu__btn--computer',
  'mode-menu__btn--online',
  'mode-menu__btn--play',
  'mode-menu__btn--classic',
  'mode-menu__btn--advanced'
].map(коробка);
const ПОДПИСЬ = коробка('mode-menu__signature');

// === 1. Подпись есть, и она не кнопка ===
//
// Нажимать за ней пока нечему: дерево ссылок не заведено. Кнопка тут соврала бы и
// читалке, и клавиатуре — в фокус попадёт, а нажатие не сделает ничего.
{
  assert(/<div id="menuSignature" class="mode-menu__signature" aria-hidden="true">/.test(html),
    '1: в меню нет подписи автора — элемент #menuSignature с классом mode-menu__signature');
  assert(!/<button[^>]*mode-menu__signature/.test(html),
    '1b: подпись стала кнопкой, а нажимать за ней нечему — пока это метка');
  assert(/pointer-events:\s*none/.test(
    /#menuLayer #modeMenu \.mode-menu__signature\s*\{([^}]*)\}/.exec(styles)[1]),
    '1c: подпись ловит нажатия — она лежит поверх меню и будет их воровать');

  const файл = /background-image:\s*url\('([^']+)'\)/.exec(
    /#menuLayer #modeMenu \.mode-menu__signature\s*\{([^}]*)\}/.exec(styles)[1]);
  assert(файл, '1d: у подписи нет картинки');
  assert(fs.existsSync(файл[1]),
    `1e: картинки подписи нет на месте: ${файл[1]}`);
}

// === 2. Ничто не вылезает за кадр ===
{
  for(const к of [...ПУНКТЫ, ПОДПИСЬ]){
    assert(к.x >= 0 && к.y >= 0 && к.x + к.w <= КАДР.w && к.y + к.h <= КАДР.h,
      `2: ${к.имя} вылезает за кадр ${КАДР.w}x${КАДР.h}: ${к.x},${к.y} ${к.w}x${к.h}`);
  }
}

// === 3. Пункты меню не наезжают друг на друга ===
{
  const все = [...ПУНКТЫ, ПОДПИСЬ];
  for(let i = 0; i < все.length; i += 1){
    for(let j = i + 1; j < все.length; j += 1){
      const a = все[i], b = все[j];
      const пересеклись = a.x < b.x + b.w && b.x < a.x + a.w
        && a.y < b.y + b.h && b.y < a.y + a.h;
      assert(!пересеклись,
        `3: ${a.имя} и ${b.имя} налезли друг на друга — на экране пункты сольются`);
    }
  }
}

// === 4. Пункты стоят по середине кадра ===
//
// Все шесть коробок посчитаны как (460 - ширина) / 2, и это не совпадение, а правило:
// меню собрано столбиком по центру. Сдвиг вбок на точку-другую в глаза не бросится, а
// столбик перекосит.
{
  for(const к of ПУНКТЫ){
    const середина = к.x + к.w / 2;
    assert(Math.abs(середина - КАДР.w / 2) <= 0.5,
      `4: ${к.имя} стоит серединой на ${середина}, а кадр делится пополам по ${КАДР.w / 2} — `
      + 'столбик меню перекосится');
  }
}

// === 5. Подпись живёт в свободной полосе ===
//
// Полоса эта появилась ровно тогда, когда нижний блок подняли. Если пункты вернут вниз,
// подпись окажется под ними — и заметить это можно будет только глазами.
{
  // Щель нужна не «чтобы не наехало», а чтобы подпись читалась отдельной строкой, а не
  // хвостом кнопки. Сейчас её 36 точек; восемь — тот минимум, ниже которого две строки
  // начинают слипаться в одну.
  const ЩЕЛЬ = 8;
  const низПунктов = Math.max(...ПУНКТЫ.map((к) => к.y + к.h));
  assert(ПОДПИСЬ.y - низПунктов >= ЩЕЛЬ,
    `5: между нижним пунктом (кончается на ${низПунктов}) и подписью (начинается на `
    + `${ПОДПИСЬ.y}) осталось ${ПОДПИСЬ.y - низПунктов} точек — подпись слипнется с меню`);
  assert(ПОДПИСЬ.y + ПОДПИСЬ.h <= ПОЛЕ_НИЗ,
    `5b: подпись кончается на ${ПОДПИСЬ.y + ПОДПИСЬ.h}, а зелёное поле — на ${ПОЛЕ_НИЗ}: `
    + 'она заедет на деревянную раму');
}

console.log('smoke-menu-signature: OK');
