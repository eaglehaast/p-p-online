#!/usr/bin/env node
'use strict';

// Smoke test: из онлайновой партии есть выход, и он спрашивает.
//
// В игре за одним устройством и против компьютера из партии выводит простая
// перезагрузка страницы: она же возвращает в меню. В комнате перезагрузка теперь
// возвращает за ТОТ ЖЕ СТОЛ — своим же адресом, — и выйти иначе как правкой адреса
// руками стало нельзя. Особенно обидно это, когда соперник просто ушёл и ждать больше
// нечего.
//
// Отсюда крестик. Три вещи, каждая ломается по-своему:
//
//   1. Он есть ровно там, где нужен: в онлайновой партии, и больше нигде. В меню и в
//      лобби ему делать нечего, в игре против компьютера — тем более.
//   2. Он спрашивает. Нажатие посреди партии стоит слишком дорого, чтобы верить ему на
//      слово: промах по углу экрана рвал бы связь.
//   3. «Да» уводит НАСОВСЕМ: рвёт связь, забывает комнату и чистит адрес. Оставь он
//      комнату в адресе — перезагрузка вернула бы человека ровно туда, откуда он только
//      что ушёл.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const source = fs.readFileSync('script.js', 'utf8');
const markup = fs.readFileSync('index.html', 'utf8');
const styles = fs.readFileSync('styles.css', 'utf8');

function extractFunctionSource(text, name){
  const start = text.indexOf(`function ${name}(`);
  if(start === -1) throw new Error(`Не найдена функция ${name}`);
  let глубина = 0;
  let i = text.indexOf('(', start);
  for(; i < text.length; i += 1){
    if(text[i] === '(') глубина += 1;
    if(text[i] === ')'){ глубина -= 1; if(глубина === 0) break; }
  }
  const bodyStart = text.indexOf('{', i);
  let depth = 0;
  for(let j = bodyStart; j < text.length; j += 1){
    if(text[j] === '{') depth += 1;
    if(text[j] === '}') depth -= 1;
    if(depth === 0) return text.slice(start, j + 1);
  }
  throw new Error(`Не найден конец функции ${name}`);
}

function правило(селектор){
  const i = styles.indexOf(`${селектор} {`);
  if(i === -1) return null;
  return styles.slice(i, styles.indexOf('}', i));
}

// Стенд: настоящие решения, поддельные узлы и последствия.
function стенд({ вКомнате = true, вПартии = true } = {}){
  const sandbox = {
    Object, Boolean, String,
    сделано: [],
    onlineSession: вКомнате ? { seat: 'blue', room: 'стол' } : null,
    onlinePresence: { blue: true, green: true },
    gameMode: вПартии ? 'online' : null,
    HTMLElement: function HTMLElement(){},
    stopOnlineSession: () => { sandbox.сделано.push('связь'); sandbox.onlineSession = null; return true; },
    forgetHostRoom: () => { sandbox.сделано.push('комната'); },
    resetGame: (о) => { sandbox.сделано.push(`меню:${JSON.stringify(о)}`); },
  };
  const узлы = {
    leaveMatchBtn: { hidden: true },
    leaveMatchConfirm: { hidden: true },
    leaveConfirmText: { textContent: '' },
  };
  for(const узел of Object.values(узлы)) Object.setPrototypeOf(узел, sandbox.HTMLElement.prototype);

  // Метка «вопрос на экране» висит на корне страницы: по ней доска поднимается над
  // слоем плашек.
  const метки = new Set();
  const корень = { classList: {
    toggle: (имя, вкл) => { if(вкл) метки.add(имя); else метки.delete(имя); },
    contains: (имя) => метки.has(имя),
  } };
  Object.setPrototypeOf(корень, sandbox.HTMLElement.prototype);
  sandbox.document = { getElementById: (id) => узлы[id] || null, documentElement: корень };

  vm.createContext(sandbox);
  vm.runInContext([
    source.match(/const LEAVE_MATCH_TEXT = "[^"]*";/)[0],
    source.match(/const LEAVE_MATCH_TEXT_ONLINE = "[^"]*";/)[0],
    extractFunctionSource(source, 'вПартии'),
    extractFunctionSource(source, 'syncLeaveMatchButton'),
    extractFunctionSource(source, 'отметитьВопросНаЭкране'),
    extractFunctionSource(source, 'показатьВопросОВыходе'),
    extractFunctionSource(source, 'спрятатьВопросОВыходе'),
    extractFunctionSource(source, 'уйтиИзПартии'),
    'this.api = {',
    '  показать: syncLeaveMatchButton, спросить: показатьВопросОВыходе,',
    '  забыть: спрятатьВопросОВыходе, уйти: уйтиИзПартии,',
    '  надпись: () => document.getElementById("leaveConfirmText").textContent,',
    '};',
  ].join('\n'), sandbox);
  return { api: sandbox.api, узлы, метки, стенд: sandbox };
}

// === 1. ГЛАВНОЕ: крестик есть только в онлайновой партии ===
{
  const вПартии = стенд({ вКомнате: true, вПартии: true });
  assert(вПартии.api.показать() === true, '1: в онлайновой партии выхода нет');
  assert(вПартии.узлы.leaveMatchBtn.hidden === false, '1b: кнопка осталась спрятанной');

  const вЛобби = стенд({ вКомнате: true, вПартии: false });
  assert(вЛобби.api.показать() === false,
    '1c: крестик висит в лобби — там для выхода есть «Cancel», и два выхода рядом только '
    + 'путают');
  assert(вЛобби.узлы.leaveMatchBtn.hidden === true, '1d: и он не спрятан');

  // И в игре за одним устройством, и против компьютера — тоже. Перезагрузка там была не
  // выходом, а обходом: игра закрывалась целиком, чтобы открыться заново.
  const сам = стенд({ вКомнате: false, вПартии: true });
  assert(сам.api.показать() === true,
    '1e: в обычной партии выхода нет — остаётся только перезагрузка страницы');

  const меню = стенд({ вКомнате: false, вПартии: false });
  assert(меню.api.показать() === false, '1f: крестик висит в меню');
}

// === 1g. ЛОВУШКА ЗАГРУЗКИ: вопрос «идёт ли партия» задают раньше, чем есть ответ ===
//
// setScreenMode('MENU') стоит в коде верхнего уровня, а let gameMode объявлен сильно
// ниже по файлу. Обращение к нему в этот миг — не «undefined», а ошибка: let до своей
// строки недоступен.
//
// Замерено: страница умирала на загрузке ЦЕЛИКОМ. Выполнение script.js обрывалось на
// этом месте, дальше не объявлялось ничего — ни одной функции игры. Снаружи это
// выглядело как пустое меню без кнопок.
//
// Стенд воспроизводит это буквально: вызов стоит ДО объявления.
{
  const sandbox = { Boolean };
  vm.createContext(sandbox);
  let упало = null;
  try {
    vm.runInContext([
      extractFunctionSource(source, 'вПартии'),
      'this.ответ = вПартии();',
      'let gameMode = null;',
    ].join('\n'), sandbox);
  } catch(ошибка){
    упало = String(ошибка);
  }
  assert(упало === null,
    `1g: вопрос «идёт ли партия», заданный во время загрузки, роняет весь файл: ${упало}`);
  assert(sandbox.ответ === false, '1g2: до загрузки ответ обязан быть «партии нет»');
}

// === 2. Пропал крестик — пропал и вопрос ===
//
// Иначе вопрос «уйти?» переживёт конец партии и повиснет поверх меню.
{
  const с = стенд({ вКомнате: true, вПартии: true });
  с.api.спросить();
  assert(с.узлы.leaveMatchConfirm.hidden === false, '2: вопрос не показался');
  с.стенд.gameMode = null;
  с.api.показать();
  assert(с.узлы.leaveMatchConfirm.hidden === true,
    '2b: партия кончилась, а вопрос «уйти?» остался висеть');
}

// === 3. Вопрос задают только там, где есть что бросать ===
{
  const меню = стенд({ вКомнате: false, вПартии: false });
  assert(меню.api.спросить() === false, '3: в меню спрашивают, уходить ли из партии');
  assert(меню.узлы.leaveMatchConfirm.hidden === true, '3b: и показывают вопрос');
}

// === 4. «Да» уводит насовсем ===
//
// Три последствия, и каждое нужно своё. Связь — чтобы соперник увидел, что мы ушли.
// Комната — чтобы прежняя ссылка умерла: иначе друг, открывший её завтра, молча сядет
// за стол, за которым нас нет. Меню — потому что уйти в никуда нельзя.
{
  const с = стенд({ вКомнате: true, вПартии: true });
  с.api.спросить();
  assert(с.api.уйти() === true, '4: выход не сработал');
  assert(с.стенд.сделано.includes('связь'), '4b: связь не разорвана — соперник так и ждёт хода');
  assert(с.стенд.сделано.includes('комната'),
    '4c: комната не забыта — прежняя ссылка переживёт выход и приведёт друга в пустоту');
  assert(с.стенд.сделано.some((д) => /^меню:/.test(д)), '4d: в меню не вернулись');
  assert(с.стенд.сделано.some((д) => /forceMenu":true/.test(д)),
    '4e: сброс не уводит в меню, а остаётся на игровом экране');
  assert(с.узлы.leaveMatchConfirm.hidden === true, '4f: вопрос остался висеть поверх меню');
  assert(с.стенд.onlinePresence === null, '4g: за столом по-прежнему кто-то числится');
}

// === 4h. Про брошенного соперника говорят только там, где он есть ===
{
  const вКомнате = стенд({ вКомнате: true, вПартии: true });
  вКомнате.api.спросить();
  assert(/opponent/i.test(вКомнате.api.надпись()),
    `4h: в комнате не предупредили про соперника: «${вКомнате.api.надпись()}»`);

  const один = стенд({ вКомнате: false, вПартии: true });
  один.api.спросить();
  assert(!/opponent/i.test(один.api.надпись()),
    `4h2: за одним устройством обещают бросить соперника, которого нет: `
    + `«${один.api.надпись()}»`);
  assert(/leave/i.test(один.api.надпись()),
    `4h3: вопрос перестал быть вопросом: «${один.api.надпись()}»`);
}

// === 4i. Из обычной партии рвать нечего ===
//
// Связь и комната — только для онлайна. Позови их вслепую, и выход из игры против
// компьютера начнёт забывать комнату, которой нет.
{
  const один = стенд({ вКомнате: false, вПартии: true });
  one: {
    assert(один.api.уйти() === true, '4i: из обычной партии выйти нельзя');
  }
  assert(!один.стенд.сделано.includes('связь'), '4i2: рвём связь, которой нет');
  assert(!один.стенд.сделано.includes('комната'), '4i3: забываем комнату, которой нет');
  assert(один.стенд.сделано.some((д) => /forceMenu":true/.test(д)), '4i4: в меню не вернулись');
}

// === 5. «Нет» не делает ничего ===
{
  const с = стенд({ вКомнате: true, вПартии: true });
  с.api.спросить();
  с.api.забыть();
  assert(с.узлы.leaveMatchConfirm.hidden === true, '5: вопрос не убрался');
  assert(с.стенд.сделано.length === 0,
    `5b: «нет» что-то натворило: ${JSON.stringify(с.стенд.сделано)}`);
  assert(с.стенд.onlineSession !== null, '5c: «нет» разорвало связь');
}

// === 6. Крестик, вопрос и ответы связаны в разметке ===
{
  assert(/id="leaveMatchBtn"[\s\S]{0,220}hidden/.test(markup),
    '6: кнопка выхода в разметке не спрятана — она мелькнёт на экранах, где не нужна');
  assert(/id="leaveMatchBtn"[\s\S]{0,220}aria-label="Leave the match"/.test(markup),
    '6b: у кнопки нет имени — читалка назовёт её «кнопка»');
  for(const id of ['leaveMatchConfirm', 'leaveConfirmYes', 'leaveConfirmNo']){
    assert(new RegExp(`id="${id}"`).test(markup), `6c: в разметке нет ${id}`);
  }
  assert(/id="leaveMatchConfirm"[\s\S]{0,200}role="dialog"/.test(markup),
    '6d: вопрос не объявлен диалогом');

  // Кнопки — буквами по дереву, теми же, что вопрос над ними.
  //
  // Готовые «YES/NO» из «Play again?» сюда не подошли: глянцевые кружки спорят с деревом
  // и золотом, и окно распадалось на две разные игры.
  const кнопка = правило('.leave-confirm__btn');
  assert(кнопка, '6e: у кнопок вопроса нет своего оформления');
  assert(!/playagain/.test(кнопка),
    '6e2: вернулись глянцевые кружки из «Play again?» — на деревянной плашке они чужие');
  assert(/Cinzel/.test(кнопка),
    '6e3: кнопки набраны не тем шрифтом, что вопрос над ними');
  assert(/id="leaveConfirmYes"[\s\S]{0,160}>YES</.test(markup)
    && /id="leaveConfirmNo"[\s\S]{0,160}>NO</.test(markup),
    '6e4: на кнопках не написано, что они делают');
  assert(!/id="leaveConfirmYes"[\s\S]{0,160}visually-hidden/.test(markup),
    '6e5: надпись на кнопке снова спрятана от глаз — а картинки под ней больше нет');
}

// === 7. Нажатие ведёт к вопросу, а не к выходу ===
//
// Главная проверка про «спрашивает»: если крестик позовёт выход напрямую, промах по
// углу экрана оборвёт партию без единого слова.
{
  const кусок = source.slice(source.indexOf('const крестик = document.getElementById("leaveMatchBtn")'));
  const блок = кусок.slice(0, кусок.indexOf('// «Cancel»'));
  assert(/крестик\.addEventListener\("click", \(\) => \{ показатьВопросОВыходе\(\); \}\)/.test(блок),
    '7: крестик зовёт не вопрос');
  assert(!/крестик[\s\S]{0,120}уйтиИзПартии/.test(блок),
    '7b: крестик рвёт связь сразу, без вопроса');
  assert(/да\.addEventListener\("click", \(\) => \{ уйтиИзПартии\(\); \}\)/.test(блок),
    '7c: «да» не уводит из партии');
  assert(/нет\.addEventListener\("click", \(\) => \{ спрятатьВопросОВыходе\(\); \}\)/.test(блок),
    '7d: «нет» не убирает вопрос');
  assert(/Escape/.test(блок), '7e: от вопроса нельзя отказаться клавишей');
  assert(/leave-confirm__veil/.test(блок),
    '7f: нажатие мимо кнопок не закрывает вопрос — целиться в «нет» придётся точно');
}

// === 8. Экран сменился — крестик пересчитан ===
{
  const экран = extractFunctionSource(source, 'setScreenMode');
  assert(/syncLeaveMatchButton\(\)/.test(экран),
    '8: переключение экрана не трогает крестик — он переживёт выход в меню');
}

// === 9. Место: в телефоне справа сверху, на десктопе слева сверху ===
//
// Кадр в горизонтали повёрнут целиком, поэтому «тот же угол экрана» — это РАЗНЫЕ углы
// кадра. Верхний правый угол кадра (портрет) после поворота уезжает вниз-вправо, туда,
// где уже стоит кнопка поворота; поэтому в горизонтали крестик переезжает в тот угол
// кадра, который оказывается вверху слева экрана: малое x, большое y.
{
  const портрет = правило('.leave-match');
  assert(портрет, '9: у кнопки выхода нет места');
  const left = Number(/left:\s*([\d.]+)px/.exec(портрет)[1]);
  const top = Number(/top:\s*([\d.]+)px/.exec(портрет)[1]);
  assert(left > 380 && top < 90,
    `9b: в портрете крестик стоит в (${left}, ${top}) — а нужен верхний правый угол кадра`);

  const горизонт = правило('html.is-board-landscape .leave-match');
  assert(горизонт, '9c: в горизонтали крестик остаётся в том же углу КАДРА — на экране это '
    + 'нижний правый угол, где уже живёт кнопка поворота');
  const left2 = Number(/left:\s*([\d.]+)px/.exec(горизонт)[1]);
  const top2 = Number(/top:\s*([\d.]+)px/.exec(горизонт)[1]);
  assert(left2 < 90 && top2 > 700,
    `9d: в горизонтали крестик стоит в (${left2}, ${top2}) — а на экране это должен быть `
    + 'верхний левый угол, то есть малое x и большое y кадра');

  // И не просто «в углу», а в свободной его части. Замерено на живом экране (кадр
  // 900x518): полоса инвентаря занимает экранные y 56..394, то есть кадр x 49.8..350;
  // счётчик самолётов — экранные x 109..791, то есть кадр y 96.9..703. Первая попытка
  // (left 25, top 744.5) ложилась на первый слот полосы инвентаря на восемь точек.
  assert(left2 + 32 <= 49,
    `9d2: крестик занимает кадр x ${left2}..${left2 + 32} и залезает на полосу инвентаря `
    + '(она начинается с 49.8)');
  assert(top2 >= 704,
    `9d3: крестик занимает кадр y от ${top2} и залезает на счётчик самолётов (он кончается `
    + 'на 703)');

  // И стоит он не «где-то в свободном месте», а на средней линии полосы инвентаря: та
  // ужата множителем 0.8772 вокруг своего начала, занимает кадр y 733..781.2, середина —
  // 757.12. Зеркало числа у кнопки поворота (она стоит на середине встречной полосы).
  const осьПолосы = 733 + 55 * 0.8772 / 2;
  assert(Math.abs(top2 + 16 - осьПолосы) <= 2,
    `9d4: середина крестика на ${top2 + 16}, а средняя линия полосы инвентаря — `
    + `${осьПолосы.toFixed(2)}: он читается случайным пятном в углу, а не её продолжением`);

  // Неприметный: это запасной выход, а не часть игры.
  const прозрачность = Number(/opacity:\s*([\d.]+)/.exec(портрет)[1]);
  assert(прозрачность > 0.3 && прозрачность < 0.8,
    `9e: прозрачность ${прозрачность} — крестик либо кричит, либо невидим`);
}

// === 9h. У вопроса есть подложка ===
//
// Без неё кнопки «да/нет» висели в пустоте поверх доски, и окно выглядело приклеенным.
// Подложка — та же деревянная плашка, на которой игра показывает «ROUND 1»: своей
// картинки у вопроса нет, а у «Play again?» в подложку вписан её собственный вопрос.
{
  const коробка = правило('.leave-confirm__box');
  assert(коробка, '9h: у вопроса нет коробки');
  assert(/gs_transfer_2\/gs_transfer_back\.webp/.test(коробка),
    '9h2: подложка пропала — кнопки снова висят на доске');

  // Пропорции картинки 1057x463 = 2.28:1. Сильно другие — и золотая рама с шариками по
  // углам растянется.
  const ш = Number(/width:\s*(\d+)px/.exec(коробка)[1]);
  const в = Number(/height:\s*(\d+)px/.exec(коробка)[1]);
  assert(Math.abs(ш / в - 2.28) < 0.2,
    `9h3: подложка ${ш}x${в} = ${(ш / в).toFixed(2)}:1 против 2.28:1 у картинки — рама `
    + 'растянется');

  // Текст пишется ПО дереву, как на плашке раунда, а не в своём окошке поверх подложки.
  const текст = правило('.leave-confirm__text');
  assert(/Cinzel/.test(текст),
    '9h4: текст вопроса набран не тем шрифтом, что плашка раунда');
  assert(!/background/.test(текст),
    '9h5: у текста снова своя подложка — коробка в коробке читается как недоделка');
}

// === 9i. Окно стоит по центру ПОЛЯ, а не по числам ===
//
// Прибитое числами (left 70, top 300), оно сползало в обоих форматах сразу. Замерено на
// стенде, кадр 460x800 в окне 520x900 и 900x600:
//
//   портрет     — центр доски 259,450, центр окна 259,416: мимо на 34 точки ВВЕРХ;
//   горизонталь — центр доски 450,259, центр окна 484,259: мимо на 34 точки ВПРАВО.
//
// Ошибка одна: окно стояло на кадр y 370 при центре поля 400. В горизонтали кадр
// повёрнут, и те же тридцать точек «выше» выходят «правее» — потому и выглядело как две
// разные поломки.
//
// Лечится привязкой к тем же переменным, которыми поле себя описывает: их пишет
// syncFieldCssVars на #gameContainer, а он у нас и есть кадр (position: relative,
// 460x800) и предок вопроса — то есть числа в них и координаты окна в одной системе.
{
  const коробка = правило('.leave-confirm__box');
  const центрX = /left:\s*calc\(\s*var\(--field-left[^)]*\)\s*\+\s*var\(--field-width[^)]*\)\s*\/\s*2\s*\)/;
  const центрY = /top:\s*calc\(\s*var\(--field-top[^)]*\)\s*\+\s*var\(--field-height[^)]*\)\s*\/\s*2\s*\)/;
  assert(центрX.test(коробка) && центрY.test(коробка),
    '9i: окно снова прибито числами к кадру, а не к центру поля — поле двигается от '
    + 'экрана к экрану, и окно опять сползёт');

  // Держим за центр, а не за угол: размер окна ещё может поменяться.
  assert(/transform:\s*translate\(-50%,\s*-50%\)/.test(коробка),
    '9i2: окно повешено на центр поля углом — оно уедет вправо-вниз на пол-окна');

  // В горизонтали к этому добавляется встречный поворот — и смещение должно уцелеть:
  // одна правка transform затирает другую, они в одном свойстве.
  const гор = правило('html.is-board-landscape .leave-confirm__box');
  assert(гор && /transform:\s*translate\(-50%,\s*-50%\)\s*rotate\(-90deg\)/.test(гор),
    '9i3: в горизонтали поворот затёр смещение за центр — окно повиснет углом на центре '
    + 'поля (замерено: мимо на 113 точек по x и 180 по y)');

  // Переменные до окна доходят только потому, что оно лежит ВНУТРИ того узла, которому
  // их пишут. Вынесут вопрос из #gameContainer — calc останется, а чисел в нём не будет.
  assert(/setProperty\("--field-left"/.test(source) && /setProperty\("--field-top"/.test(source),
    '9i4: поле больше не публикует свои координаты — окну не на что опереться');
  const контейнер = markup.lastIndexOf('<div', markup.indexOf('id="gameContainer"'));
  const вопрос = markup.indexOf('id="leaveMatchConfirm"');
  assert(контейнер !== -1 && вопрос > контейнер, '9i5: не найдены узлы для проверки вложенности');
  const кусок = markup.slice(контейнер, вопрос);
  const глубина = (кусок.match(/<div\b/g) || []).length - (кусок.match(/<\/div>/g) || []).length;
  assert(глубина >= 1,
    '9i5: вопрос вынесли из #gameContainer — переменные поля туда не наследуются, и окно '
    + 'встанет по запасным числам');
}

// === 9j. Вопрос не прячется под плашку раунда ===
//
// Поймано живьём: человек входит в новый раунд, жмёт крестик — и видит на экране только
// «ROUND 2 / YOUR TURN». Вопроса нет, крестик выглядит сломанным.
//
// Своё z-index: 400 вопросу не помогает: он лежит ВНУТРИ доски (#gameContainer), а
// плашка — этажом выше, в #transferSystemHost; оба дети #gsFrame, и доска стоит там на
// z 0. Соревнуются не числа у вопроса и плашки, а числа у их общих предков.
//
// Поэтому на время вопроса поднимается сама доска, и метку снимает тот же код, что
// прячет вопрос: оставшись, она накроет плашки до конца партии.
{
  const х = стенд({ вКомнате: false, вПартии: true });
  assert(х.метки.has('is-leave-asking') === false, '9j: метка стоит до вопроса');
  х.api.спросить();
  assert(х.метки.has('is-leave-asking') === true,
    '9j2: вопрос открыт, а доска не поднята — плашка раунда накроет его целиком, и крестик '
    + 'будет выглядеть сломанным');
  х.api.забыть();
  assert(х.метки.has('is-leave-asking') === false,
    '9j3: метка осталась после ответа — поднятая доска накроет все плашки до конца партии');

  // Уход по «да» и смена экрана — те же двери, и обе ведут через то же «спрятать».
  const у = стенд({ вКомнате: true, вПартии: true });
  у.api.спросить();
  у.api.уйти();
  assert(у.метки.has('is-leave-asking') === false, '9j4: ушли из партии, а метка уехала в меню');

  const з = стенд({ вКомнате: false, вПартии: true });
  з.api.спросить();
  з.стенд.gameMode = null;
  з.api.показать();
  assert(з.метки.has('is-leave-asking') === false,
    '9j5: партия кончилась, вопрос спрятан, а метка осталась');

  // И само правило: поднимать нужно выше слоя, на котором живут плашки. Числа берём из
  // кода — чтобы проверка ловила и то, что подняли слой плашек.
  const правилоПодъёма = правило('html.is-leave-asking #gameStage');
  assert(правилоПодъёма, '9j6: правила подъёма нет — метку некому читать');
  const подъём = Number(/z-index:\s*(\d+)/.exec(правилоПодъёма)[1]);
  const слойПлашек = Number(/TRANSFER_SYSTEM_HOST_Z_INDEX = (\d+)/.exec(source)[1]);
  assert(подъём > слойПлашек,
    `9j7: доску поднимают на ${подъём}, а плашки лежат на ${слойПлашек} — вопрос снова под ними`);
}

