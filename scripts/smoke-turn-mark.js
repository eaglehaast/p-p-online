#!/usr/bin/env node
'use strict';

// Smoke test: метка «чей ход».
//
// Прежняя рисовалась копией спрайта, размытой ctx.filter, поверх оригинала в режиме
// «lighter». Ломалось это двумя способами, и оба видны глазом:
//
//   1. Размытие холста меряется в пикселях ХОЛСТА и с масштабом не едет — замерено
//      отдельным стендом: хвост blur(4px) одинаков и при ctx.scale(1), и при ctx.scale(3).
//      Холст же растёт вместе с плотностью экрана, поэтому на плотном экране кант
//      вырождался в тонкий неоновый обвод, а при отдалении раздувался. «Сбоит при
//      приближении» — это оно.
//   2. «lighter» складывает свет: на светлой бумаге сумма упирается в белое. В сафари та
//      же пара (filter + lighter) рисует вокруг спрайта прямоугольную коробку.
//
// Теперь метка — заливка и кольцо В ЕДИНИЦАХ ИГРЫ, обычным наложением. Проверяется то,
// что отличает её от прежней и ломается тихо: никакой браузерной обработки изображения,
// размеры от самолёта, цвет от стороны, прозрачность от силы и от невидимости.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

function extractFunctionSource(source, fnName){
  const signature = `function ${fnName}(`;
  const start = source.indexOf(signature);
  if(start === -1) throw new Error(`Не найдена функция ${fnName}`);
  const bodyStart = source.indexOf('{', source.indexOf(')', start));
  let depth = 0;
  for(let i = bodyStart; i < source.length; i += 1){
    if(source[i] === '{') depth += 1;
    if(source[i] === '}') depth -= 1;
    if(depth === 0) return source.slice(start, i + 1);
  }
  throw new Error(`Не найден конец функции ${fnName}`);
}

const source = fs.readFileSync('script.js', 'utf8');
const метка = extractFunctionSource(source, 'нарисоватьМеткуХода');

// Поддельный холст: записывает всё, что на нём делали.
function стенд(){
  const ходы = [];
  const остановки = [];
  const ctx = {
    save(){ ходы.push(['save']); },
    restore(){ ходы.push(['restore']); },
    beginPath(){ ходы.push(['beginPath']); },
    arc(x, y, r){ ходы.push(['arc', x, y, r]); },
    fill(){ ходы.push(['fill']); },
    stroke(){ ходы.push(['stroke']); },
    createRadialGradient(x0, y0, r0, x1, y1, r1){
      ходы.push(['gradient', r0, r1]);
      return { addColorStop(поз, цвет){ остановки.push([поз, цвет]); } };
    },
    set filter(значение){ ходы.push(['filter', значение]); },
    set globalCompositeOperation(значение){ ходы.push(['composite', значение]); },
    set globalAlpha(значение){ ходы.push(['globalAlpha', значение]); },
    set shadowBlur(значение){ ходы.push(['shadowBlur', значение]); },
    set fillStyle(_v){}, set strokeStyle(значение){ ходы.push(['strokeStyle', значение]); },
    set lineWidth(значение){ ходы.push(['lineWidth', значение]); },
    setLineDash(узор){ ходы.push(['dash', узор.join(',')]); },
    drawImage(){ ходы.push(['drawImage']); },
  };
  const sandbox = {
    Math, Object, String, Number,
    PLANE_DRAW_W: 36,
    performance: { now: () => 0 },   // дыхание замораживаем: иначе числа пляшут
    Date,
    window: undefined,
  };
  vm.createContext(sandbox);
  vm.runInContext([
    source.match(/const TURN_MARK_RADIUS = [^;]*;/)[0],
    source.match(/const TURN_MARK_ALPHA = [^;]*;/)[0],
    source.match(/const TURN_MARK_INK = Object\.freeze\(\{[\s\S]*?\}\);/)[0],
    source.match(/const TURN_MARK_BREATH_MS = [^;]*;/)[0],
    метка,
    'this.рисовать = нарисоватьМеткуХода;',
    'this.радиус = TURN_MARK_RADIUS;',
  ].join('\n'), sandbox);
  return { ctx, ходы, остановки, api: sandbox };
}

const альфа = (цвет) => Number(/rgba\([^)]*,\s*([0-9.]+)\)/.exec(цвет)[1]);

// === 1. ГЛАВНОЕ: никакой браузерной обработки изображения ===
//
// Ровно на ней метка и ломалась: размытие не масштабируется, «lighter» выжигает светлый
// фон, а сафари на этой паре рисует прямоугольник.
{
  const с = стенд();
  с.api.рисовать(с.ctx, { color: 'green' }, 1, 1);
  const имена = с.ходы.map(([имя]) => имя);
  assert(!имена.includes('filter'),
    '1: метка снова размывается средствами холста — размытие меряется в пикселях холста и '
    + 'при приближении станет втрое тоньше, а в сафари даст прямоугольную коробку');
  assert(!имена.includes('composite'),
    '1b: метка снова складывает свет («lighter») — на светлой бумаге край выгорит в белое');
  assert(!имена.includes('drawImage'),
    '1c: метка снова рисует копию спрайта — это и был тот самый ореол');
  assert(!имена.includes('shadowBlur'), '1d: метка размывается тенью холста');
  assert(имена.includes('fill'), '1e: метка больше ничего не заливает — показывать нечем');
  assert(!имена.includes('stroke'),
    '1f: у метки снова появилось кольцо — обводка спорит с картинкой, а картинка здесь '
    + 'важнее метки');
  assert(имена.includes('save') && имена.includes('restore'),
    '1g: метка не возвращает холст в прежнее состояние — следующий рисунок поедет');
}

// === 2. Размеры — от самолёта, а не от экрана ===
{
  const с = стенд();
  с.api.рисовать(с.ctx, { color: 'blue' }, 1, 1);
  const дуги = с.ходы.filter(([имя]) => имя === 'arc').map(([, , , r]) => r);
  assert(дуги.length === 1, `2: у метки ${дуги.length} окружностей вместо одной`);
  assert(дуги[0] > 36 * 0.4 && дуги[0] < 36 * 1.2,
    `2b: окружность радиусом ${дуги[0]} при самолёте в 36 единиц — метка оторвалась от самолёта`);
  assert(Math.abs(с.api.радиус - 36 * 0.8) < 0.001,
    '2c: радиус метки больше не считается от размера самолёта');
}

// === 3. Цвет — от стороны ===
{
  const синий = стенд();
  синий.api.рисовать(синий.ctx, { color: 'blue' }, 1, 1);
  const зелёный = стенд();
  зелёный.api.рисовать(зелёный.ctx, { color: 'green' }, 1, 1);
  const первый = (с) => с.остановки[0][1];
  assert(первый(синий) !== первый(зелёный),
    '3: обе стороны отмечаются одним цветом — по метке будет не понять, чей ход');
  const числа = (цвет) => /rgba\((\d+), (\d+), (\d+)/.exec(цвет).slice(1, 4).map(Number);
  const [sr, sg, sb] = числа(первый(синий));
  const [zr, zg, zb] = числа(первый(зелёный));
  assert(sb > sr && sb > sg, `3b: метка синей стороны не синяя (${sr},${sg},${sb})`);
  assert(zg > zr && zg > zb, `3c: метка зелёной стороны не зелёная (${zr},${zg},${zb})`);
}

// === 4. Сила и невидимость гасят метку, а не включают её ===
{
  const нет = стенд();
  assert(нет.api.рисовать(нет.ctx, { color: 'green' }, 0, 1) === false,
    '4: метка рисуется при нулевой силе — она будет гореть и в чужой ход');
  assert(нет.ходы.length === 0, '4b: при нулевой силе холст всё равно трогали');

  const скрытый = стенд();
  assert(скрытый.api.рисовать(скрытый.ctx, { color: 'green' }, 1, 0) === false,
    '4c: у невидимого самолёта метка осталась — невидимость перестала быть невидимостью');

  const полный = стенд();
  полный.api.рисовать(полный.ctx, { color: 'green' }, 1, 1);
  const половина = стенд();
  половина.api.рисовать(половина.ctx, { color: 'green' }, 0.5, 1);
  assert(альфа(половина.остановки[0][1]) < альфа(полный.остановки[0][1]),
    '4d: вполовину разгоревшаяся метка не бледнее полной — появление станет рывком');

  const призрак = стенд();
  призрак.api.рисовать(призрак.ctx, { color: 'green' }, 1, 0.4);
  assert(альфа(призрак.остановки[0][1]) < альфа(полный.остановки[0][1]),
    '4e: прозрачность самолёта на метку не влияет — она будет ярче того, что метит');
}

// === 5. Метка не навязчива ===
//
// Она отвечает на один вопрос и не должна спорить с доской: сквозь неё видно и клетку, и
// кирпич, и сам самолёт.
{
  const с = стенд();
  с.api.рисовать(с.ctx, { color: 'green' }, 1, 1);
  const центр = альфа(с.остановки[0][1]);
  assert(центр > 0.05 && центр < 0.45,
    `5: заливка метки непрозрачна на ${центр} — это уже не подсветка, а пятно`);
  const край = альфа(с.остановки[с.остановки.length - 1][1]);
  assert(край === 0, '5b: лужица обрывается резким краем');

  // И главное про форму: середина ровная, а не конус.
  //
  // Самолёт закрывает центр метки, видна только внешняя половина. У обычного конуса там
  // остаются доли процента — метку приходится задирать до пятна, чтобы её заметили.
  const середина = с.остановки.find(([поз]) => поз > 0.4 && поз < 0.7);
  assert(середина, '5c: у метки нет ровной середины — градиент снова конус');
  assert(альфа(середина[1]) >= центр * 0.9,
    `5d: к середине метка уже выцвела (${альфа(середина[1])} против ${центр} в центре) — `
    + 'видимая часть окажется прозрачной, и её придётся делать пятном');
}

// === 6. Рисует её тот же путь, что и прежде ===
{
  const самолёт = extractFunctionSource(source, 'drawThinPlane');
  assert(/нарисоватьМеткуХода\(ctx2d, plane, blend, invisibilityVisualAlpha\)/.test(самолёт),
    '6: метку перестали рисовать при отрисовке самолёта');
  assert(!/drawPlaneSpriteGlow/.test(source),
    '6b: прежняя подсветка спрайта осталась в коде — две метки на один вопрос');
}

console.log('smoke-turn-mark: OK');
