#!/usr/bin/env node
'use strict';

// Smoke test: метка «чей ход» — контур по силуэту самолёта.
//
// Обвести самолёт — мысль верная, ломалось исполнение. Прежний контур делался копией
// спрайта, размытой ctx.filter, поверх оригинала в режиме «lighter», и разваливался
// двумя способами:
//
//   1. Размытие холста меряется в пикселях ХОЛСТА и с масштабом не едет — замерено
//      отдельным стендом: хвост blur(4px) одинаков и при ctx.scale(1), и при ctx.scale(3).
//      Холст растёт вместе с плотностью экрана, поэтому при приближении кант вырождался в
//      тонкую неоновую нитку, а при отдалении раздувался в муть.
//   2. «lighter» складывает свет: на светлой бумаге край выгорает, а в сафари эта пара
//      рисует вокруг спрайта прямоугольную коробку.
//
// Теперь контур печётся из самого силуэта: спрайт штампуется по кругу со сдвигом в
// единицах игры, перекрашивается целиком и запекается в заготовку — по одной на сторону.
// На кадре это один drawImage. Проверяется то, что отличает новый контур от старого и
// ломается тихо.

const fs = require('fs');
const vm = require('vm');
const { светлота } = require('./sprite-alpha-utils.js');

const ПУТЬ_ЗЕЛЁНОГО = 'ui_gamescreen/PLANES/gs_plane_green.png';
const ПУТЬ_СИНЕГО = 'ui_gamescreen/PLANES/gs_plane_blue.png';

function assert(condition, message){
  if(!condition) throw new Error(message);
}

function extractFunctionSource(source, fnName){
  const signature = `function ${fnName}(`;
  const start = source.indexOf(signature);
  if(start === -1) throw new Error(`Не найдена функция ${fnName}`);
  const bodyStart = source.indexOf('{', source.indexOf(')', start));
  let depth = 0;
  for(let i = bodyStart; i < source.length; i += 1){
    if(source[i] === '{') depth += 1;
    if(source[i] === '}') depth -= 1;
    if(depth === 0) return source.slice(start, i + 1);
  }
  throw new Error(`Не найден конец функции ${fnName}`);
}

const source = fs.readFileSync('script.js', 'utf8');

// Стенд: поддельные холст и спрайты, всё записывается.
function стенд(){
  const ходы = [];
  const заготовки = [];

  const поддельныйКонтекст = (куда) => ({
    set imageSmoothingEnabled(_v){},
    set globalCompositeOperation(значение){ куда.push(['composite', значение]); },
    set fillStyle(значение){ куда.push(['fillStyle', значение]); },
    set filter(значение){ куда.push(['filter', значение]); },
    set shadowBlur(значение){ куда.push(['shadowBlur', значение]); },
    set globalAlpha(значение){ куда.push(['globalAlpha', значение]); },
    get globalAlpha(){ return 1; },
    fillRect(){ куда.push(['fillRect']); },
    drawImage(_img, x, y, w, h){ куда.push(['drawImage', x, y, w, h]); },
    save(){ куда.push(['save']); },
    restore(){ куда.push(['restore']); },
  });

  const ctx = поддельныйКонтекст(ходы);
  const sandbox = {
    Math, Object, String, Number, Map,
    PLANE_DRAW_W: 36,
    performance: { now: () => 0 },   // дыхание замораживаем
    Date,
    bluePlaneImg: { ready: true, src: 'blue' },
    greenPlaneImg: { ready: true, src: 'green' },
    isSpriteReady: (img) => Boolean(img && img.ready),
    document: {
      createElement(тип){
        const свой = [];
        const холст = {
          тип, width: 0, height: 0, следы: свой,
          getContext: () => поддельныйКонтекст(свой),
        };
        заготовки.push(холст);
        return холст;
      },
    },
  };
  vm.createContext(sandbox);
  vm.runInContext([
    source.match(/const TURN_OUTLINE_WIDTH = [^;]*;/)[0],
    source.match(/const TURN_OUTLINE_STAMPS = [^;]*;/)[0],
    source.match(/const TURN_OUTLINE_OVERSAMPLE = [^;]*;/)[0],
    source.match(/const TURN_OUTLINE_ALPHA = [^;]*;/)[0],
    source.match(/const TURN_OUTLINE_INK = Object\.freeze\(\{[\s\S]*?\}\);/)[0],
    source.match(/const TURN_MARK_BREATH_MS = [^;]*;/)[0],
    'const запечённыеКонтуры = new Map();',
    extractFunctionSource(source, 'запечьКонтур'),
    extractFunctionSource(source, 'нарисоватьМеткуХода'),
    'this.рисовать = нарисоватьМеткуХода;',
    'this.ширина = TURN_OUTLINE_WIDTH;',
    'this.штампов = TURN_OUTLINE_STAMPS;',
    'this.чернила = TURN_OUTLINE_INK;',
    'this.альфа = TURN_OUTLINE_ALPHA;',
    'this.запечено = () => запечённыеКонтуры.size;',
  ].join('\n'), sandbox);
  return { ctx, ходы, заготовки, api: sandbox };
}

// === 1. ГЛАВНОЕ: никакой браузерной обработки изображения ===
{
  const с = стенд();
  с.api.рисовать(с.ctx, { color: 'green' }, 1, 1);
  const всеХоды = [...с.ходы, ...с.заготовки.flatMap((з) => з.следы)];
  const имена = всеХоды.map(([имя]) => имя);
  assert(!имена.includes('filter'),
    '1: контур снова размывается средствами холста — размытие меряется в пикселях холста, '
    + 'при приближении станет втрое тоньше, а в сафари даст прямоугольную коробку');
  assert(!имена.includes('shadowBlur'), '1b: контур размывается тенью холста');
  const склейки = всеХоды.filter(([имя]) => имя === 'composite').map(([, v]) => v);
  assert(!склейки.includes('lighter'),
    '1c: контур снова складывает свет — на светлой бумаге край выгорит в белое');
  assert(склейки.includes('source-in'),
    '1d: штампы не перекрашиваются целиком — на перекрытиях скопится плотность, и контур '
    + 'выйдет пятнистым');
}

// === 2. Контур строится из силуэта, а не из круга ===
{
  const с = стенд();
  с.api.рисовать(с.ctx, { color: 'green' }, 1, 1);
  const заготовка = с.заготовки[0];
  assert(заготовка, '2: заготовка контура не создана');
  const штампы = заготовка.следы.filter(([имя]) => имя === 'drawImage');
  // Число сверяется с числом, а не с той же константой: иначе проверка согласится с
  // любым. Меньше десяти сдвигов по кругу — и контур идёт углами, это видно глазом.
  assert(штампы.length >= 10,
    `2b: силуэт отштампован ${штампы.length} раз — у контура будут углы вместо кромки`);
  assert(штампы.length === с.api.штампов, '2b2: штампов не столько, сколько заказано');
  // Штампы расходятся во все стороны: и влево-вправо, и вверх-вниз.
  const xs = штампы.map(([, x]) => x);
  const ys = штампы.map(([, , y]) => y);
  assert(Math.max(...xs) - Math.min(...xs) > 0 && Math.max(...ys) - Math.min(...ys) > 0,
    '2c: штампы сдвинуты только по одной оси — контур выйдет односторонним');
}

// === 3. Толщина — в единицах игры, а не в пикселях экрана ===
//
// Ровно на этом ломался прежний контур.
{
  const с = стенд();
  с.api.рисовать(с.ctx, { color: 'blue' }, 1, 1);
  const рисунок = с.ходы.find(([имя]) => имя === 'drawImage');
  assert(рисунок, '3: контур не нарисован');
  const [, x, y, w, h] = рисунок;
  assert(Math.abs(w - (36 + с.api.ширина * 2)) < 0.001 && Math.abs(h - w) < 0.001,
    `3b: контур рисуется размером ${w} вместо ${36 + с.api.ширина * 2} — толщина перестала `
    + 'считаться от самолёта');
  assert(Math.abs(x + w / 2) < 0.001 && Math.abs(y + h / 2) < 0.001,
    '3c: контур смещён относительно самолёта');
  assert(с.api.ширина > 0.3 && с.api.ширина < 3,
    `3d: толщина ${с.api.ширина} при самолёте в 36 единиц — это либо не видно, либо шуба`);
  assert(!/const TURN_OUTLINE_WIDTH = [^;]*(devicePixelRatio|dpr)/i.test(source),
    '3e: толщина снова зависит от плотности экрана');
}

// === 4. Заготовка печётся один раз на сторону ===
//
// Иначе на каждом кадре создаётся холст на каждый самолёт — и это на каждом кадре.
{
  const с = стенд();
  for(let i = 0; i < 20; i += 1){
    с.api.рисовать(с.ctx, { color: 'green' }, 1, 1);
    с.api.рисовать(с.ctx, { color: 'blue' }, 1, 1);
  }
  assert(с.заготовки.length === 2,
    `4: заготовок напечено ${с.заготовки.length} вместо двух — холст создаётся на каждом кадре`);
  assert(с.api.запечено() === 2, '4b: заготовки не запоминаются');
  const рисунков = с.ходы.filter(([имя]) => имя === 'drawImage').length;
  assert(рисунков === 40, `4c: на 40 вызовов пришлось ${рисунков} рисований`);
}

// === 5. Цвет — от стороны, темнее самой машины и насыщенный ===
//
// Прежде правило было обратным: кант делали светлее самолёта. На бумаге светлый кант
// расплывался дымкой и съедал собственный тёмный контур спрайта. Пересмотрено по
// лесенке снимков: светлота 158 и 185 — бледно, 92 — вяло, 39 — траур и похоже на тень.
{
  const с = стенд();
  с.api.рисовать(с.ctx, { color: 'green' }, 1, 1);
  с.api.рисовать(с.ctx, { color: 'blue' }, 1, 1);
  const краски = с.заготовки.map((з) => з.следы.find(([имя]) => имя === 'fillStyle')[1]);
  assert(краски[0] !== краски[1],
    '5: обе стороны обводятся одним цветом — по метке будет не понять, чей ход');

  const разобрать = (цвет) => /rgb\((\d+), (\d+), (\d+)\)/.exec(цвет).slice(1, 4).map(Number);
  const яркость = (канал) => (канал[0] + канал[1] + канал[2]) / 3;

  // Светлота машины считается из её же картинки, а не списана числом: правило должно
  // пережить перекраску спрайтов. Замерено сейчас: зелёная 89.7, синяя 83.9, кант 62.
  for(const [сторона, спрайт] of [['green', ПУТЬ_ЗЕЛЁНОГО], ['blue', ПУТЬ_СИНЕГО]]){
    const канал = разобрать(с.api.чернила[сторона]);
    const машина = светлота(спрайт);
    assert(яркость(канал) < машина,
      `5b: кант стороны ${сторона} светлее самой машины (${яркость(канал).toFixed(0)} против `
      + `${машина.toFixed(0)}) — светлый расплывается дымкой и съедает контур спрайта`);
    assert(яркость(канал) >= 45,
      `5c: кант стороны ${сторона} почти чёрный (${яркость(канал).toFixed(0)}) — такой читается `
      + 'как тень, а не как метка');
    const размах = Math.max(...канал) - Math.min(...канал);
    assert(размах >= 60,
      `5d: кант стороны ${сторона} обесцвечен (размах каналов ${размах}) — серый кант не говорит, `
      + 'чья сторона, а у тёмной синей машины ещё и сливается с её собственными краями');
  }

  const зелёный = разобрать(с.api.чернила.green);
  const синий = разобрать(с.api.чернила.blue);
  assert(зелёный[1] > зелёный[0] && зелёный[1] > зелёный[2], '5e: кант зелёной стороны не зелёный');
  assert(синий[2] > синий[0] && синий[2] > синий[1], '5f: кант синей стороны не синий');
  assert(Math.abs(яркость(зелёный) - яркость(синий)) <= 12,
    `5g: стороны разной светлоты (${яркость(зелёный).toFixed(0)} и ${яркость(синий).toFixed(0)}) — `
    + 'одна метка выглядит ярче другой, хотя значат они одно и то же');
}

// === 6. Сила и невидимость гасят метку, а не включают её ===
{
  const нет = стенд();
  assert(нет.api.рисовать(нет.ctx, { color: 'green' }, 0, 1) === false,
    '6: метка рисуется при нулевой силе — она будет гореть и в чужой ход');
  assert(нет.ходы.length === 0, '6b: при нулевой силе холст всё равно трогали');

  const скрытый = стенд();
  assert(скрытый.api.рисовать(скрытый.ctx, { color: 'green' }, 1, 0) === false,
    '6c: у невидимого самолёта метка осталась — невидимость перестала быть невидимостью');

  const альфа = (с) => с.ходы.find(([имя]) => имя === 'globalAlpha')[1];
  const полный = стенд();
  полный.api.рисовать(полный.ctx, { color: 'green' }, 1, 1);
  const половина = стенд();
  половина.api.рисовать(половина.ctx, { color: 'green' }, 0.5, 1);
  assert(альфа(половина) < альфа(полный),
    '6d: вполовину разгоревшаяся метка не бледнее полной — появление станет рывком');
  const призрак = стенд();
  призрак.api.рисовать(призрак.ctx, { color: 'green' }, 1, 0.35);
  assert(альфа(призрак) < альфа(полный),
    '6e: прозрачность самолёта на метку не влияет — она будет ярче того, что метит');
  assert(альфа(полный) <= 1, `6f: прозрачность метки ${альфа(полный)} — больше единицы не бывает`);
}

// === 7. Без спрайта метка молчит ===
//
// Спрайты подгружаются позже страницы, и до их приезда печь нечего.
{
  const с = стенд();
  с.api.greenPlaneImg = { ready: false };
  assert(с.api.рисовать(с.ctx, { color: 'green' }, 1, 1) === false,
    '7: контур печётся из незагруженного спрайта — получится пустая заготовка, и она же '
    + 'запомнится навсегда');
  assert(с.заготовки.length === 0, '7b: холст заготовки создан впустую');
}

// === 8. Рисует её тот же путь, что и прежде ===
{
  const самолёт = extractFunctionSource(source, 'drawThinPlane');
  assert(/нарисоватьМеткуХода\(ctx2d, plane, blend, invisibilityVisualAlpha\)/.test(самолёт),
    '8: метку перестали рисовать при отрисовке самолёта');
  assert(!/drawPlaneSpriteGlow/.test(source),
    '8b: прежняя подсветка спрайта осталась в коде — две метки на один вопрос');
}

console.log('smoke-turn-mark: OK');
