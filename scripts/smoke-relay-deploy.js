#!/usr/bin/env node
'use strict';

// Smoke test: ретранслятор заливается сам, и заливается не вслепую.
//
// Сайт и ретранслятор живут в разных местах. Сайт раздаёт GitHub Pages прямо из ветки, и
// после слияния новая версия у всех сама. Ретранслятор лежит в Cloudflare, и попадает туда
// только заливкой.
//
// Расходятся они молча и ломают всё разом: комната сверяет номер протокола при входе и с
// чужим не пускает. Игра на сайте новая, ретранслятор старый — «Play» не загорается
// никогда, и по экрану не понять почему. На этом уже наступали.
//
// Поэтому заливка повешена на слияние в main. Здесь проверяется, что она не разъехалась с
// тем, ради чего заведена, и что перед заливкой гоняются проверки: иначе автоматика будет
// исправно разносить сломанное.

const fs = require('fs');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const ПУТЬ = '.github/workflows/relay.yml';
assert(fs.existsSync(ПУТЬ),
  `0: нет ${ПУТЬ} — ретранслятор снова заливается руками, а значит рано или поздно `
  + 'разойдётся с сайтом');
// Разбирать надо сам поток, а не комментарии к нему: в шапке файла объяснено, зачем он
// нужен, и там же словами названы и «wrangler deploy», и имена ключей. Первая же версия
// этого теста на них и попалась — нашла заливку в объяснении и решила, что проверки идут
// после неё.
const поток = fs.readFileSync(ПУТЬ, 'utf8')
  .split('\n')
  .filter((строка) => !/^\s*#/.test(строка))
  .join('\n');

// === 1. Срабатывает на слияние в main, и только из-за самого ретранслятора ===
//
// Фильтр по папке — не экономия минут. Лишняя перезаливка рвёт соединение тем, кто прямо
// сейчас играет, а правки игры к ретранслятору отношения не имеют.
{
  assert(/on:/.test(поток) && /branches:\s*\[main\]/.test(поток),
    '1: заливка не привязана к main — она не случится тогда, когда нужна');
  assert(/paths:/.test(поток) && /'worker\/\*\*'/.test(поток),
    '1b: пропал фильтр по папке — ретранслятор станет перезаливаться на каждую правку '
    + 'игры и рвать соединение играющим');
  assert(/'\.github\/workflows\/relay\.yml'/.test(поток),
    '1c: правка самого потока не вызывает заливку — проверить её будет нечем');
  assert(/workflow_dispatch:/.test(поток),
    '1d: нет ручного запуска — залить, не трогая файлов, станет нечем');
}

// === 2. ГЛАВНОЕ: перед заливкой гоняются проверки ===
//
// Без этого автоматика превращается в способ разносить поломку быстрее, чем раньше. И
// проверки должны идти ИМЕННО ДО заливки: после — это уже отчёт о случившемся.
{
  const где = (что) => поток.indexOf(что);
  const проверки = где('node "$f"');
  const заливка = где('wrangler deploy');
  assert(проверки !== -1,
    '2: перед заливкой не гоняется набор проверок — автоматика начнёт разносить сломанное');
  assert(заливка !== -1, '2b: в потоке нет самой заливки');
  assert(проверки < заливка,
    '2c: проверки идут ПОСЛЕ заливки — это уже не заслон, а отчёт о случившемся');

  // Падение любой проверки обязано останавливать заливку.
  assert(/exit 1/.test(поток),
    '2d: упавшая проверка не останавливает заливку');
}

// === 3. Ключ лежит в секретах, а не в файле ===
//
// Репозиторий открытый. Ключ Cloudflare, попавший в него хоть на один коммит, считается
// утёкшим навсегда: его видно в истории и в зеркалах, и отзывать его придётся в любом
// случае.
{
  const ключи = [...поток.matchAll(/(CLOUDFLARE_[A-Z_]+):\s*(.+)/g)];
  assert(ключи.length >= 2,
    '3: заливке не передают ни ключ, ни номер аккаунта — она не пройдёт');
  for(const [, имя, значение] of ключи){
    assert(/^\$\{\{\s*secrets\./.test(значение.trim()),
      `3b: ${имя} записан в файл прямо («${значение.trim().slice(0, 24)}…») — репозиторий `
      + 'открытый, и такой ключ считается утёкшим навсегда');
  }
}

// === 4. Заливается именно та папка ===
{
  assert(/working-directory:\s*worker/.test(поток),
    '4: заливка идёт не из папки worker — wrangler не найдёт своих настроек');
  assert(fs.existsSync('worker/wrangler.toml'),
    '4b: нет worker/wrangler.toml — заливать нечего');

  // На бесплатном плане Durable Objects бывают только на SQLite. С new_classes заливка
  // отказывает с ошибкой 10097, и сломается она не здесь, а в облаке.
  //
  // Комментарии отрезаны по той же причине, что и у потока: в самом wrangler.toml над этой
  // строкой написано «new_sqlite_classes, а не new_classes», и проверка находила нужное
  // слово в объяснении, даже когда в настройке стояло неверное.
  const настройки = fs.readFileSync('worker/wrangler.toml', 'utf8')
    .split('\n')
    .filter((строка) => !/^\s*#/.test(строка))
    .join('\n');
  assert(/new_sqlite_classes/.test(настройки),
    '4c: в wrangler.toml не new_sqlite_classes — на бесплатном плане заливка откажет (10097)');
}

console.log('smoke-relay-deploy: OK');
