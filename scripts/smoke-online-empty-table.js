#!/usr/bin/env node
'use strict';

// Smoke test: пришедшему по ссылке говорят, если за столом никого нет.
//
// Ссылка живёт двенадцать часов, так что открыть её, когда хозяина уже нет, — обычное
// дело, а не редкий случай. До сих пор это выглядело ровно так же, как «друг сейчас
// подойдёт»: надпись WAITING, крутящиеся самолёты и больше ничего. Навсегда. Отличить
// одно от другого было нечем, и единственный вывод, который из этого следует, — «игра
// сломалась».
//
// Поломка тихая вдвойне: ошибки нет, оба конца исправны, просто за столом один человек.
//
// Надпись встаёт НА МЕСТО вертушки, а не рядом. Крутящиеся самолёты означают «идёт
// дело» — что-то грузится, кто-то вот-вот подключится; ровно этого здесь и не
// происходит, и крутиться им в такую минуту значит обещать. Оформление — то же, что у
// остальных подсказок игры («Link copied» и прочих), и медленное дыхание вместо
// вращения: жизнь на экране остаётся, обещание — нет.
//
// Проверяется:
//
//   1. Что сказано и когда — не сразу, а пережив мигание связи.
//   2. Самолёты при этом уходят, и возвращаются, когда надписи больше нет.
//   3. Чужую надпись в том же окошке («Link sent.» у хозяина) она не трогает.
//   4. Будильник: пустой стол — это не событие, а его отсутствие.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const source = fs.readFileSync('script.js', 'utf8');
const styles = fs.readFileSync('styles.css', 'utf8');

function extractFunctionSource(text, name){
  const start = text.indexOf(`function ${name}(`);
  if(start === -1) throw new Error(`Не найдена функция ${name}`);
  let глубина = 0;
  let i = text.indexOf('(', start);
  for(; i < text.length; i += 1){
    if(text[i] === '(') глубина += 1;
    if(text[i] === ')'){ глубина -= 1; if(глубина === 0) break; }
  }
  const bodyStart = text.indexOf('{', i);
  let depth = 0;
  for(let j = bodyStart; j < text.length; j += 1){
    if(text[j] === '{') depth += 1;
    if(text[j] === '}') depth -= 1;
    if(depth === 0) return text.slice(start, j + 1);
  }
  throw new Error(`Не найден конец функции ${name}`);
}

const СРОК = Number(/const ONLINE_EMPTY_TABLE_NOTICE_MS = ([\d_]+);/.exec(source)[1].replace(/_/g, ''));
const ТЕКСТ = /const ONLINE_EMPTY_TABLE_TEXT =\s*\n?\s*"((?:[^"\\]|\\.)*)";/.exec(source)[1]
  .replace(/\\n/g, '\n');

// Стенд: настоящие функции показа, поддельные часы, окошко и меню.
function стенд({ место = 'blue', хозяинСтола = 'green', завёл = false, соседа = false,
  связь = 'online' } = {}){
  const часы = { ms: 1_700_000_000_000 };

  function узел(){
    const классы = new Set();
    const n = {
      hidden: true,
      textContent: '',
      classList: {
        add: (...к) => к.forEach((x) => классы.add(x)),
        remove: (...к) => к.forEach((x) => классы.delete(x)),
        toggle: (к, в) => { if(в === true) классы.add(к); else классы.delete(к); },
        contains: (к) => классы.has(к),
      },
      классы,
    };
    return n;
  }

  const sandbox = {
    Object, Number, Boolean, String,
    Date: { now: () => часы.ms },
    часы,
    заведено: [],
    снято: 0,
    setTimeout: (fn, ms) => { sandbox.заведено.push({ ms, fn }); return sandbox.заведено.length; },
    clearTimeout: () => { sandbox.снято += 1; },
    requestAnimationFrame: (fn) => fn(),
    gameMode: null,
    onlinePresence: { blue: место === 'blue' || соседа, green: место === 'green' || соседа },
    onlineSession: {
      seat: место,
      host: завёл,
      hostSeat: хозяинСтола,
      aloneSince: null,
      transport: { status: () => связь, rejection: () => null },
    },
    HTMLElement: function HTMLElement(){},
    lobbyToast: null,
    меню: узел(),
  };
  sandbox.lobbyToast = узел();
  Object.setPrototypeOf(sandbox.lobbyToast, sandbox.HTMLElement.prototype);
  sandbox.document = { getElementById: (id) => (id === 'modeMenu' ? sandbox.меню : null) };

  vm.createContext(sandbox);
  vm.runInContext([
    `const ONLINE_EMPTY_TABLE_NOTICE_MS = ${СРОК};`,
    source.match(/const ONLINE_EMPTY_TABLE_TEXT =[\s\S]*?;/)[0],
    'let onlineEmptyTableTimer = null;',
    extractFunctionSource(source, 'isOnlineHost'),
    extractFunctionSource(source, 'isOnlineTableFull'),
    extractFunctionSource(source, 'следитьЗаПустымСтолом'),
    extractFunctionSource(source, 'isOnlineTableEmptyForLong'),
    extractFunctionSource(source, 'getOnlineTroubleText'),
    extractFunctionSource(source, 'показатьПодсказкуЛобби'),
    extractFunctionSource(source, 'спрятатьПодсказкуЛобби'),
    extractFunctionSource(source, 'обновитьНадписьПустогоСтола'),
    'this.api = {',
    '  следить: следитьЗаПустымСтолом, обновить: обновитьНадписьПустогоСтола,',
    '  беда: getOnlineTroubleText,',
    '  видна: () => lobbyToast.hidden !== true && lobbyToast.classList.contains("is-visible"),',
    '  текст: () => lobbyToast.textContent,',
    '  наМестеСамолётов: () => lobbyToast.classList.contains("is-empty-table"),',
    '  самолётыСпрятаны: () => меню.classList.contains("is-table-empty"),',
    '  сел: () => { onlinePresence = { blue: true, green: true }; },',
    '  чужаяПодсказка: (т) => показатьПодсказкуЛобби(т),',
    '};',
  ].join('\n'), sandbox);
  return { api: sandbox.api, часы, стенд: sandbox };
}

// === 1. ГЛАВНОЕ: надпись появляется, но не раньше срока ===
{
  const г = стенд();
  г.api.следить();
  г.api.обновить();
  assert(г.api.видна() === false,
    '1: надпись выскочила сразу — она соврёт каждому, у кого друг просто на секунду '
    + 'провалился в лифте');

  г.часы.ms += СРОК - 1;
  г.api.обновить();
  assert(г.api.видна() === false, '1b: надпись появилась за миг до срока');

  г.часы.ms += 1;
  г.api.обновить();
  assert(г.api.видна() === true,
    '1c: за пустым столом так ничего и не сказано — гость по-прежнему не отличает «сейчас '
    + 'подойдёт» от «тут никого»');
  assert(г.api.текст() === ТЕКСТ, `1d: сказано не то: «${г.api.текст()}»`);
}

// === 2. Что именно сказано ===
//
// Три вещи, и каждая отвечает на свой вопрос: что происходит, жива ли ссылка, что делать.
{
  assert(/table/i.test(ТЕКСТ), `2: в надписи нет речи о столе: «${ТЕКСТ}»`);
  assert(/link/i.test(ТЕКСТ),
    `2b: не сказано, что ссылка ещё жива («${ТЕКСТ}») — человек решит, что она протухла, и `
    + 'попросит новую');
  assert(/Cancel/.test(ТЕКСТ),
    `2c: не названо, чем отсюда выйти («${ТЕКСТ}») — кнопка Cancel рядом, но догадаться о `
    + 'ней неоткуда');
  assert(ТЕКСТ.includes('\n'),
    '2d: надпись в одну строку — в окошке подсказки она растянется некрасиво');
  assert(ТЕКСТ.split('\n').length === 2, '2e: строк стало больше двух: это уже инструкция');
  assert(!/[А-Яа-яЁё]/.test(ТЕКСТ), `2f: надпись не на языке лобби: «${ТЕКСТ}»`);
}

// === 3. Самолёты уходят, а надпись встаёт на их место ===
{
  const г = стенд();
  г.api.следить();
  г.часы.ms += СРОК;
  г.api.обновить();
  assert(г.api.наМестеСамолётов() === true,
    '3: надпись встала не на место вертушки, а в обычное — под кнопками, где её ждёт '
    + '«Link sent.»');
  assert(г.api.самолётыСпрятаны() === true,
    '3b: самолёты продолжают крутиться рядом с надписью «тут никого» — вращение обещает '
    + 'то, чего не происходит');

  // Пришёл друг — всё возвращается на место.
  г.api.сел();
  г.api.обновить();
  assert(г.api.видна() === false, '3c: друг за столом, а надпись осталась');
  assert(г.api.самолётыСпрятаны() === false,
    '3d: самолёты не вернулись — экран гостя остался без вертушки навсегда');
  assert(г.api.наМестеСамолётов() === false, '3e: окошко осталось в месте вертушки');
}

// === 4. Чужую надпись в том же окошке не трогает ===
//
// «Link sent.» у хозяина живёт в этом же окошке. Погасить его заодно значило бы отнять у
// человека единственный ответ на нажатие.
{
  const х = стенд({ место: 'green', хозяинСтола: 'green', завёл: true });
  х.api.чужаяПодсказка('Link sent.\nWaiting for your friend…');
  х.часы.ms += СРОК * 2;
  х.api.обновить();
  assert(х.api.видна() === true && /Link sent/.test(х.api.текст()),
    '4: ответ на «Send link» погашен чужой заботой о пустом столе');
  assert(х.api.самолётыСпрятаны() === false, '4b: у хозяина спрятали вертушку, которой у него и нет');
}

// === 5. Нажавшему Online этого не говорят ===
//
// У него на экране «Send link» и зазывание нажать её. Решает именно НАЖАТИЕ, а не роль за
// столом: ролью комната может наградить и пришедшего по ссылке.
{
  const х = стенд({ место: 'green', хозяинСтола: 'green', завёл: true });
  х.api.следить();
  х.часы.ms += СРОК * 2;
  х.api.обновить();
  assert(х.api.видна() === false, `5: нажавшему Online сказали, что за столом никого`);

  const поСсылкеНоХозяин = стенд({ место: 'green', хозяинСтола: 'green', завёл: false });
  поСсылкеНоХозяин.api.следить();
  поСсылкеНоХозяин.часы.ms += СРОК * 2;
  поСсылкеНоХозяин.api.обновить();
  assert(поСсылкеНоХозяин.api.видна() === true,
    '5b: пришедшему по ссылке не сказали, что за столом никого, — только потому, что '
    + 'комната назвала его хозяином стола. Он об этом не просил и ждёт друга');

  const тело = extractFunctionSource(source, 'обновитьНадписьПустогоСтола');
  assert(/onlineSession\.host !== true/.test(тело),
    '5c: надпись снова привязана к роли за столом, а не к тому, как человек сюда попал');
}

// === 6. Беда со связью важнее ===
//
// Оборванная связь — другая беда и другой совет, и у неё своя панель. Сказать «за столом
// никого», когда мы сами отвалились, значило бы послать человека ждать того, кто, может,
// давно за столом.
{
  for(const связь of ['offline', 'rejected']){
    const о = стенд({ связь });
    о.api.следить();
    о.часы.ms += СРОК * 2;
    о.api.обновить();
    assert(о.api.видна() === false,
      `6: при связи «${связь}» поверх беды висит ещё и «за столом никого»`);
    assert(о.api.беда() !== '', `6b: беда «${связь}» перестала попадать в свою панель`);
  }
}

// === 7. Будильник ===
//
// Без него надпись ждала бы следующего события — а за пустым столом не происходит ничего.
{
  const г = стенд();
  г.api.следить();
  assert(г.стенд.заведено.length === 1,
    '7: будильник не заведён — надпись дождётся события, которого не будет');
  assert(г.стенд.заведено[0].ms === СРОК,
    `7b: будильник заведён на ${г.стенд.заведено[0].ms} мс вместо ${СРОК}`);

  // Повторное известие о присутствии не отодвигает срок: иначе каждое мигание соседнего
  // места начинало бы отсчёт заново, и надпись не появилась бы никогда.
  const началС = г.стенд.onlineSession.aloneSince;
  г.часы.ms += 5000;
  г.api.следить();
  assert(г.стенд.onlineSession.aloneSince === началС,
    '7c: отсчёт начался заново — при мигающем соседе надпись не появится никогда');
  assert(г.стенд.заведено[1].ms === СРОК - 5000,
    `7d: новый будильник на ${г.стенд.заведено[1].ms} мс, а ждать осталось ${СРОК - 5000}`);
  assert(г.стенд.снято >= 1, '7e: прежний будильник не снят — их станет по одному на известие');

  // Полный стол будильника не заводит вовсе.
  const полный = стенд({ соседа: true });
  полный.api.следить();
  assert(полный.стенд.заведено.length === 0, '7f: за полным столом заведён будильник пустого');

  // А разбудив — зовёт показ надписи, а не панель бед.
  const з = стенд();
  з.api.следить();
  з.часы.ms += СРОК;
  з.стенд.заведено[0].fn();
  assert(з.api.видна() === true, '7g: будильник прозвонил, а надписи нет');
}

// === 8. Выход из комнаты гасит будильник ===
{
  const выход = extractFunctionSource(source, 'stopOnlineSession');
  assert(/onlineEmptyTableTimer !== null/.test(выход) && /clearTimeout\(onlineEmptyTableTimer\)/.test(выход),
    '8: выход из комнаты не гасит будильник пустого стола');

  const присутствие = extractFunctionSource(source, 'receiveOnlinePresence');
  assert(/следитьЗаПустымСтолом\(\)/.test(присутствие),
    '8b: известие о присутствии больше не заводит будильник — надпись не появится вовсе');

  const меню = extractFunctionSource(source, 'applyOnlineMenuState');
  assert(/обновитьНадписьПустогоСтола\(\)/.test(меню),
    '8c: перерисовка лобби не трогает надпись — она переживёт приход друга');
}

// === 9. Оформление: место вертушки, вид подсказки, дыхание ===
{
  assert(/#modeMenu\.is-table-empty \.mode-menu__waiting-spinner \{ display: none; \}/.test(styles),
    '9: вертушка не прячется — надпись ляжет поверх крутящихся самолётов');

  const правило = /\.lobby-toast\.is-empty-table \{([^}]*)\}/.exec(styles);
  assert(правило, '9b: у надписи нет своего места — она останется под кнопками');
  // Посередине между «WAITING» (кончается на 321) и «Cancel» (начинается на 555), то
  // есть на 438. Привязка за середину: высота коробки зависит от числа строк, и
  // приколотая верхом надпись съезжала бы вниз на каждой лишней.
  const верх = /top:\s*(\d+)px/.exec(правило[1]);
  const середина = (321 + 555) / 2;
  assert(верх && Math.abs(Number(верх[1]) - середина) <= 8,
    `9c: надпись стоит на ${верх?.[1]}px, а середина между «WAITING» и «Cancel» — ${середина}`);
  assert(/transform:\s*translateY\(-50%\)/.test(правило[1]),
    '9c2: надпись приколота верхом, а не серединой — от лишней строки она съедет вниз');

  assert(/\.lobby-toast\.is-empty-table\.is-visible \{\s*animation: lobbyToastBreath/.test(styles),
    '9d: пропало дыхание — экран ожидания замер совсем');
  assert(/@keyframes lobbyToastBreath \{[^}]*opacity: 1[\s\S]*?opacity: 0\.6\d/.test(styles),
    '9e: дыхание не про прозрачность или слишком глубокое — надпись будет мигать, а не дышать');

  // Блоков «не двигать» в файле несколько — ищем во всех.
  const тихо = styles.match(/@media \(prefers-reduced-motion: reduce\) \{[\s\S]*?\n\}/g) || [];
  assert(тихо.some((б) => /is-empty-table\.is-visible \{\s*animation: none/.test(б)),
    '9f: при запрете движения надпись всё равно дышит');
}

console.log('smoke-online-empty-table: OK');
