#!/usr/bin/env node
'use strict';

// Smoke test: пришедшему по ссылке говорят, если за столом никого нет.
//
// Ссылка живёт двенадцать часов, так что открыть её, когда хозяина уже нет, — обычное
// дело, а не редкий случай. До сих пор это выглядело ровно так же, как «друг сейчас
// подойдёт»: экран ожидания, вертушка и больше ничего. Навсегда. Отличить одно от другого
// было нечем, и единственный вывод, который из этого можно сделать, — «игра сломалась».
//
// Поломка тихая вдвойне: ошибки нет, оба конца исправны, просто за столом один человек.
//
// Проверяется три вещи:
//
//   1. Надпись появляется — но не сразу, а пережив мигание связи.
//   2. Она исчезает, как только друг пришёл, и не показывается хозяину: у него на экране
//      «Send link», и чего он ждёт, ему объяснять не надо.
//   3. Будильник. Пустой стол — это не событие, а его отсутствие: без будильника надпись
//      ждала бы следующего события, а за пустым столом не происходит ничего.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const source = fs.readFileSync('script.js', 'utf8');

function extractFunctionSource(text, name){
  const start = text.indexOf(`function ${name}(`);
  if(start === -1) throw new Error(`Не найдена функция ${name}`);
  let глубина = 0;
  let i = text.indexOf('(', start);
  for(; i < text.length; i += 1){
    if(text[i] === '(') глубина += 1;
    if(text[i] === ')'){ глубина -= 1; if(глубина === 0) break; }
  }
  const bodyStart = text.indexOf('{', i);
  let depth = 0;
  for(let j = bodyStart; j < text.length; j += 1){
    if(text[j] === '{') depth += 1;
    if(text[j] === '}') depth -= 1;
    if(depth === 0) return text.slice(start, j + 1);
  }
  throw new Error(`Не найден конец функции ${name}`);
}

const СРОК = Number(/const ONLINE_EMPTY_TABLE_NOTICE_MS = ([\d_]+);/.exec(source)[1].replace(/_/g, ''));

// Стенд: настоящие тексты и сроки, поддельные часы и будильник.
function стенд({ место = 'blue', хозяинСтола = 'green', завёл = false, соседа = false,
  связь = 'online' } = {}){
  const часы = { ms: 1_700_000_000_000 };
  const sandbox = {
    Object, Number, Boolean,
    Date: { now: () => часы.ms },
    часы,
    заведено: [],
    снято: 0,
    показано: 0,
    setTimeout: (fn, ms) => { sandbox.заведено.push({ ms, fn }); return sandbox.заведено.length; },
    clearTimeout: () => { sandbox.снято += 1; },
    gameMode: null,
    onlinePresence: { blue: место === 'blue' || соседа, green: место === 'green' || соседа },
    onlineSession: {
      seat: место,
      // Нажимал ли Online в этой вкладке. Именно это, а не роль за столом, решает, кому
      // надпись нужна: пришедшему по ссылке обещали, что тут кто-то есть.
      host: завёл,
      hostSeat: хозяинСтола,
      aloneSince: null,
      transport: { status: () => связь, rejection: () => null },
    },
    showOnlineTrouble(){ sandbox.показано += 1; },
  };
  vm.createContext(sandbox);
  vm.runInContext([
    `const ONLINE_EMPTY_TABLE_NOTICE_MS = ${СРОК};`,
    'let onlineEmptyTableTimer = null;',
    extractFunctionSource(source, 'isOnlineHost'),
    extractFunctionSource(source, 'isOnlineTableFull'),
    extractFunctionSource(source, 'следитьЗаПустымСтолом'),
    extractFunctionSource(source, 'isOnlineTableEmptyForLong'),
    extractFunctionSource(source, 'getOnlineTroubleText'),
    'this.api = {',
    '  следить: следитьЗаПустымСтолом, текст: getOnlineTroubleText,',
    '  давно: isOnlineTableEmptyForLong,',
    '  одниС: () => onlineSession.aloneSince,',
    '  сел: () => { onlinePresence = { blue: true, green: true }; },',
    '  будильник: () => onlineEmptyTableTimer,',
    '};',
  ].join('\n'), sandbox);
  return { api: sandbox.api, часы, стенд: sandbox };
}

// === 1. ГЛАВНОЕ: надпись появляется, но не раньше срока ===
{
  const г = стенд();
  г.api.следить();
  assert(г.api.текст() === '',
    `1: надпись выскочила сразу («${г.api.текст()}») — она соврёт каждому, у кого друг `
    + 'просто на секунду провалился в лифте');

  г.часы.ms += СРОК - 1;
  assert(г.api.текст() === '', '1b: надпись появилась за миг до срока');

  г.часы.ms += 1;
  const текст = г.api.текст();
  assert(текст.length > 0,
    '1c: за пустым столом так ничего и не сказано — гость по-прежнему не отличает «сейчас '
    + 'подойдёт» от «тут никого»');

  // Сказано должно быть ровно то, чего человеку не хватает: что стол пуст, что ссылка
  // жива и что отсюда есть выход.
  assert(/table/i.test(текст), `1d: в надписи нет речи о столе: «${текст}»`);
  assert(/link/i.test(текст),
    `1e: не сказано, что ссылка ещё жива («${текст}») — человек решит, что она протухла, `
    + 'и попросит новую');
  assert(/Cancel/.test(текст),
    `1f: не названо, чем отсюда выйти («${текст}») — кнопка Cancel рядом, но догадаться `
    + 'о ней неоткуда');

  // Про Reload — отдельно: по этому слову панель показывает кнопку перезагрузки, а
  // перезагрузка здесь не поможет ничем, стол от неё не наполнится.
  assert(!/Reload/.test(текст),
    `1g: в надписи «${текст}» есть слово Reload — панель покажет кнопку перезагрузки, а `
    + 'она тут ни при чём');

  // Язык лобби один — английский; отдельная проверка на это есть в smoke-lobby-english.
  assert(!/[А-Яа-яЁё]/.test(текст), `1h: надпись не на языке лобби: «${текст}»`);
}

// === 2. Пришёл друг — надписи нет ===
//
// Она не должна пережить его приход ни на миг: «тут никого» поверх начавшейся партии
// читается как поломка.
{
  const г = стенд();
  г.api.следить();
  г.часы.ms += СРОК * 2;
  assert(г.api.текст() !== '', '2: подготовка не удалась — надписи нет и до прихода друга');

  г.api.сел();
  assert(г.api.текст() === '', `2b: друг за столом, а надпись осталась: «${г.api.текст()}»`);
  assert(г.api.давно() === false, '2c: стол с двумя игроками всё ещё считается пустым');

  // И отметка одиночества снимается, иначе он уйдёт — и надпись выскочит мгновенно,
  // отсчитав время с прошлого раза.
  г.api.следить();
  assert(г.api.одниС() === null, '2d: отметка одиночества пережила приход друга');
}

// === 3. Нажавшему Online этого не говорят ===
//
// У него на экране «Send link» и зазывание нажать её. Сказать ему «за столом никого» —
// значит объяснить то, что он и так знает, и затереть то, что ему нужно.
//
// Решает именно НАЖАТИЕ, а не роль за столом: ролью комната может наградить и того, кто
// пришёл по ссылке, — а ему-то обещали, что за столом кто-то есть.
{
  const х = стенд({ место: 'green', хозяинСтола: 'green', завёл: true });
  х.api.следить();
  х.часы.ms += СРОК * 2;
  assert(х.api.текст() === '', `3: хозяину сказали, что за столом никого: «${х.api.текст()}»`);
}

// === 4. Беда со связью важнее ===
//
// Оборванная связь — другая беда и другой совет. Сказать «за столом никого», когда мы
// сами отвалились, значило бы послать человека ждать того, кто, может, давно за столом.
{
  const о = стенд({ связь: 'offline' });
  о.api.следить();
  о.часы.ms += СРОК * 2;
  assert(/Connection lost/.test(о.api.текст()),
    `4: при оборванной связи сказано не о ней: «${о.api.текст()}»`);

  const отказ = стенд({ связь: 'rejected' });
  отказ.api.следить();
  отказ.часы.ms += СРОК * 2;
  assert(/Room refused|seat is already taken/i.test(отказ.api.текст()),
    `4b: при отказе комнаты сказано не о нём: «${отказ.api.текст()}»`);
}

// === 5. Будильник ===
//
// Без него надпись ждала бы следующего события — а за пустым столом не происходит
// ничего, в том-то и беда.
{
  const г = стенд();
  г.api.следить();
  assert(г.стенд.заведено.length === 1,
    '5: будильник не заведён — надпись дождётся события, которого не будет');
  assert(г.стенд.заведено[0].ms === СРОК,
    `5b: будильник заведён на ${г.стенд.заведено[0].ms} мс вместо ${СРОК}`);

  // Повторное известие о присутствии не отодвигает срок: иначе каждое мигание соседнего
  // места начинало бы отсчёт заново, и надпись не появилась бы никогда.
  const началС = г.api.одниС();
  г.часы.ms += 5000;
  г.api.следить();
  assert(г.api.одниС() === началС,
    '5c: отсчёт начался заново — при мигающем соседе надпись не появится никогда');
  assert(г.стенд.заведено[1].ms === СРОК - 5000,
    `5d: новый будильник заведён на ${г.стенд.заведено[1].ms} мс, а ждать осталось `
    + `${СРОК - 5000}`);
  assert(г.стенд.снято >= 1, '5e: прежний будильник не снят — их станет по одному на известие');

  // Срок вышел — будить больше некого.
  г.часы.ms += СРОК;
  г.api.следить();
  assert(г.стенд.заведено.length === 2, '5f: после срока заводится лишний будильник');

  // Полный стол будильника не заводит вовсе.
  const полный = стенд({ соседа: true });
  полный.api.следить();
  assert(полный.стенд.заведено.length === 0, '5g: за полным столом заведён будильник пустого');

  // А разбудив — зовёт показ, а не считает что-то про себя.
  const з = стенд();
  з.api.следить();
  з.часы.ms += СРОК;
  з.стенд.заведено[0].fn();
  assert(з.стенд.показано === 1, '5h: будильник прозвонил, а панель не пересобрана');
}

// === 6. Выход из комнаты гасит будильник ===
//
// Иначе он прозвонит уже в меню и покажет надпись про стол, из-за которого мы вышли.
{
  const выход = extractFunctionSource(source, 'stopOnlineSession');
  assert(/onlineEmptyTableTimer !== null/.test(выход) && /clearTimeout\(onlineEmptyTableTimer\)/.test(выход),
    '6: выход из комнаты не гасит будильник пустого стола');

  const присутствие = extractFunctionSource(source, 'receiveOnlinePresence');
  assert(/следитьЗаПустымСтолом\(\)/.test(присутствие),
    '6b: известие о присутствии больше не заводит будильник — надпись не появится вовсе');
}

// === 7. Решает нажатие, а не роль ===
{
  const поСсылкеНоХозяин = стенд({ место: 'green', хозяинСтола: 'green', завёл: false });
  поСсылкеНоХозяин.api.следить();
  поСсылкеНоХозяин.часы.ms += СРОК * 2;
  assert(поСсылкеНоХозяин.api.текст() !== '',
    '7: пришедшему по ссылке не сказали, что за столом никого, — только потому, что '
    + 'комната назвала его хозяином стола. Он об этом не просил и ждёт друга');

  const текст = extractFunctionSource(source, 'getOnlineTroubleText');
  assert(/onlineSession\.host !== true/.test(текст),
    '7b: надпись снова привязана к роли за столом, а не к тому, как человек сюда попал');
}

console.log('smoke-online-empty-table: OK');
