#!/usr/bin/env node
'use strict';

// Smoke test: кнопки в панелях меню стоят в строку, а панель извещений стоит по центру и
// не отбирает нажатия.
//
// Правило раскладки кнопок меню было написано по типу — «#modeMenu button», то есть
// ЛЮБАЯ кнопка внутри меню. А внутри меню живут ещё и панели. Их кнопки должны стоять в
// строку обычным потоком, но position:absolute вынимал их оттуда, и они складывались в
// одну точку: три кнопки тогдашнего лобби рисовались друг на друге, кашей из букв.
//
// Ломается это тихо и заново: достаточно дописать в меню ещё одну панель с кнопкой.
// Поэтому проверяется не «у кнопок панели position: static», а сам корень — что правило
// раскладки адресовано классу кнопок меню, а не всем подряд.
//
// Второе — нажатия. Панель стоит посередине кадра, поверх «Play», которой партия
// начинается. Поймает нажатие — и играть будет нельзя вовсе: кнопка видна, а нажатие
// достаётся панели. Прежде её ради этого держали внизу и считали зазор до кнопки; теперь
// она просто пропускает нажатия сквозь себя, а своё принимает только кнопка внутри.
//
// Панель с тех пор осталась одна. Лобби перестало быть панелью и стало пунктами меню, а
// весь текст к игроку — и про карты, и про оборванную связь — говорит menu-notice.

const fs = require('fs');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const styles = fs.readFileSync('styles.css', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');

// === 1. Раскладка кнопок меню адресована классу, а не всем кнопкам подряд ===
{
  assert(!/(^|\})\s*(\/\*[\s\S]*?\*\/\s*)*#modeMenu button\s*\{/.test(styles),
    '1: правило раскладки снова ловит ВСЕ кнопки меню (#modeMenu button) — кнопки панелей '
    + 'внутри меню опять вылетят из потока и сложатся в одну точку');

  const правило = /#modeMenu \.mode-menu__btn\s*\{([^}]*)\}/.exec(styles);
  assert(правило, '1b: не найдено правило раскладки кнопок меню (#modeMenu .mode-menu__btn)');
  assert(/position:\s*absolute/.test(правило[1]),
    '1c: кнопки меню перестали быть absolute — столбик меню разложится потоком и рассыплется');
}

// === 1d. Кнопки меню все до одной этим классом размечены ===
//
// На этом держится пункт 1: сузили правило до класса — значит без класса кнопка меню
// молча потеряет своё место. Кнопки панелей и те, что позиционируют себя сами, названы
// поимённо, чтобы список не разрастался незаметно.
{
  const САМИ_ПО_СЕБЕ = ['menuSignature', 'swapSidesBtn'];
  const В_ПАНЕЛЯХ = ['mapsErrorNoticeReload', 'onlineAgainYes', 'onlineAgainNo'];

  const меню = /<div id="modeMenu"[\s\S]*?<div id="gsFrame"/.exec(html);
  assert(меню, '1d: разметка меню не найдена');

  const кнопки = меню[0].match(/<button[^>]*>/g) || [];
  assert(кнопки.length >= 12, `1e: в меню найдено всего ${кнопки.length} кнопок — тест ослеп`);

  for(const кнопка of кнопки){
    const id = (/id="([^"]+)"/.exec(кнопка) || [])[1] || '';
    if(САМИ_ПО_СЕБЕ.includes(id) || В_ПАНЕЛЯХ.includes(id)) continue;
    // Целым словом из списка, а не подстрокой: у mode-menu__btn--play дефис — граница
    // слова, и поиск по \bmode-menu__btn\b нашёлся бы прямо в имени модификатора.
    const классы = ((/class="([^"]*)"/.exec(кнопка) || [])[1] || '').split(/\s+/);
    assert(классы.includes('mode-menu__btn'),
      `1f: кнопка меню ${id || кнопка} без класса mode-menu__btn — правило раскладки её не `
      + 'найдёт, и она уедет в поток');
  }
}

// === 2. Кнопки панелей ничем обратно в absolute не загнаны ===
{
  for(const класс of ['menu-notice__btn']){
    const правила = styles.match(new RegExp(`[^{}]*\\.${класс}[^{}]*\\{[^}]*\\}`, 'g')) || [];
    assert(правила.length, `2: не найдено ни одного правила для .${класс}`);
    for(const правило of правила){
      assert(!/position:\s*(absolute|fixed)/.test(правило),
        `2b: .${класс} снова вынут из потока — кнопки панели сложатся друг на друга`);
    }
  }
}

// === 3. Панель стоит по центру и не отбирает нажатия ===
//
// Прежде она была прижата к нижней грани и росла вверх, к «Play», и всё это правило
// считало арифметику «не дотянуться»: дотянувшись, панель забрала бы нажатие, и партию
// стало бы не начать — кнопка видна, а играть нельзя.
//
// Теперь панель говорит тем же, чем говорят подсказки инвентаря, и стоит там, куда
// смотрят, — посередине кадра, поверх «Play». Арифметика зазора больше не нужна, но её
// причина никуда не делась: нажатие по-прежнему должно доставаться кнопке под панелью.
// Поэтому вместо зазора проверяется то, что раньше им обеспечивалось.
{
  const правило = /#menuLayer #modeMenu \.menu-notice\s*\{([^}]*)\}/.exec(styles);
  assert(правило, '3: не найдено правило .menu-notice');
  const блок = правило[1];
  const кнопка = /#menuLayer #modeMenu \.menu-notice__btn\s*\{([^}]*)\}/.exec(styles);
  assert(кнопка, '3b: не найдено правило кнопки панели');

  // Главное: сквозь панель нажимается то, что под ней.
  assert(/pointer-events:\s*none/.test(блок),
    '3c: панель снова ловит нажатия, а стоит она поверх «Play» — кнопка будет видна, '
    + 'а партию не начать');
  assert(/pointer-events:\s*auto/.test(кнопка[1]),
    '3d: кнопка внутри панели тоже не ловит нажатий — она стала картинкой, и вернуть игру '
    + 'в эту вкладку нечем');

  // По центру кадра, и держится за свой центр: высота зависит от числа строк.
  const КАДР = 800;
  const верх = /top:\s*(\d+)px/.exec(блок);
  assert(верх && Number(верх[1]) === КАДР / 2,
    `3e: панель стоит на ${верх ? верх[1] : '?'}, а середина кадра — ${КАДР / 2}`);
  assert(/left:\s*50%/.test(блок), '3f: панель не по центру по горизонтали');
  assert(/transform:\s*translate\(-50%,\s*-50%\)/.test(блок),
    '3g: панель прибита углом к центру — она съедет вправо-вниз на пол-себя, а с каждой '
    + 'новой строкой текста ещё и вниз');

  // Потолок с прокруткой остаётся: расти без предела посреди экрана нельзя.
  const потолок = /max-height:\s*(\d+)px/.exec(блок);
  assert(потолок && Number(потолок[1]) >= 160,
    `3h: потолок ${потолок ? потолок[1] : 'пропал'} ниже того, что панель просит (160) — `
    + 'длинное сообщение начнёт прокручиваться вместе с кнопкой под ним');
  assert(/overflow-y:\s*auto/.test(блок),
    '3i: содержимое выше потолка вылезает наружу, а не прокручивается');

  // И это речь игры, а не браузера: тот же шрифт и та же плашка, что у подсказок.
  assert(/--inventory-tooltip-background/.test(блок) && /--inventory-tooltip-font-family/.test(блок),
    '3j: панель снова оформлена сама по себе — на экране опять появится белая системная '
    + 'коробка среди игровых надписей');
}

console.log('smoke-online-lobby-fits: OK');
