#!/usr/bin/env node
'use strict';

// Smoke test: кнопки лобби стоят в строку, а сама панель не дотягивается до «Play».
//
// Правило раскладки кнопок меню было написано по типу — «#modeMenu button», то есть
// ЛЮБАЯ кнопка внутри меню. А внутри меню живут ещё и панели: лобби онлайна и сообщение
// о непришедших картах. Их кнопки должны стоять в строку обычным потоком, но
// position:absolute вынимал их оттуда, и три кнопки лобби складывались в одну точку:
// «Copy link» поверх «Cancel», «Join» поверх поля ввода. На вид — каша из букв.
//
// Ломается это тихо и заново: достаточно дописать в меню ещё одну панель с кнопкой.
// Поэтому проверяется не «у кнопок лобби position: static», а сам корень — что правило
// раскладки адресовано классу кнопок меню, а не всем подряд.
//
// Второе. Кнопки, вернувшись в поток, заняли в панели место — она подросла на 31 точку и
// начала прокручиваться, срезая нижнюю строку. Потолок пришлось поднять, а он упирается
// в «Play»: панель растёт ВВЕРХ, к той самой кнопке, которой партия начинается. Дотянется
// — и играть будет нельзя вовсе: кнопка видна, а нажатие достаётся панели. Эта арифметика
// тут и считается.

const fs = require('fs');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const styles = fs.readFileSync('styles.css', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');

// === 1. Раскладка кнопок меню адресована классу, а не всем кнопкам подряд ===
{
  assert(!/(^|\})\s*(\/\*[\s\S]*?\*\/\s*)*#modeMenu button\s*\{/.test(styles),
    '1: правило раскладки снова ловит ВСЕ кнопки меню (#modeMenu button) — кнопки панелей '
    + 'внутри меню опять вылетят из потока и сложатся в одну точку');

  const правило = /#modeMenu \.mode-menu__btn\s*\{([^}]*)\}/.exec(styles);
  assert(правило, '1b: не найдено правило раскладки кнопок меню (#modeMenu .mode-menu__btn)');
  assert(/position:\s*absolute/.test(правило[1]),
    '1c: кнопки меню перестали быть absolute — столбик меню разложится потоком и рассыплется');
}

// === 1d. Кнопки меню все до одной этим классом размечены ===
//
// На этом держится пункт 1: сузили правило до класса — значит без класса кнопка меню
// молча потеряет своё место. Кнопки панелей и те, что позиционируют себя сами, названы
// поимённо, чтобы список не разрастался незаметно.
{
  const САМИ_ПО_СЕБЕ = ['menuSignature', 'swapSidesBtn'];
  const В_ПАНЕЛЯХ = ['onlineLobbyCopy', 'onlineLobbyClose', 'onlineLobbyJoin',
    'mapsErrorNoticeReload'];

  const меню = /<div id="modeMenu"[\s\S]*?<div id="gsFrame"/.exec(html);
  assert(меню, '1d: разметка меню не найдена');

  const кнопки = меню[0].match(/<button[^>]*>/g) || [];
  assert(кнопки.length >= 12, `1e: в меню найдено всего ${кнопки.length} кнопок — тест ослеп`);

  for(const кнопка of кнопки){
    const id = (/id="([^"]+)"/.exec(кнопка) || [])[1] || '';
    if(САМИ_ПО_СЕБЕ.includes(id) || В_ПАНЕЛЯХ.includes(id)) continue;
    // Целым словом из списка, а не подстрокой: у mode-menu__btn--play дефис — граница
    // слова, и поиск по \bmode-menu__btn\b нашёлся бы прямо в имени модификатора.
    const классы = ((/class="([^"]*)"/.exec(кнопка) || [])[1] || '').split(/\s+/);
    assert(классы.includes('mode-menu__btn'),
      `1f: кнопка меню ${id || кнопка} без класса mode-menu__btn — правило раскладки её не `
      + 'найдёт, и она уедет в поток');
  }
}

// === 2. Кнопки панелей ничем обратно в absolute не загнаны ===
{
  for(const класс of ['online-lobby__btn', 'menu-notice__btn']){
    const правила = styles.match(new RegExp(`[^{}]*\\.${класс}[^{}]*\\{[^}]*\\}`, 'g')) || [];
    assert(правила.length, `2: не найдено ни одного правила для .${класс}`);
    for(const правило of правила){
      assert(!/position:\s*(absolute|fixed)/.test(правило),
        `2b: .${класс} снова вынут из потока — кнопки панели сложатся друг на друга`);
    }
  }
}

// === 3. Панель не дотягивается до «Play» ===
//
// Панель прижата к нижней грани и растёт вверх, поэтому её верх — это арифметика:
// 800 − отступ снизу − потолок. «Play» кончается на top + height.
{
  const число = (правило, имя) => {
    const блок = new RegExp(`#menuLayer #modeMenu \\.${правило}\\s*\\{([^}]*)\\}`).exec(styles);
    assert(блок, `3: не найдено правило .${правило}`);
    const m = new RegExp(`${имя}:\\s*(\\d+)px`).exec(блок[1]);
    assert(m, `3b: у .${правило} нет ${имя}`);
    return Number(m[1]);
  };

  const КАДР = 800;
  const низПанели = число('online-lobby', 'bottom');
  const потолок = число('online-lobby', 'max-height');
  const низPlay = число('mode-menu__btn--play', 'top') + число('mode-menu__btn--play', 'height');

  const верхПанели = КАДР - низПанели - потолок;
  const зазор = верхПанели - низPlay;
  assert(зазор > 0,
    `3c: панель дотягивается до «Play» (её верх ${верхПанели}, кнопка кончается на ${низPlay}) `
    + '— кнопка будет видна, а нажатие достанется панели, и партию будет не начать');
  assert(зазор >= 12,
    `3d: между панелью и «Play» осталось ${зазор} точек — это уже не зазор, а совпадение`);

  // Обратная сторона: потолок должен быть не ниже того, что панель просит. Содержимое
  // намерено на живом экране — 254 точки в девяти состояниях из десяти. Опустят потолок
  // (например, вернут прежние 232) — панель снова начнёт прокручиваться во всех
  // состояниях, срезая нижнюю строку.
  const НУЖНО = 254;
  assert(потолок >= НУЖНО,
    `3e: потолок ${потолок} ниже того, что панель просит (${НУЖНО}) — она будет `
    + 'прокручиваться в каждом состоянии, и нижняя строка уедет за край');
}

console.log('smoke-online-lobby-fits: OK');
