#!/usr/bin/env node
'use strict';

// Smoke test: полёт выглядит плавным на экране любой частоты.
//
// Шаг симуляции строго 1/60 с, и таким обязан остаться: он сам появился как лекарство от
// того, что траектория зависела от частоты кадров, и один бросок садился у двоих игроков в
// разные точки. Но экран в 120 или 144 Гц рисует кадров БОЛЬШЕ, чем есть шагов, и лишние
// кадры показывают ровно ту же картинку. Замер в браузере, 40 кадров подряд, шаг 6.618 px:
//
//              было (сырое положение)        стало (сглаженное)
//    60 Гц      0 кадров без движения         0, шаг те же 6.62 px
//   120 Гц     20 кадров без движения из 40   0, шаг ровный 3.31 px
//   144 Гц     24 кадра без движения из 40    0, шаг 1.65–2.76 px
//
// То есть на 120 Гц самолёт стоял каждый второй кадр, а на 144 — почти два кадра из трёх.
// Физика при этом идеально ровная: рывки были чисто в показе, и потому одинаково видны и в
// вертикальном поле, и в горизонтальном.
//
// Лечится отрисовкой, а не шагом: самолёт рисуется МЕЖДУ двумя последними просчитанными
// положениями, по доле недосчитанного времени. Симуляция не трогается совсем.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

function extractFn(source, name){
  const at = source.indexOf(`function ${name}(`);
  if(at === -1) throw new Error(`не найдено: ${name}`);
  const open = source.indexOf('{', source.indexOf(')', at));
  let depth = 0;
  for(let i = open; i < source.length; i += 1){
    if(source[i] === '{') depth += 1;
    if(source[i] === '}'){ depth -= 1; if(depth === 0) return source.slice(at, i + 1); }
  }
  throw new Error(`не закрыто: ${name}`);
}

const source = fs.readFileSync('script.js', 'utf8');
const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/.*$/gm, '');

// Стенд: настоящие накопитель, разбивка кадра на шаги и сглаживание. Подставной только сам
// шаг полёта — и он нарочно повторяет порядок настоящего: отметка для отрисовки снимается
// ДО движения, а p.prevX обновляется ПОСЛЕ (там он нужен проверкам попаданий по отрезку).
const ШАГ_PX = 6.618;
const sandbox = { Number, Math, simulationStepAccumulator: 0, flyingPoints: [], plane: null };
vm.createContext(sandbox);
vm.runInContext([
  source.match(/const SIMULATION_STEP_SEC = [^;]+;/)[0],
  source.match(/const SIMULATION_MAX_STEPS_PER_FRAME = [^;]+;/)[0],
  extractFn(source, 'getRenderInterpolationAlpha'),
  extractFn(source, 'getPlaneRenderPosition'),
  extractFn(source, 'runSimulationSteps'),
  `const ШАГ_PX = ${ШАГ_PX};`,
  'plane = { x: 180, y: 500, prevX: 180, prevY: 500, renderPrevX: 180, renderPrevY: 500 };',
  'flyingPoints = [{ plane }];',
  'function stepSimulation(){',
  '  plane.renderPrevX = plane.x; plane.renderPrevY = plane.y;',
  '  plane.y -= ШАГ_PX;',
  '  plane.prevX = plane.x; plane.prevY = plane.y;',
  '}',
  'this.STEP_SEC = SIMULATION_STEP_SEC;',
  'this.полёт = (кадрСек, кадров) => {',
  '  simulationStepAccumulator = 0;',
  '  plane.x = 180; plane.y = 500;',
  '  plane.prevX = 180; plane.prevY = 500;',
  '  plane.renderPrevX = 180; plane.renderPrevY = 500;',
  '  const сырое = [], сглаженное = [], между = [];',
  '  let прошлоеСырое = plane.y, прошлоеСглаж = plane.y;',
  '  for(let i = 0; i < кадров; i += 1){',
  '    runSimulationSteps(кадрСек, 0);',
  '    сырое.push(Math.abs(plane.y - прошлоеСырое)); прошлоеСырое = plane.y;',
  '    const где = getPlaneRenderPosition(plane);',
  '    сглаженное.push(Math.abs(где.y - прошлоеСглаж)); прошлоеСглаж = где.y;',
  '    между.push(Math.abs(где.y - plane.renderPrevY) <= Math.abs(plane.y - plane.renderPrevY) + 1e-9);',
  '  }',
  '  return { сырое, сглаженное, между }; };',
  'this.альфаПри = (остаток) => { simulationStepAccumulator = остаток;',
  '  return getRenderInterpolationAlpha(); };',
].join('\n'), sandbox);

const БЕЗ_ДВИЖЕНИЯ = (шаги) => шаги.filter((v) => v < 0.001).length;

// Первый кадр честно стоит на месте: шаг ещё не просчитан, и рисовать самолёт где-то
// впереди значило бы гадать о будущем. Считаем всё, что после него.
const ПОСЛЕ_РАЗГОНА = 2;

// === 1. ГЛАВНОЕ: на частом экране кадры перестали повторяться ===
{
  for(const [имя, кадрСек, ожидалосьБыло] of [['120 Гц', 1 / 120, 15], ['144 Гц', 1 / 144, 18]]){
    const { сырое, сглаженное } = sandbox.полёт(кадрСек, 40);

    const было = БЕЗ_ДВИЖЕНИЯ(сырое.slice(ПОСЛЕ_РАЗГОНА));
    assert(было >= ожидалосьБыло,
      `1: стенд перестал воспроизводить саму беду — на ${имя} сырых кадров без движения `
      + `${было}, а их должно быть около половины. Проверка ничего не сторожит`);

    const стало = БЕЗ_ДВИЖЕНИЯ(сглаженное.slice(ПОСЛЕ_РАЗГОНА));
    assert(стало === 0,
      `1b: на ${имя} ${стало} кадров из ${40 - ПОСЛЕ_РАЗГОНА} рисуют то же самое, что и `
      + 'предыдущий. Это и есть рывки: физика ровная, а глаз видит дёрганье');
  }
}

// === 2. Шаг на экране стал РОВНЫМ, а не просто ненулевым ===
//
// Без этого пункт 1 прошёл бы и на «0.001 px и 6.6 px через кадр» — то есть на тех же
// рывках, только формально без остановок.
{
  const { сглаженное } = sandbox.полёт(1 / 120, 40);
  const шаги = сглаженное.slice(ПОСЛЕ_РАЗГОНА);
  const мин = Math.min(...шаги);
  const макс = Math.max(...шаги);
  assert(макс - мин < 1e-6,
    `2: на 120 Гц смещение всё ещё скачет от ${мин.toFixed(2)} до ${макс.toFixed(2)} px`);
  assert(Math.abs(макс - ШАГ_PX / 2) < 1e-6,
    `2b: на вдвое частом экране кадр обязан двигать самолёт на половину шага `
    + `(${(ШАГ_PX / 2).toFixed(3)} px), а двигает на ${макс.toFixed(3)}`);
}

// === 3. На 60 Гц не изменилось ничего ===
//
// Игра, в которую уже играли, обязана остаться прежней.
{
  const { сырое, сглаженное } = sandbox.полёт(sandbox.STEP_SEC, 40);
  for(let i = ПОСЛЕ_РАЗГОНА; i < 40; i += 1){
    assert(Math.abs(сглаженное[i] - сырое[i]) < 1e-9,
      `3: на 60 Гц кадр ${i} стал двигать самолёт на ${сглаженное[i].toFixed(3)} px вместо `
      + `${сырое[i].toFixed(3)} — сглаживание влезло туда, где сглаживать нечего`);
  }
}

// === 4. Рисуем МЕЖДУ шагами, а не дальше последнего ===
//
// Отставание на неполный шаг (16 мс) глазу незаметно. Выход вперёд — это догадка о ещё не
// просчитанном будущем, и самолёт дёргался бы назад каждый раз, когда догадка не сходится.
{
  for(const кадрСек of [1 / 60, 1 / 120, 1 / 144, 1 / 30]){
    const { между } = sandbox.полёт(кадрСек, 40);
    assert(между.every(Boolean),
      `4: при кадре ${(кадрСек * 1000).toFixed(1)} мс самолёт нарисован дальше последнего `
      + 'просчитанного шага — это уже не сглаживание, а предсказание');
  }
  assert(sandbox.альфаПри(sandbox.STEP_SEC * 12) === 1,
    '4b: доля недосчитанного времени не прижата к единице — на просевшем кадре самолёт '
    + 'улетит вперёд симуляции');
  assert(sandbox.альфаПри(-1) === 0, '4c: отрицательный остаток отбрасывает самолёт назад');
  assert(sandbox.альфаПри(NaN) === 0, '4d: пустой остаток даёт NaN вместо положения');
}

// === 5. Отметка для отрисовки — СВОЯ, и снимается ДО шага ===
//
// Ровно на этом сглаживание один раз уже не сработало: p.prevX нарочно обновляется в самом
// конце шага, после проверок попаданий (иначе они считают попадание по точке и мина в 20 px
// перепрыгивается). К моменту отрисовки p.prevX равен текущему положению, и «интерполяция»
// между ними — тождество.
{
  const step = extractFn(source, 'stepSimulation');
  const отметка = step.indexOf('p.renderPrevX = prevX;');
  const конецШага = step.indexOf('p.prevX = p.x;');
  assert(отметка > 0, '5: в шаге симуляции не снимается отметка положения для отрисовки');
  assert(конецШага > 0, '5b: проверка устарела: p.prevX больше не обновляется в шаге');
  assert(отметка < конецШага,
    '5c: отметка для отрисовки снимается не раньше конца шага — значит она снята уже после '
    + 'движения и рисовать между ней и текущим местом нечего');

  const движение = step.indexOf('resolveFlightSurfaceCollision(fp, prevX, prevY, deltaSec);');
  assert(движение > 0, '5d: проверка устарела: шаг двигает самолёт как-то иначе');
  assert(отметка < движение,
    '5e: отметка снимается после того, как самолёт уже сдвинулся');

  const рисовать = extractFn(source, 'getPlaneRenderPosition');
  assert(/plane\.renderPrevX/.test(рисовать) && !/plane\.prevX/.test(рисовать),
    '5f: отрисовка снова смотрит на p.prevX — а он к этому моменту равен текущему положению');
}

// === 6. Симуляция о сглаживании не знает ===
//
// Иначе оно перестало бы быть чисто показом: партия начала бы зависеть от того, с какой
// частотой обновляется экран у игрока, — то самое, от чего и лечил постоянный шаг.
{
  const step = extractFn(source, 'stepSimulation');
  for(const name of ['getPlaneRenderPosition', 'getRenderInterpolationAlpha']){
    assert(!step.includes(name),
      `6: шаг симуляции зовёт ${name} — положение для показа потекло обратно в физику`);
  }

  const рисовать = extractFn(source, 'getPlaneRenderPosition');
  assert(!/plane\.\w+\s*=[^=]/.test(рисовать),
    '6b: вычисление места для отрисовки пишет в самолёт — это уже не показ');

  assert(/const SIMULATION_STEP_SEC = 1 ?\/ ?60;/.test(code),
    '6c: постоянный шаг симуляции исчез — а сглаживание задумано как замена только показу, '
    + 'но не ему');
}

// === 7. Всё, что движется вместе с самолётом, движется по той же точке ===
//
// След строится по просчитанным шагам и кончается на шаг впереди нарисованного самолёта.
// Оставить как есть — значит получить хвост, торчащий из носа на 6.6 px.
{
  const draw = extractFn(source, 'drawThinPlane');
  assert(/const \{ x: cx, y: cy \} = getPlaneRenderPosition\(plane\);/.test(draw),
    '7: самолёт снова рисуется по просчитанному положению, мимо сглаживания');

  const рисуемВсё = extractFn(source, 'drawPlanesAndTrajectories');
  assert(/const tip = getPlaneRenderPosition\(plane\);/.test(рисуемВсё),
    '7b: след больше не знает, где нарисован самолёт');
  assert(/if\(i === lastIndex\) ctx\.lineTo\(tip\.x, tip\.y\);/.test(рисуемВсё),
    '7c: последний отрезок следа снова кончается в конце просчитанного шага, а не там, где '
    + 'нарисован самолёт — хвост будет торчать из носа');
}

console.log('smoke-smooth-flight-rendering: OK');
