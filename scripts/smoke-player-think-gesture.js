#!/usr/bin/env node
'use strict';

// Smoke test: жест задумчивости живого игрока.
//
// Копыто у ИИ было и раньше. Здесь то же копыто, но правило другое, и разница как раз
// в том, что легко потерять:
//
//   у ИИ           одноразовый жест: окно раздумий кончается само, когда он целится
//   у игрока       повторяющийся: человек может думать сколько угодно
//
// Отсюда четыре места, где это ломается молча, и все четыре тест держит.
//
// 1. sync() зовётся ИЗ ОТРИСОВКИ, то есть по многу раз в секунду. Если он будет
//    заводить отсчёт заново на каждом вызове, копыто не вылезет никогда: отсчёт просто
//    не доживёт до конца. Проверка «ход тот же — отсчёт не трогаем» тут главная.
//
// 2. Отсчёт заводится заново ПОСЛЕ жеста. Скопировать одноразовость ИИ — значит
//    показать копыто один раз за ход и замолчать.
//
// 3. Считается бездействие, а не время хода: нажатие сбрасывает отсчёт. Иначе копыто
//    вылезет посреди затянувшегося прицеливания, когда игрок как раз занят.
//
// 4. Угол берётся по КРАЮ, а не по цвету. Морда переезжает вместе со своей половиной
//    поля, и жест обязан ехать за ней — ровно те же грабли, на которых уже стояла
//    полоса инвентаря.
//
// И пятое, появившееся вместе с наклоном козла внизу: угол наклона морды и разворот её
// копыта считаются от ОДНОГО числа. Разъедутся — копыто сожмётся мимо бороды, и увидеть
// это можно только перевернув доску и просидев над ходом десять секунд.
//
// И отдельно: на ходу ИИ жеста быть не должно вовсе — у компьютера своё копыто, и два
// сразу означали бы, что игроку показывают чужие раздумья.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const source = fs.readFileSync('script.js', 'utf8');
const styles = fs.readFileSync('styles.css', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');

function кусок(начало){
  const at = source.indexOf(начало);
  assert(at !== -1, `не найдено: ${начало}`);
  const open = source.indexOf('{', at);
  let depth = 0;
  for(let i = open; i < source.length; i += 1){
    if(source[i] === '{') depth += 1;
    if(source[i] === '}'){
      depth -= 1;
      if(depth === 0) return source.slice(at, source.indexOf(';', i) + 1);
    }
  }
  throw new Error(`не закрыто: ${начало}`);
}

// === Стенд: поддельный узел, поддельные часы ===
function стенд({ локальные = ['blue', 'green'], край = (c) => c, экран = true } = {}){
  const классы = new Set();
  let слушатель = null;
  const node = {
    className: '',
    classList: {
      add: (...c) => c.forEach((x) => классы.add(x)),
      remove: (...c) => c.forEach((x) => классы.delete(x)),
      contains: (c) => классы.has(c),
      toggle: (c, on) => { if(on) классы.add(c); else классы.delete(c); },
    },
    addEventListener: (тип, fn) => { if(тип === 'animationend') слушатель = fn; },
  };

  let времени = 0;
  const таймеры = new Map();
  let следующий = 1;

  const sandbox = {
    document: {
      getElementById: (id) => (id === 'playerThinkHoof' ? node : null),
      body: { classList: { contains: (c) => (c === 'screen--game' ? экран : false) } },
      addEventListener: () => {},
    },
    getHudEdgeSeat: (c) => край(c),
    isLocalColor: (c) => локальные.includes(c),
    setTimeout: (fn, ms) => { const id = следующий++; таймеры.set(id, { fn, при: времени + ms }); return id; },
    clearTimeout: (id) => { таймеры.delete(id); },
    console,
  };
  vm.createContext(sandbox);
  const порогСтрока = /^let (PLAYER_THINK_GESTURE_IDLE_MS = \d+);$/m.exec(source);
  assert(порогСтрока, 'не найдено объявление PLAYER_THINK_GESTURE_IDLE_MS');
  vm.runInContext([
    `var ${порогСтрока[1]};`,
    кусок('const GESTURE_PHASE_BY_KEYFRAMES = Object.freeze(').replace(/^const /, 'var '),
    кусок('const playerThinkGesture = (() =>').replace(/^const /, 'var '),
  ].join('\n'), sandbox);

  return {
    жест: sandbox.playerThinkGesture,
    порог: sandbox.PLAYER_THINK_GESTURE_IDLE_MS,
    классы,
    // Класс угла (is-north / is-south) остаётся на узле и после жеста — это место, а не
    // фаза. Поэтому «копыта нет» проверяется по фазовым классам, а не по пустоте.
    фаза: () => ['is-entering', 'is-fidgeting', 'is-leaving'].find((c) => классы.has(c)) || null,
    // Проматываем часы и выполняем всё, что успело сработать.
    ждать(ms){
      времени += ms;
      let сработало = 0;
      for(let шаг = 0; шаг < 50; шаг += 1){
        const готов = [...таймеры.entries()].find(([, t]) => t.при <= времени);
        if(!готов) break;
        таймеры.delete(готов[0]);
        готов[1].fn();
        сработало += 1;
      }
      return сработало;
    },
    // Кадры сами не играют — доигрываем их руками, как это делает браузер.
    доиграть(набор = ['aiHoofSlideIn', 'aiHoofFidgetOpen', 'aiHoofSlideOut']){
      assert(слушатель, 'на копыто не повесили обработчик animationend');
      for(const имя of набор) слушатель({ animationName: имя });
    },
    ждётТаймер: () => таймеры.size > 0,
  };
}

const ПОРОГ = стенд().порог;
assert(Number.isFinite(ПОРОГ) && ПОРОГ >= 3000 && ПОРОГ <= 60000,
  `0: порог бездействия ${ПОРОГ}мс — либо копыто полезет на каждый чих, либо не полезет никогда`);

// === 1. ГЛАВНОЕ: отрисовка зовёт sync постоянно, и это не должно мешать отсчёту ===
{
  const с = стенд();
  с.жест.sync('blue');
  // Ход тот же, кадров много: так это и работает в игре.
  for(let i = 0; i < 200; i += 1){
    с.ждать(ПОРОГ / 100);
    с.жест.sync('blue');
  }
  assert(с.фаза(),
    '1: копыто не вылезло за два порога, хотя игрок бездействовал. sync() зовётся из '
    + 'отрисовки много раз в секунду — значит он заводит отсчёт заново на каждом кадре, '
    + 'и тот никогда не доживает до конца');
}

// === 2. Ход ИИ жеста не получает ===
//
// У компьютера своё копыто и своё правило. Два сразу — это чужие раздумья на своей морде.
{
  const с = стенд({ локальные: ['green'] });
  с.жест.sync('blue');
  с.ждать(ПОРОГ * 3);
  assert(!с.фаза(),
    `2: на ходу ИИ вылез жест игрока (${[...с.классы].join(' ')})`);
  assert(!с.ждётТаймер(), '2b: на ходу ИИ остался заведённый отсчёт');
}

// === 3. Жест ПОВТОРЯЕТСЯ ===
{
  const с = стенд();
  с.жест.sync('blue');
  с.ждать(ПОРОГ + 1);
  assert(с.классы.has('is-entering'), '3: первый жест не начался');
  с.доиграть();
  assert(!с.фаза(), `3b: после ухода копыто осталось на экране (${с.фаза()})`);
  assert(с.ждётТаймер(), '3c: после жеста отсчёт не заведён заново — копыто покажется '
    + 'один раз за ход и замолчит, а человек думает сколько угодно');
  с.ждать(ПОРОГ + 1);
  assert(с.классы.has('is-entering'), '3d: второго жеста не было');
}

// === 4. Нажатие сбрасывает отсчёт ===
{
  const с = стенд();
  с.жест.sync('blue');
  // Игрок тыкает каждые полпорога — жест не должен появиться никогда.
  for(let i = 0; i < 10; i += 1){
    с.ждать(ПОРОГ * 0.5);
    с.жест.poke();
  }
  assert(!с.фаза(),
    '4: копыто вылезло, хотя игрок всё время что-то нажимал — считается время хода, '
    + 'а должно бездействие');
  // А если перестал — вылезает.
  с.ждать(ПОРОГ + 1);
  assert(с.классы.has('is-entering'), '4b: после того как игрок затих, жеста не дождались');
}

// === 5. Угол берётся по КРАЮ, а не по цвету ===
{
  const обычный = стенд({ край: (c) => c });                       // синий сверху
  обычный.жест.sync('blue');
  обычный.ждать(ПОРОГ + 1);
  assert(обычный.классы.has('is-north'),
    '5: на обычном крае синий сидит сверху, а жест ушёл вниз');

  const перевёрнутый = стенд({ край: (c) => (c === 'blue' ? 'green' : 'blue') });
  перевёрнутый.жест.sync('blue');
  перевёрнутый.ждать(ПОРОГ + 1);
  assert(перевёрнутый.классы.has('is-south'),
    '5b: при своём крае снизу синий сидит внизу, а жест остался наверху — морда уехала, '
    + 'а копыто нет');

  const зелёный = стенд({ край: (c) => c });
  зелёный.жест.sync('green');
  зелёный.ждать(ПОРОГ + 1);
  assert(зелёный.классы.has('is-south'), '5c: зелёный сидит снизу, а жест ушёл наверх');
}

// === 6. Вне игрового экрана жеста нет ===
{
  const с = стенд({ экран: false });
  с.жест.sync('blue');
  с.ждать(ПОРОГ * 2);
  assert(!с.фаза(), '6: копыто вылезло в меню');
}

// === 7. Разметка и стили ===
//
// Маршрутизатор фаз переключается по ИМЕНИ кадров. Имя, которого нет в стилях, — это
// жест, замерший на первой фазе навсегда: браузер просто не пришлёт animationend,
// который ждут. В обратную сторону так же: кадры, которых нет в таблице, не переключат
// фазу. Обе стороны и проверяются.
{
  const таблица = кусок('const GESTURE_PHASE_BY_KEYFRAMES = Object.freeze(');
  const имена = [...таблица.matchAll(/^\s*(\w+):\s*"(entering|fidgeting|leaving)"/gm)]
    .map((m) => [m[1], m[2]]);
  assert(имена.length >= 3 && имена.length % 3 === 0,
    `7: в таблице фаз ${имена.length} имён — набор состоит из трёх фаз, целыми наборами`);

  for(const [имя] of имена){
    assert(new RegExp(`@keyframes ${имя}\\b`).test(styles),
      `7b: в стилях нет кадров ${имя}, а маршрутизатор фаз ждёт именно это имя`);
  }

  // Каждый набор обязан быть полным: без «leaving» жест не уйдёт с экрана и не заведёт
  // отсчёт заново, без «fidgeting» замрёт на въезде.
  for(const набор of [['aiHoofSlideIn', 'aiHoofFidgetOpen', 'aiHoofSlideOut']]){
    const фазы = набор.map((имя) => (имена.find(([n]) => n === имя) || [])[1]);
    assert(фазы.join(',') === 'entering,fidgeting,leaving',
      `7c: набор ${набор.join('/')} расписан по фазам как ${фазы.join(',')} — жест застрянет`);
  }

  // Кадры, которые правило вешает на САМО копыто, обязаны быть в таблице: иначе фаза
  // отыграет, а переключить её будет некому. И наоборот — кадры на кадрах копыта
  // (мигание сжато/раскрыто) в таблице быть НЕ должны: они короче и отыгрывают по
  // нескольку раз, и фаза переключилась бы посреди жеста.
  const правила = [...styles.matchAll(/(#playerThinkHoof[^{]*)\{([^}]*)\}/g)];
  for(const [, селектор, тело] of правила){
    const кадры = /animation:\s*(\w+)/.exec(тело);
    if(!кадры) continue;
    const наСамомКопыте = !селектор.includes('.ai-think-hoof__frame');
    const вТаблице = имена.some(([n]) => n === кадры[1]);
    assert(наСамомКопыте === вТаблице,
      наСамомКопыте
        ? `7d: правило «${селектор.trim()}» включает кадры ${кадры[1]}, но маршрутизатор про `
          + 'них не знает — фаза не переключится'
        : `7d2: кадры ${кадры[1]} играют на кадрах копыта, а маршрутизатор считает их фазой — `
          + 'жест оборвётся посреди себя');
  }

  // Общие правила написаны на классе: без него у копыта игрока не будет ни кадров,
  // ни фаз — оно останется невидимым навсегда.
  for(const id of ['aiThinkHoof', 'playerThinkHoof']){
    assert(new RegExp(`id="${id}"[^>]*class="[^"]*\\bthink-hoof\\b`).test(html),
      `7e: у #${id} нет класса think-hoof — общие правила копыта мимо него`);
  }
  assert(/\.think-hoof\.is-entering\s*\{/.test(styles) && /\.think-hoof\.is-fidgeting\s*\{/.test(styles)
    && /\.think-hoof\.is-leaving\s*\{/.test(styles),
    '7f: фазы копыта снова описаны по id — второе копыто останется без анимаций');
  // Места разные: одно копыто у морды ИИ, второе переезжает между углами.
  assert(/#playerThinkHoof\.is-north\s*\{/.test(styles) && /#playerThinkHoof\.is-south\s*\{/.test(styles),
    '7g: у копыта игрока нет правил на оба угла');
}

// === 8. Особое место копыта достаётся ровно козлу внизу ===
//
// Козёл — синий, и внизу он оказывается только при перевёрнутой доске. Там морда
// наклонена, и копыто должно стоять у наклонённой бороды. Воробью и козлу наверху это
// место не годится: у них борода на своих местах.
{
  const где = (цвет, край) => {
    const с = стенд({ край });
    с.жест.sync(цвет);
    с.ждать(ПОРОГ + 1);
    return с.классы;
  };
  const прямо = (c) => c;
  const наоборот = (c) => (c === 'blue' ? 'green' : 'blue');

  assert(где('blue', наоборот).has('is-goat-south'),
    '8: козёл внизу не получил своего места для копыта');
  assert(!где('blue', прямо).has('is-goat-south'),
    '8b: козлу наверху досталось место для нижнего угла — там борода не наклонена');
  assert(!где('green', прямо).has('is-goat-south'),
    '8c: воробей внизу получил место у козлиной бороды');
  assert(!где('green', наоборот).has('is-goat-south'),
    '8d: воробей наверху получил чужое место');
}

// === 9. ГЛАВНОЕ ПРО НАКЛОН: морда и копыто считаются от одного числа ===
//
// Наклон козла внизу и разворот его копыта — это один и тот же угол. Записать его
// дважды значит однажды поправить одно и забыть второе: копыто сожмётся мимо бороды,
// а увидеть это можно только перевернув доску и просидев над ходом десять секунд.
{
  const тело = (селектор) => {
    const m = new RegExp(`^${селектор.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\{([^}]*)\\}`, 'm')
      .exec(styles);
    assert(m, `9: в стилях нет правила ${селектор}`);
    return m[1];
  };

  assert(/--goat-south-tilt:\s*-?[\d.]+deg/.test(styles),
    '9: угол наклона козла внизу больше не задан одним именем');

  const морда = тело('html.is-board-flipped #mantisIndicator');
  assert(/--tilt:\s*var\(--goat-south-tilt\)/.test(морда),
    '9b: морда козла внизу наклоняется своим числом, мимо общего');

  const копыто = тело('#playerThinkHoof.is-south.is-goat-south');
  assert(/--hoof-rot:\s*var\(--goat-south-tilt\)/.test(копыто),
    '9c: копыто у козла внизу разворачивается своим числом — разойдётся с наклоном морды');

  const копытоГориз = тело('html.is-board-landscape #playerThinkHoof.is-south.is-goat-south');
  assert(/--hoof-rot:\s*calc\(-90deg \+ var\(--goat-south-tilt\)\)/.test(копытоГориз),
    '9d: в горизонтали разворот копыта не складывается из встречных -90° и общего наклона');

  // Число живёт в одном месте: градусы в самих правилах — это и есть разъезд.
  for(const [имя, т] of [['морды', морда], ['копыта', копыто], ['копыта в горизонтали', копытоГориз]]){
    assert(!/-?\d+deg/.test(т.replace(/calc\(-90deg/g, 'calc(')),
      `9e: в правиле ${имя} снова стоят градусы числом, а не общим именем`);
  }
}

// === 10. Наклон крутит морду вокруг ГОЛОВЫ и стоит в цепочке на своём месте ===
//
// Окно морды в портрете высотой в пол-кадра: поворот вокруг его центра унёс бы голову
// за грань. И место наклона в цепочке не случайно — он стоит ПОСЛЕ разворота ориентации
// и ДО отражения, то есть считается в экранных осях. Иначе одно число не работало бы в
// обеих ориентациях, и понадобился бы отдельный угол для горизонтали.
{
  const общее = /^\.turn-indicator\s*\{([^}]*)\}/m.exec(styles);
  assert(общее, '10: не найдено общее правило морд');
  assert(/rotate\(var\(--turn\)\)\s*\n?\s*translate\(var\(--tilt-x\), var\(--tilt-y\)\) rotate\(var\(--tilt\)\)/
    .test(общее[1]),
    '10b: наклон уехал из своего места в цепочке — он обязан стоять сразу после разворота '
    + 'ориентации, иначе угол перестанет быть экранным');
  assert(/rotate\(var\(--tilt\)\)\s*\n?\s*translate\(calc\(-1 \* var\(--tilt-x\)\), calc\(-1 \* var\(--tilt-y\)\)\)/
    .test(общее[1]),
    '10c: центр вращения не возвращается назад — морда уедет с места');
  assert(/--tilt:\s*0deg/.test(общее[1]) && /--tilt-x:\s*0px/.test(общее[1]),
    '10d: по умолчанию наклона быть не должно — три морды из четырёх стоят прямо');

  // Смещение центра вращения задано в ОБЕИХ ориентациях: окна разной высоты, и
  // расстояние от центра окна до головы у них разное.
  const портрет = /^html\.is-board-flipped #mantisIndicator\s*\{([^}]*)\}/m.exec(styles)[1];
  const гориз = /^html\.is-board-flipped\.is-board-landscape #mantisIndicator\s*\{([^}]*)\}/m.exec(styles)[1];
  const y = (т) => { const m = /--tilt-y:\s*(-?[\d.]+)px/.exec(т); return m ? Number(m[1]) : null; };
  assert(y(портрет) !== null && y(гориз) !== null,
    '10e: центр наклона задан не в обеих ориентациях — в одной из них морда крутится '
    + 'вокруг центра окна и уезжает за грань');
  assert(y(портрет) !== y(гориз),
    `10f: центр наклона одинаков (${y(портрет)}) в обеих ориентациях, хотя окна разной `
    + 'высоты — где-то он посчитан не от головы');

  // И этого мало: центр обязан лежать В ГОЛОВЕ, иначе морда не наклонится, а уедет.
  // Голова козла внизу занимает в портретном окне (400 точек) нижние 309..400, а в
  // горизонтальном (104 точки) — 13..104; центры самих окон — 200 и 52.
  for(const [имя, сдвиг, центр, от, до] of [['портрет', y(портрет), 200, 309, 400],
                                             ['горизонталь', y(гориз), 52, 13, 104]]){
    const где = центр + сдвиг;
    assert(где >= от && где <= до,
      `10g: в ${имя} морда крутится вокруг ${где}, а голова лежит в ${от}..${до} — она не `
      + 'наклонится, а уедет с места');
  }
}

// === 11. Жест остался ОДИН ===
//
// Наклон затевался ровно ради этого: чтобы у козла внизу работал тот же жест, а не
// заводился свой набор кадров. Своя анимация в правилах места — это второй жест
// чёрным ходом.
{
  for(const селектор of ['#playerThinkHoof\\.is-south\\.is-goat-south',
                          'html\\.is-board-landscape #playerThinkHoof\\.is-south\\.is-goat-south']){
    const m = new RegExp(`^${селектор}\\s*\\{([^}]*)\\}`, 'm').exec(styles);
    assert(m, `11: не найдено правило ${селектор}`);
    assert(!/animation/.test(m[1]),
      `11b: у козла внизу завелись свои кадры (${селектор}) — жест должен остаться прежним`);
  }
  const наборы = new Set([...styles.matchAll(/@keyframes (\w*[Hh]oof\w*|\w*[Cc]omb\w*)/g)].map((m) => m[1]));
  assert(наборы.size === 4,
    `11c: наборов кадров копыта стало ${наборы.size} вместо четырёх (въезд, два мигания, `
    + `уход): ${[...наборы].join(', ')}. Лишний набор — это второй жест чёрным ходом`);
}

