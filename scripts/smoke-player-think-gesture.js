#!/usr/bin/env node
'use strict';

// Smoke test: жест задумчивости живого игрока.
//
// Копыто у ИИ было и раньше. Здесь то же копыто, но правило другое, и разница как раз
// в том, что легко потерять:
//
//   у ИИ           одноразовый жест: окно раздумий кончается само, когда он целится
//   у игрока       повторяющийся: человек может думать сколько угодно
//
// Отсюда четыре места, где это ломается молча, и все четыре тест держит.
//
// 1. sync() зовётся ИЗ ОТРИСОВКИ, то есть по многу раз в секунду. Если он будет
//    заводить отсчёт заново на каждом вызове, копыто не вылезет никогда: отсчёт просто
//    не доживёт до конца. Проверка «ход тот же — отсчёт не трогаем» тут главная.
//
// 2. Отсчёт заводится заново ПОСЛЕ жеста. Скопировать одноразовость ИИ — значит
//    показать копыто один раз за ход и замолчать.
//
// 3. Считается бездействие, а не время хода: нажатие сбрасывает отсчёт. Иначе копыто
//    вылезет посреди затянувшегося прицеливания, когда игрок как раз занят.
//
// 4. Угол берётся по КРАЮ, а не по цвету. Морда переезжает вместе со своей половиной
//    поля, и жест обязан ехать за ней — ровно те же грабли, на которых уже стояла
//    полоса инвентаря.
//
// И отдельно: на ходу ИИ жеста быть не должно вовсе — у компьютера своё копыто, и два
// сразу означали бы, что игроку показывают чужие раздумья.

const fs = require('fs');
const vm = require('vm');
const { читатьАльфу, полосы } = require('./sprite-alpha-utils.js');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const source = fs.readFileSync('script.js', 'utf8');
const styles = fs.readFileSync('styles.css', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');

function кусок(начало){
  const at = source.indexOf(начало);
  assert(at !== -1, `не найдено: ${начало}`);
  const open = source.indexOf('{', at);
  let depth = 0;
  for(let i = open; i < source.length; i += 1){
    if(source[i] === '{') depth += 1;
    if(source[i] === '}'){
      depth -= 1;
      if(depth === 0) return source.slice(at, source.indexOf(';', i) + 1);
    }
  }
  throw new Error(`не закрыто: ${начало}`);
}

// === Стенд: поддельный узел, поддельные часы ===
function стенд({ локальные = ['blue', 'green'], край = (c) => c, экран = true } = {}){
  let слушатель = null;
  function узел(){
    const набор = new Set();
    return {
      набор,
      className: '',
      classList: {
        add: (...c) => c.forEach((x) => набор.add(x)),
        remove: (...c) => c.forEach((x) => набор.delete(x)),
        contains: (c) => набор.has(c),
        toggle: (c, on) => { if(on) набор.add(c); else набор.delete(c); },
      },
      addEventListener: (тип, fn) => { if(тип === 'animationend') слушатель = fn; },
    };
  }
  const node = узел();
  const классы = node.набор;
  // Морды — тоже узлы: жест подставляет им позу раздумья.
  const морды = { mantisIndicator: узел(), goatIndicator: узел() };

  let времени = 0;
  const таймеры = new Map();
  let следующий = 1;

  const sandbox = {
    document: {
      getElementById: (id) => (id === 'playerThinkHoof' ? node : (морды[id] || null)),
      body: { classList: { contains: (c) => (c === 'screen--game' ? экран : false) } },
      addEventListener: () => {},
    },
    getHudEdgeSeat: (c) => край(c),
    isLocalColor: (c) => локальные.includes(c),
    setTimeout: (fn, ms) => { const id = следующий++; таймеры.set(id, { fn, при: времени + ms }); return id; },
    clearTimeout: (id) => { таймеры.delete(id); },
    console,
  };
  vm.createContext(sandbox);
  const порогСтрока = /^let (PLAYER_THINK_GESTURE_IDLE_MS = \d+);$/m.exec(source);
  assert(порогСтрока, 'не найдено объявление PLAYER_THINK_GESTURE_IDLE_MS');
  vm.runInContext([
    `var ${порогСтрока[1]};`,
    кусок('const playerThinkGesture = (() =>').replace(/^const /, 'var '),
  ].join('\n'), sandbox);

  return {
    жест: sandbox.playerThinkGesture,
    порог: sandbox.PLAYER_THINK_GESTURE_IDLE_MS,
    классы,
    поза: (id) => морды[id].набор.has('is-thinking'),
    позаУ: () => Object.keys(морды).filter((id) => морды[id].набор.has('is-thinking')),
    // Класс угла (is-north / is-south) остаётся на узле и после жеста — это место, а не
    // фаза. Поэтому «копыта нет» проверяется по фазовым классам, а не по пустоте.
    фаза: () => ['is-entering', 'is-fidgeting', 'is-leaving'].find((c) => классы.has(c)) || null,
    // Проматываем часы и выполняем всё, что успело сработать.
    ждать(ms){
      времени += ms;
      let сработало = 0;
      for(let шаг = 0; шаг < 50; шаг += 1){
        const готов = [...таймеры.entries()].find(([, t]) => t.при <= времени);
        if(!готов) break;
        таймеры.delete(готов[0]);
        готов[1].fn();
        сработало += 1;
      }
      return сработало;
    },
    // Кадры сами не играют — доигрываем их руками, как это делает браузер.
    доиграть(){
      assert(слушатель, 'на копыто не повесили обработчик animationend');
      for(const имя of ['aiHoofSlideIn', 'aiHoofFidgetOpen', 'aiHoofSlideOut']){
        слушатель({ animationName: имя });
      }
    },
    ждётТаймер: () => таймеры.size > 0,
  };
}

const ПОРОГ = стенд().порог;
assert(Number.isFinite(ПОРОГ) && ПОРОГ >= 3000 && ПОРОГ <= 60000,
  `0: порог бездействия ${ПОРОГ}мс — либо копыто полезет на каждый чих, либо не полезет никогда`);

// === 1. ГЛАВНОЕ: отрисовка зовёт sync постоянно, и это не должно мешать отсчёту ===
{
  const с = стенд();
  с.жест.sync('blue');
  // Ход тот же, кадров много: так это и работает в игре.
  for(let i = 0; i < 200; i += 1){
    с.ждать(ПОРОГ / 100);
    с.жест.sync('blue');
  }
  assert(с.фаза(),
    '1: копыто не вылезло за два порога, хотя игрок бездействовал. sync() зовётся из '
    + 'отрисовки много раз в секунду — значит он заводит отсчёт заново на каждом кадре, '
    + 'и тот никогда не доживает до конца');
}

// === 2. Ход ИИ жеста не получает ===
//
// У компьютера своё копыто и своё правило. Два сразу — это чужие раздумья на своей морде.
{
  const с = стенд({ локальные: ['green'] });
  с.жест.sync('blue');
  с.ждать(ПОРОГ * 3);
  assert(!с.фаза(),
    `2: на ходу ИИ вылез жест игрока (${[...с.классы].join(' ')})`);
  assert(!с.ждётТаймер(), '2b: на ходу ИИ остался заведённый отсчёт');
}

// === 3. Жест ПОВТОРЯЕТСЯ ===
{
  const с = стенд();
  с.жест.sync('blue');
  с.ждать(ПОРОГ + 1);
  assert(с.классы.has('is-entering'), '3: первый жест не начался');
  с.доиграть();
  assert(!с.фаза(), `3b: после ухода копыто осталось на экране (${с.фаза()})`);
  assert(с.ждётТаймер(), '3c: после жеста отсчёт не заведён заново — копыто покажется '
    + 'один раз за ход и замолчит, а человек думает сколько угодно');
  с.ждать(ПОРОГ + 1);
  assert(с.классы.has('is-entering'), '3d: второго жеста не было');
}

// === 4. Нажатие сбрасывает отсчёт ===
{
  const с = стенд();
  с.жест.sync('blue');
  // Игрок тыкает каждые полпорога — жест не должен появиться никогда.
  for(let i = 0; i < 10; i += 1){
    с.ждать(ПОРОГ * 0.5);
    с.жест.poke();
  }
  assert(!с.фаза(),
    '4: копыто вылезло, хотя игрок всё время что-то нажимал — считается время хода, '
    + 'а должно бездействие');
  // А если перестал — вылезает.
  с.ждать(ПОРОГ + 1);
  assert(с.классы.has('is-entering'), '4b: после того как игрок затих, жеста не дождались');
}

// === 5. Угол берётся по КРАЮ, а не по цвету ===
{
  const обычный = стенд({ край: (c) => c });                       // синий сверху
  обычный.жест.sync('blue');
  обычный.ждать(ПОРОГ + 1);
  assert(обычный.классы.has('is-north'),
    '5: на обычном крае синий сидит сверху, а жест ушёл вниз');

  const перевёрнутый = стенд({ край: (c) => (c === 'blue' ? 'green' : 'blue') });
  перевёрнутый.жест.sync('blue');
  перевёрнутый.ждать(ПОРОГ + 1);
  assert(перевёрнутый.классы.has('is-south'),
    '5b: при своём крае снизу синий сидит внизу, а жест остался наверху — морда уехала, '
    + 'а копыто нет');

  const зелёный = стенд({ край: (c) => c });
  зелёный.жест.sync('green');
  зелёный.ждать(ПОРОГ + 1);
  assert(зелёный.классы.has('is-south'), '5c: зелёный сидит снизу, а жест ушёл наверх');
}

// === 6. Вне игрового экрана жеста нет ===
{
  const с = стенд({ экран: false });
  с.жест.sync('blue');
  с.ждать(ПОРОГ * 2);
  assert(!с.фаза(), '6: копыто вылезло в меню');
}

// === 6b. Поза раздумья надевается и СНИМАЕТСЯ ===
//
// Жест подставляет морде второй рисунок — голову с поднятой мордой. Забыть снять её
// хуже, чем не надеть: голова так и останется поднятой до конца партии, а виноватым
// будет выглядеть лист.
{
  const с = стенд();
  с.жест.sync('blue');
  assert(с.позаУ().length === 0, '6b: поза надета до того, как жест начался');
  с.ждать(ПОРОГ + 1);
  assert(с.поза('mantisIndicator'), '6c: жест не подставил позу раздумья');
  assert(!с.поза('goatIndicator'), '6d: поза досталась и чужой морде');
  с.доиграть();
  assert(с.позаУ().length === 0,
    `6e: после жеста поза осталась на ${с.позаУ().join(', ')} — голова так и будет стоять поднятой`);

  // Зелёному — своей морде.
  const з = стенд();
  з.жест.sync('green');
  з.ждать(ПОРОГ + 1);
  assert(з.поза('goatIndicator') && !з.поза('mantisIndicator'),
    '6f: поза надета не той морде, которая думает');
}

// === 6g. Ход сменился посреди жеста — поза снимается с ПРЕЖНЕЙ морды ===
//
// Копыто живёт несколько секунд, и за это время ход может уйти к сопернику. Снимать
// позу надо с той морды, которой её надели, а не с той, которая думает сейчас.
{
  const с = стенд();
  с.жест.sync('blue');
  с.ждать(ПОРОГ + 1);
  assert(с.поза('mantisIndicator'), '6g: поза не надета');
  с.жест.sync('green');
  assert(!с.поза('mantisIndicator'),
    '6h: ход ушёл к сопернику, а прежняя морда осталась с поднятой головой');
}

// === 6i. У воробья наверху своя лапа, а не козье копыто ===
//
// Воробей — зелёный, и наверху он оказывается только при перевёрнутой доске. Копыто там
// смотрелось бы чужой лапой на своей морде, поэтому у него отдельный рисунок.
{
  const где = (цвет, край) => {
    const с = стенд({ край });
    с.жест.sync(цвет);
    с.ждать(ПОРОГ + 1);
    return с.классы;
  };
  const прямо = (c) => c;
  const наоборот = (c) => (c === 'blue' ? 'green' : 'blue');

  assert(где('green', наоборот).has('is-sparrow-north'),
    '6i: воробей наверху не получил свою лапу');
  assert(!где('green', прямо).has('is-sparrow-north'),
    '6j: воробью внизу досталась лапа для верхнего угла');
  assert(!где('blue', наоборот).has('is-sparrow-north'),
    '6k: козлу досталась воробьиная лапа');
  assert(!где('blue', прямо).has('is-sparrow-north'),
    '6l: козлу наверху досталась воробьиная лапа');

  // Внизу воробей сидит на ОБЫЧНОЙ доске — это самый частый случай, и лапа там своя же,
  // но заходит снизу. Козлу она не достаётся ни в одном углу.
  assert(где('green', прямо).has('is-sparrow-south'),
    '6l1: воробью внизу не досталась лапа');
  assert(!где('green', наоборот).has('is-sparrow-south'),
    '6l2: воробью наверху досталась лапа для нижнего угла');
  assert(!где('blue', прямо).has('is-sparrow-south'),
    '6l3: козлу наверху досталась нижняя воробьиная лапа');
  assert(!где('blue', наоборот).has('is-sparrow-south'),
    '6l4: козлу внизу досталась воробьиная лапа');
}

// === 6m. Воробьиная лапа: обе границы, о которые её уже резали ===
//
// Границ у лапы две, и обе невидимые:
//
//   КОРОБКА самого элемента — фон за её края не рисуется. На этом уже погорели:
//   коробку кроили по рамке рисунка, рамку считали по порогу альфы, полупрозрачный
//   кончик пальца в неё не попадал — и палец кончался плоским срезом.
//
//   КРАЙ КАДРА ИГРЫ — у #uiFrame стоит overflow: hidden. Ногу он резать обязан, лапа
//   тем и выныривает из-за грани; а вот пальцы за ним просто пропадают, и заметить
//   это можно было только глазами на живом экране.
//
// Лап теперь две — верхняя и нижняя, — и у нижней своё МЕСТО, свой РАЗВОРОТ и свои
// отражения. Поэтому считается всё одной формулой, честно повторяющей стили: точка
// листа -> отражения -> поворот -> место коробки -> (в горизонтали) поворот кадра.
{
  const ФАЙЛ = 'ui_gamescreen/gamescreen_outside/sparrows_hands.png';
  assert(styles.includes(ФАЙЛ), '6m: стили не ссылаются на файл лапы');

  const лапа = читатьАльфу(ФАЙЛ);
  const кадры = полосы(лапа, 0, лапа.width, 0);
  assert(кадры.length === 2,
    `6n: в файле лапы ${кадры.length} кадров вместо двух — вырезы в стилях устарели`);

  // Селектор может стоять не один, а в списке через запятую — тело всё равно общее.
  // Проверка следующего знака нужна, чтобы «...__frame» не поймал «...__frame--open».
  const правило = (селектор) => {
    const m = new RegExp(`${селектор}(?=[\\s,{])[^{}]*\\{([^}]*)\\}`).exec(styles);
    assert(m, `6o: не найдено правило ${селектор}`);
    return m[1];
  };
  const чис = (тело, имя, иначе) => {
    const m = new RegExp(`${имя}:\\s*(-?[\\d.]+)(?:px|deg)?`).exec(тело);
    if(m) return Number(m[1]);
    assert(иначе !== undefined, `6p: в правиле нет ${имя}`);
    return иначе;
  };
  const вырез = (тело) => {
    const m = /background-position:\s*(-?[\d.]+)(?:px)?\s+(-?[\d.]+)px/.exec(тело);
    assert(m, '6p: в правиле нет background-position');
    return { x: Number(m[1]), y: Number(m[2]) };
  };
  const сдвиг = (тело) => {
    const m = /transform:\s*translate\((-?[\d.]+)px,\s*(-?[\d.]+)px\)/.exec(тело);
    return m ? { x: Number(m[1]), y: Number(m[2]) } : { x: 0, y: 0 };
  };

  const сомкнуто = вырез(правило(
    '#playerThinkHoof\\.is-sparrow-north \\.ai-think-hoof__frame'));
  const раскрыто = вырез(правило(
    '#playerThinkHoof\\.is-sparrow-north \\.ai-think-hoof__frame--open'));
  assert(сомкнуто.x === раскрыто.x && сомкнуто.x === 0,
    `6q: вырезы кадров лапы взяты не от левой грани листа (${сомкнуто.x} и ${раскрыто.x}) — `
    + 'коробка обязана быть целой полосой, иначе рисунок опять начнёт стричь');

  // Два места лапы. У каждого правило портрета и правило горизонтали, и горизонталь
  // задаёт только то, что меняется: остальное берётся из портрета.
  const ВАРИАНТЫ = [
    { имя: 'верхняя', угол: 'is-north', класс: 'is-sparrow-north' },
    { имя: 'нижняя', угол: 'is-south', класс: 'is-sparrow-south' }
  ].map((в) => {
    const П = правило(`#playerThinkHoof\\.${в.угол}\\.${в.класс}`);
    const Г = правило(
      `html\\.is-board-landscape #playerThinkHoof\\.${в.угол}\\.${в.класс}`);
    const общее = { ш: чис(П, 'width'), в: чис(П, 'height') };
    const место = (тело, свой) => ({
      left: чис(тело, 'left', свой ? свой.left : undefined),
      top: чис(тело, 'top', свой ? свой.top : undefined),
      rot: чис(тело, '--hoof-rot', свой ? свой.rot : 0),
      fx: чис(тело, '--hoof-flip', свой ? свой.fx : 1),
      fy: чис(тело, '--hoof-flip-y', свой ? свой.fy : 1)
    });
    const п = место(П, null);
    return {
      имя: в.имя, ш: общее.ш, в: общее.в,
      портрет: п,
      горизонталь: место(Г, п),
      сдвиги: {
        false: сдвиг(правило(`#playerThinkHoof\\.${в.класс} \\.ai-think-hoof__frame--close`)),
        true: сдвиг(правило(`html\\.is-board-landscape #playerThinkHoof\\.${в.класс} `
          + '\\.ai-think-hoof__frame--close'))
      }
    };
  });

  // Место точки листа на экране игры — той же цепочкой, что и в стилях. Поворот кадра
  // в горизонтали даёт +90° элементу и переносит оси: точка кадра (u, v) видна на
  // экране в (800 - v, u).
  const РАМКА = { false: { x1:460, y1:800 }, true: { x1:800, y1:460 } };
  const место = (в, гориз, кадр, sx, sy) => {
    const п = гориз ? в.горизонталь : в.портрет;
    const т = кадр === 'close' ? в.сдвиги[гориз] : { x: 0, y: 0 };
    const B = кадр === 'close' ? -сомкнуто.y : -раскрыто.y;
    const мх = sx + т.x, му = (sy - B) + т.y;
    let dx = (мх - в.ш / 2) * п.fx, dy = (му - в.в / 2) * п.fy;
    const a = п.rot * Math.PI / 180, cos = Math.cos(a), sin = Math.sin(a);
    const u = п.left + в.ш / 2 + dx * cos - dy * sin;
    const v = п.top + в.в / 2 + dx * sin + dy * cos;
    return гориз ? { x: 800 - v, y: u, мх, му } : { x: u, y: v, мх, му };
  };

  const строки = (кадр) => {
    const из = [];
    const полоса = кадр === 'close' ? кадры[0] : кадры[1];
    for(let y = полоса.y0; y < полоса.y1; y += 1){
      const точки = [];
      for(let x = 0; x < лапа.width; x += 1){
        if(лапа.alpha[y * лапа.width + x] > 16) точки.push(x);
      }
      if(точки.length) из.push({ y, точки });
    }
    return из;
  };

  for(const в of ВАРИАНТЫ){
    for(const кадр of ['close', 'open']){
      for(const строка of строки(кадр)){
        const л = место(в, false, кадр, строка.точки[0], строка.y);
        const п = место(в, false, кадр, строка.точки[строка.точки.length - 1], строка.y);
        assert(л.мх >= 0 && п.мх < в.ш && л.му >= 0 && л.му < в.в,
          `6r: ${в.имя} лапа, кадр ${кадр} не влезает в коробку ${в.ш}x${в.в} в строке `
          + `${строка.y} (${л.мх}..${п.мх} по x, ${л.му} по y) — рисунок срежет коробкой`);
      }
    }
  }

  // Край кадра проверяется по КОНЧИКУ ДЛИННОГО ПАЛЬЦА — той точке, которой лапа и
  // чешет шею. Считать весь срез бессмысленно: ногу край режет по делу, и сколько
  // именно точек ноги ушло, зависит от места. А вот кончик обязан лежать с запасом
  // внутри: как только он подбирается к грани, палец на экране обрубается — ровно это
  // и было видно на живом экране, пока место подбиралось на глаз.
  const ЗАПАС = 10;
  const кончик = (кадр) => {
    const полоса = кадр === 'close' ? кадры[0] : кадры[1];
    for(let y = полоса.y0; y < полоса.y1; y += 1){
      for(let x = 0; x < лапа.width; x += 1){
        if(лапа.alpha[y * лапа.width + x] > 16) return { x, y };
      }
    }
    assert(false, '6s: у кадра лапы не нашлось кончика пальца');
    return null;
  };
  for(const в of ВАРИАНТЫ){
    for(const кадр of ['close', 'open']){
      const к = кончик(кадр);
      for(const гориз of [false, true]){
        const т = место(в, гориз, кадр, к.x, к.y);
        const р = РАМКА[гориз];
        const запас = Math.min(т.x, р.x1 - 1 - т.x, т.y, р.y1 - 1 - т.y);
        assert(запас >= ЗАПАС,
          `6s: ${в.имя} лапа ${гориз ? 'в горизонтали' : 'в портрете'}, кончик пальца кадра `
          + `${кадр} стоит в ${запас.toFixed(1)} точках от грани кадра — палец обрубится`);
      }
    }
  }

  // Кадры расставлены на стенде порознь, и сдвиг между ними — это само движение. Но
  // движение это МАЛЕНЬКОЕ: если кадры разъедутся, лапа будет прыгать на каждом сжатии.
  // Мерится по месту, где нога уходит за правую грань листа: пальцы в кадрах расходятся
  // по-разному, а нога у бедра нарисована на одном месте.
  const ПРЫЖОК = 6;
  const бедро = (кадр) => {
    const полоса = кадр === 'close' ? кадры[0] : кадры[1];
    for(let y = полоса.y0; y < полоса.y1; y += 1){
      if(лапа.alpha[y * лапа.width + (лапа.width - 1)] > 16) return y;
    }
    assert(false, '6t: у кадра лапы нога не доходит до правой грани файла');
    return 0;
  };
  for(const в of ВАРИАНТЫ){
    for(const гориз of [false, true]){
      const с = место(в, гориз, 'close', лапа.width - 1, бедро('close'));
      const р = место(в, гориз, 'open', лапа.width - 1, бедро('open'));
      const d = Math.hypot(с.x - р.x, с.y - р.y);
      assert(d <= ПРЫЖОК,
        `6t: ${в.имя} лапа ${гориз ? 'в горизонтали' : 'в портрете'}, нога у кадров `
        + `расходится на ${d.toFixed(1)} точек — на сжатии лапа прыгнет, а не скребнёт`);
    }
  }

  // И последнее про край кадра: нога обязана за него УЙТИ. Лист обрывает ногу на своей
  // грани, и если это место осталось внутри кадра, лапа висит в воздухе обрубком — она
  // ведь ниоткуда не растёт. Проверка ловит и перепутанный разворот: стоит лапе лечь не
  // вдоль своей грани, как обрубок ноги выезжает на видное место.
  for(const в of ВАРИАНТЫ){
    for(const кадр of ['close', 'open']){
      for(const гориз of [false, true]){
        const т = место(в, гориз, кадр, лапа.width - 1, бедро(кадр));
        const р = РАМКА[гориз];
        assert(т.x < 0 || т.x > р.x1 - 1 || т.y < 0 || т.y > р.y1 - 1,
          `6u: ${в.имя} лапа ${гориз ? 'в горизонтали' : 'в портрете'}, конец ноги кадра `
          + `${кадр} стоит внутри кадра, в (${т.x.toFixed(1)}, ${т.y.toFixed(1)}) — `
          + 'нога оборвётся на виду, лапа повиснет в воздухе');
      }
    }
  }
}

