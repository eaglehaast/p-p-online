#!/usr/bin/env node
'use strict';

// Smoke test: жест задумчивости живого игрока.
//
// Копыто у ИИ было и раньше. Здесь то же копыто, но правило другое, и разница как раз
// в том, что легко потерять:
//
//   у ИИ           одноразовый жест: окно раздумий кончается само, когда он целится
//   у игрока       повторяющийся: человек может думать сколько угодно
//
// Отсюда четыре места, где это ломается молча, и все четыре тест держит.
//
// 1. sync() зовётся ИЗ ОТРИСОВКИ, то есть по многу раз в секунду. Если он будет
//    заводить отсчёт заново на каждом вызове, копыто не вылезет никогда: отсчёт просто
//    не доживёт до конца. Проверка «ход тот же — отсчёт не трогаем» тут главная.
//
// 2. Отсчёт заводится заново ПОСЛЕ жеста. Скопировать одноразовость ИИ — значит
//    показать копыто один раз за ход и замолчать.
//
// 3. Считается бездействие, а не время хода: нажатие сбрасывает отсчёт. Иначе копыто
//    вылезет посреди затянувшегося прицеливания, когда игрок как раз занят.
//
// 4. Угол берётся по КРАЮ, а не по цвету. Морда переезжает вместе со своей половиной
//    поля, и жест обязан ехать за ней — ровно те же грабли, на которых уже стояла
//    полоса инвентаря.
//
// И отдельно: на ходу ИИ жеста быть не должно вовсе — у компьютера своё копыто, и два
// сразу означали бы, что игроку показывают чужие раздумья.

const fs = require('fs');
const vm = require('vm');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const source = fs.readFileSync('script.js', 'utf8');
const styles = fs.readFileSync('styles.css', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');

function кусок(начало){
  const at = source.indexOf(начало);
  assert(at !== -1, `не найдено: ${начало}`);
  const open = source.indexOf('{', at);
  let depth = 0;
  for(let i = open; i < source.length; i += 1){
    if(source[i] === '{') depth += 1;
    if(source[i] === '}'){
      depth -= 1;
      if(depth === 0) return source.slice(at, source.indexOf(';', i) + 1);
    }
  }
  throw new Error(`не закрыто: ${начало}`);
}

// === Стенд: поддельный узел, поддельные часы ===
function стенд({ локальные = ['blue', 'green'], край = (c) => c, экран = true } = {}){
  let слушатель = null;
  function узел(){
    const набор = new Set();
    return {
      набор,
      className: '',
      classList: {
        add: (...c) => c.forEach((x) => набор.add(x)),
        remove: (...c) => c.forEach((x) => набор.delete(x)),
        contains: (c) => набор.has(c),
        toggle: (c, on) => { if(on) набор.add(c); else набор.delete(c); },
      },
      addEventListener: (тип, fn) => { if(тип === 'animationend') слушатель = fn; },
    };
  }
  const node = узел();
  const классы = node.набор;
  // Морды — тоже узлы: жест подставляет им позу раздумья.
  const морды = { mantisIndicator: узел(), goatIndicator: узел() };

  let времени = 0;
  const таймеры = new Map();
  let следующий = 1;

  const sandbox = {
    document: {
      getElementById: (id) => (id === 'playerThinkHoof' ? node : (морды[id] || null)),
      body: { classList: { contains: (c) => (c === 'screen--game' ? экран : false) } },
      addEventListener: () => {},
    },
    getHudEdgeSeat: (c) => край(c),
    isLocalColor: (c) => локальные.includes(c),
    setTimeout: (fn, ms) => { const id = следующий++; таймеры.set(id, { fn, при: времени + ms }); return id; },
    clearTimeout: (id) => { таймеры.delete(id); },
    console,
  };
  vm.createContext(sandbox);
  const порогСтрока = /^let (PLAYER_THINK_GESTURE_IDLE_MS = \d+);$/m.exec(source);
  assert(порогСтрока, 'не найдено объявление PLAYER_THINK_GESTURE_IDLE_MS');
  vm.runInContext([
    `var ${порогСтрока[1]};`,
    кусок('const playerThinkGesture = (() =>').replace(/^const /, 'var '),
  ].join('\n'), sandbox);

  return {
    жест: sandbox.playerThinkGesture,
    порог: sandbox.PLAYER_THINK_GESTURE_IDLE_MS,
    классы,
    поза: (id) => морды[id].набор.has('is-thinking'),
    позаУ: () => Object.keys(морды).filter((id) => морды[id].набор.has('is-thinking')),
    // Класс угла (is-north / is-south) остаётся на узле и после жеста — это место, а не
    // фаза. Поэтому «копыта нет» проверяется по фазовым классам, а не по пустоте.
    фаза: () => ['is-entering', 'is-fidgeting', 'is-leaving'].find((c) => классы.has(c)) || null,
    // Проматываем часы и выполняем всё, что успело сработать.
    ждать(ms){
      времени += ms;
      let сработало = 0;
      for(let шаг = 0; шаг < 50; шаг += 1){
        const готов = [...таймеры.entries()].find(([, t]) => t.при <= времени);
        if(!готов) break;
        таймеры.delete(готов[0]);
        готов[1].fn();
        сработало += 1;
      }
      return сработало;
    },
    // Кадры сами не играют — доигрываем их руками, как это делает браузер.
    доиграть(){
      assert(слушатель, 'на копыто не повесили обработчик animationend');
      for(const имя of ['aiHoofSlideIn', 'aiHoofFidgetOpen', 'aiHoofSlideOut']){
        слушатель({ animationName: имя });
      }
    },
    ждётТаймер: () => таймеры.size > 0,
  };
}

const ПОРОГ = стенд().порог;
assert(Number.isFinite(ПОРОГ) && ПОРОГ >= 3000 && ПОРОГ <= 60000,
  `0: порог бездействия ${ПОРОГ}мс — либо копыто полезет на каждый чих, либо не полезет никогда`);

// === 1. ГЛАВНОЕ: отрисовка зовёт sync постоянно, и это не должно мешать отсчёту ===
{
  const с = стенд();
  с.жест.sync('blue');
  // Ход тот же, кадров много: так это и работает в игре.
  for(let i = 0; i < 200; i += 1){
    с.ждать(ПОРОГ / 100);
    с.жест.sync('blue');
  }
  assert(с.фаза(),
    '1: копыто не вылезло за два порога, хотя игрок бездействовал. sync() зовётся из '
    + 'отрисовки много раз в секунду — значит он заводит отсчёт заново на каждом кадре, '
    + 'и тот никогда не доживает до конца');
}

// === 2. Ход ИИ жеста не получает ===
//
// У компьютера своё копыто и своё правило. Два сразу — это чужие раздумья на своей морде.
{
  const с = стенд({ локальные: ['green'] });
  с.жест.sync('blue');
  с.ждать(ПОРОГ * 3);
  assert(!с.фаза(),
    `2: на ходу ИИ вылез жест игрока (${[...с.классы].join(' ')})`);
  assert(!с.ждётТаймер(), '2b: на ходу ИИ остался заведённый отсчёт');
}

// === 3. Жест ПОВТОРЯЕТСЯ ===
{
  const с = стенд();
  с.жест.sync('blue');
  с.ждать(ПОРОГ + 1);
  assert(с.классы.has('is-entering'), '3: первый жест не начался');
  с.доиграть();
  assert(!с.фаза(), `3b: после ухода копыто осталось на экране (${с.фаза()})`);
  assert(с.ждётТаймер(), '3c: после жеста отсчёт не заведён заново — копыто покажется '
    + 'один раз за ход и замолчит, а человек думает сколько угодно');
  с.ждать(ПОРОГ + 1);
  assert(с.классы.has('is-entering'), '3d: второго жеста не было');
}

// === 4. Нажатие сбрасывает отсчёт ===
{
  const с = стенд();
  с.жест.sync('blue');
  // Игрок тыкает каждые полпорога — жест не должен появиться никогда.
  for(let i = 0; i < 10; i += 1){
    с.ждать(ПОРОГ * 0.5);
    с.жест.poke();
  }
  assert(!с.фаза(),
    '4: копыто вылезло, хотя игрок всё время что-то нажимал — считается время хода, '
    + 'а должно бездействие');
  // А если перестал — вылезает.
  с.ждать(ПОРОГ + 1);
  assert(с.классы.has('is-entering'), '4b: после того как игрок затих, жеста не дождались');
}

// === 5. Угол берётся по КРАЮ, а не по цвету ===
{
  const обычный = стенд({ край: (c) => c });                       // синий сверху
  обычный.жест.sync('blue');
  обычный.ждать(ПОРОГ + 1);
  assert(обычный.классы.has('is-north'),
    '5: на обычном крае синий сидит сверху, а жест ушёл вниз');

  const перевёрнутый = стенд({ край: (c) => (c === 'blue' ? 'green' : 'blue') });
  перевёрнутый.жест.sync('blue');
  перевёрнутый.ждать(ПОРОГ + 1);
  assert(перевёрнутый.классы.has('is-south'),
    '5b: при своём крае снизу синий сидит внизу, а жест остался наверху — морда уехала, '
    + 'а копыто нет');

  const зелёный = стенд({ край: (c) => c });
  зелёный.жест.sync('green');
  зелёный.ждать(ПОРОГ + 1);
  assert(зелёный.классы.has('is-south'), '5c: зелёный сидит снизу, а жест ушёл наверх');
}

// === 6. Вне игрового экрана жеста нет ===
{
  const с = стенд({ экран: false });
  с.жест.sync('blue');
  с.ждать(ПОРОГ * 2);
  assert(!с.фаза(), '6: копыто вылезло в меню');
}

// === 6b. Поза раздумья надевается и СНИМАЕТСЯ ===
//
// Жест подставляет морде второй рисунок — голову с поднятой мордой. Забыть снять её
// хуже, чем не надеть: голова так и останется поднятой до конца партии, а виноватым
// будет выглядеть лист.
{
  const с = стенд();
  с.жест.sync('blue');
  assert(с.позаУ().length === 0, '6b: поза надета до того, как жест начался');
  с.ждать(ПОРОГ + 1);
  assert(с.поза('mantisIndicator'), '6c: жест не подставил позу раздумья');
  assert(!с.поза('goatIndicator'), '6d: поза досталась и чужой морде');
  с.доиграть();
  assert(с.позаУ().length === 0,
    `6e: после жеста поза осталась на ${с.позаУ().join(', ')} — голова так и будет стоять поднятой`);

  // Зелёному — своей морде.
  const з = стенд();
  з.жест.sync('green');
  з.ждать(ПОРОГ + 1);
  assert(з.поза('goatIndicator') && !з.поза('mantisIndicator'),
    '6f: поза надета не той морде, которая думает');
}

// === 6g. Ход сменился посреди жеста — поза снимается с ПРЕЖНЕЙ морды ===
//
// Копыто живёт несколько секунд, и за это время ход может уйти к сопернику. Снимать
// позу надо с той морды, которой её надели, а не с той, которая думает сейчас.
{
  const с = стенд();
  с.жест.sync('blue');
  с.ждать(ПОРОГ + 1);
  assert(с.поза('mantisIndicator'), '6g: поза не надета');
  с.жест.sync('green');
  assert(!с.поза('mantisIndicator'),
    '6h: ход ушёл к сопернику, а прежняя морда осталась с поднятой головой');
}

// === 7. Разметка и стили: копыта делят один набор кадров ===
//
// Маршрутизатор фаз переключается по ИМЕНИ анимации. Переименуют кадры под одно
// копыто — второе замрёт на въезде, и заметить это можно только глазами.
{
  for(const имя of ['aiHoofSlideIn', 'aiHoofFidgetOpen', 'aiHoofSlideOut']){
    assert(new RegExp(`@keyframes ${имя}\\b`).test(styles),
      `7: в стилях нет кадров ${имя}, а маршрутизатор фаз ждёт именно это имя`);
  }
  const тело = кусок('const playerThinkGesture = (() =>');
  for(const имя of ['aiHoofSlideIn', 'aiHoofFidgetOpen', 'aiHoofSlideOut']){
    assert(тело.includes(имя), `7b: жест игрока перестал слушать кадр ${имя}`);
  }
  // Общие правила написаны на классе: без него у копыта игрока не будет ни кадров,
  // ни фаз — оно останется невидимым навсегда.
  for(const id of ['aiThinkHoof', 'playerThinkHoof']){
    assert(new RegExp(`id="${id}"[^>]*class="[^"]*\\bthink-hoof\\b`).test(html),
      `7c: у #${id} нет класса think-hoof — общие правила копыта мимо него`);
  }
  assert(/\.think-hoof\.is-entering\s*\{/.test(styles) && /\.think-hoof\.is-fidgeting\s*\{/.test(styles)
    && /\.think-hoof\.is-leaving\s*\{/.test(styles),
    '7d: фазы копыта снова описаны по id — второе копыто останется без анимаций');
  // Места разные: одно копыто у морды ИИ, второе переезжает между углами.
  assert(/#playerThinkHoof\.is-north\s*\{/.test(styles) && /#playerThinkHoof\.is-south\s*\{/.test(styles),
    '7e: у копыта игрока нет правил на оба угла');
}

console.log('smoke-player-think-gesture: OK');
