#!/usr/bin/env node
'use strict';

// Smoke test: окна морд вырезают с листа ровно свою голову.
//
// Лист goat_and_sparrow.png 460x800 несёт ЧЕТЫРЕ головы, по одной в каждом углу:
//
//              слева (портрет)        справа (горизонталь)
//   сверху     козёл, смотрит вправо   воробей, смотрит влево
//   снизу      воробей, смотрит вправо козёл, смотрит влево
//
// Левая колонка — портретная пара: в портрете морды стоят у левой грани кадра, и
// «внутрь поля» для них значит вправо. Правая — отдельно нарисованная пара для
// горизонтали; на лист её уложили отражённой по горизонтали, поэтому обе головы
// смотрят там в одну сторону, влево.
//
// Из этого следует правило, которое нельзя держать в голове: в горизонтали козёл
// стоит в ПРАВОМ ВЕРХНЕМ углу экрана, где «внутрь поля» — влево, и отражать его не
// надо; воробей стоит в ЛЕВОМ НИЖНЕМ, где внутрь поля вправо, и отражение ему
// обязательно. Ровно одна из двух горизонтальных морд отражена — и это воробей.
//
// Само вырезание держится на трёх числах: размере окна, background-size и
// background-position. Ошибиться в любом из них — значит показать кусок соседней
// головы или срезать свою, и заметить это можно только глазами в игре. Поэтому
// тест читает НАСТОЯЩИЙ png, находит там головы по альфе и проверяет каждое окно:
// своя голова целиком внутри, чужих точек внутри нет.
//
// Замер листа (порог альфы 16): слева сверху (0,0)-(45,93), слева снизу
// (0,722)-(50,800), справа сверху (411,0)-(460,92), справа снизу (405,709)-(460,800).
// Вне голов в окнах максимальная альфа 4 из 255 — это невидимый мусор, поэтому
// порог 16 и стоит.

const fs = require('fs');
const zlib = require('zlib');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const styles = fs.readFileSync('styles.css', 'utf8');
const source = fs.readFileSync('script.js', 'utf8');
const ЛИСТ = 'ui_gamescreen/gamescreen_outside/goat_and_sparrow.png';

// === Чтение png: только альфа, только 8 бит RGBA без чересстрочности ===
function читатьАльфу(путь){
  const buf = fs.readFileSync(путь);
  assert(buf.slice(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])),
    'это не png: ' + путь);
  let pos = 8;
  let width = 0, height = 0;
  const данные = [];
  while(pos < buf.length){
    const len = buf.readUInt32BE(pos);
    const тип = buf.slice(pos + 4, pos + 8).toString('latin1');
    const тело = buf.slice(pos + 8, pos + 8 + len);
    if(тип === 'IHDR'){
      width = тело.readUInt32BE(0);
      height = тело.readUInt32BE(4);
      assert(тело[8] === 8 && тело[9] === 6 && тело[12] === 0,
        'лист морд перестал быть 8-битным RGBA без чересстрочности — читалка теста рассчитана '
        + 'только на такой');
    } else if(тип === 'IDAT'){
      данные.push(тело);
    } else if(тип === 'IEND'){
      break;
    }
    pos += 12 + len;
  }
  const raw = zlib.inflateSync(Buffer.concat(данные));
  const bpp = 4;
  const строка = width * bpp;
  const alpha = new Uint8Array(width * height);
  let prev = Buffer.alloc(строка);
  for(let y = 0; y < height; y += 1){
    const фильтр = raw[y * (строка + 1)];
    const cur = Buffer.from(raw.slice(y * (строка + 1) + 1, y * (строка + 1) + 1 + строка));
    for(let i = 0; i < строка; i += 1){
      const a = i >= bpp ? cur[i - bpp] : 0;
      const b = prev[i];
      const c = i >= bpp ? prev[i - bpp] : 0;
      let v = cur[i];
      if(фильтр === 1) v += a;
      else if(фильтр === 2) v += b;
      else if(фильтр === 3) v += (a + b) >> 1;
      else if(фильтр === 4){
        const p = a + b - c;
        const pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
        v += (pa <= pb && pa <= pc) ? a : (pb <= pc ? b : c);
      }
      cur[i] = v & 0xff;
    }
    for(let x = 0; x < width; x += 1) alpha[y * width + x] = cur[x * bpp + 3];
    prev = cur;
  }
  return { width, height, alpha };
}

const лист = читатьАльфу(ЛИСТ);
const ПОРОГ = 16;

function рамка(лист, x0, y0, x1, y1){
  let minX = Infinity, minY = Infinity, maxX = -1, maxY = -1;
  for(let y = y0; y < y1; y += 1){
    for(let x = x0; x < x1; x += 1){
      if(лист.alpha[y * лист.width + x] <= ПОРОГ) continue;
      if(x < minX) minX = x;
      if(y < minY) minY = y;
      if(x > maxX) maxX = x;
      if(y > maxY) maxY = y;
    }
  }
  return maxX < 0 ? null : { x0: minX, y0: minY, x1: maxX + 1, y1: maxY + 1 };
}

// === 1. Лист на месте и головы лежат по углам ===
{
  assert(лист.width === 460 && лист.height === 800,
    `1: лист морд стал ${лист.width}x${лист.height} — все вырезы в стилях считаны от 460x800`);
}

const головы = {
  'слева сверху': рамка(лист, 0, 0, 230, 400),
  'слева снизу': рамка(лист, 0, 400, 230, 800),
  'справа сверху': рамка(лист, 230, 0, 460, 400),
  'справа снизу': рамка(лист, 230, 400, 460, 800),
};
for(const [где, r] of Object.entries(головы)){
  assert(r, `1b: в четверти «${где}» нет головы — лист перерисован, вырезы в стилях устарели`);
}

// === 2. Разбор правил из стилей ===
function правило(селектор){
  const at = styles.indexOf(selectorKey(селектор));
  assert(at !== -1, `не найдено правило: ${селектор}`);
  const open = styles.indexOf('{', at);
  const close = styles.indexOf('}', open);
  return styles.slice(open + 1, close);
}
function selectorKey(селектор){ return селектор + ' {'; }

function число(тело, имя){
  const m = new RegExp(`(?:^|;|\\n)\\s*${имя}:\\s*(-?[\\d.]+)px`).exec(тело);
  return m ? Number(m[1]) : null;
}

// background-position задаёт, где лежит ЛЕВЫЙ ВЕРХНИЙ угол листа внутри окна.
// Ключевые слова разворачиваются в те же смещения: right — это (окно - лист).
function смещение(тело, окно){
  const m = /background-position:\s*([^;]+);/.exec(тело);
  assert(m, 'в правиле нет background-position');
  const [сx, сy] = m[1].trim().split(/\s+/);
  assert(сy !== undefined, `background-position: «${m[1].trim()}» — тест ждёт два значения`);
  const разбор = (t, размерОкна, размерЛиста) => {
    if(t === 'left' || t === 'top') return 0;
    if(t === 'right' || t === 'bottom') return размерОкна - размерЛиста;
    if(t === 'center') return (размерОкна - размерЛиста) / 2;
    const v = /^(-?[\d.]+)(px)?$/.exec(t);
    assert(v, `непонятное значение background-position: «${t}»`);
    return Number(v[1]);
  };
  return { x: разбор(сx, окно.w, лист.width), y: разбор(сy, окно.h, лист.height) };
}

// Кусок листа, видимый в окне.
function вырез(тело, окно){
  const с = смещение(тело, окно);
  return { x0: -с.x, y0: -с.y, x1: -с.x + окно.w, y1: -с.y + окно.h };
}

const базовое = правило('.turn-indicator');
assert(new RegExp(`background-image:\\s*url\\("${ЛИСТ}"\\)`).test(базовое),
  `2: .turn-indicator берёт не ${ЛИСТ}`);
assert(/background-size:\s*460px 800px/.test(базовое),
  '2b: background-size разошёлся с размером листа — все вырезы посчитаны от 460x800');

const окноПортрет = { w: число(базовое, 'width'), h: число(базовое, 'height') };
const горизБаза = правило('html.is-board-landscape .turn-indicator');
const окноГориз = { w: число(горизБаза, 'width'), h: число(горизБаза, 'height') };
assert(окноПортрет.w > 0 && окноПортрет.h > 0 && окноГориз.w > 0 && окноГориз.h > 0,
  '2c: размеры окон морд не читаются из стилей — проверка устарела');

// === 3. ГЛАВНОЕ: каждое окно показывает ровно свою голову ===
//
// «Целиком своя и ни куска чужой» — это и есть весь смысл вырезов. Отдельно ловим
// самый тихий вид поломки: окно во всю ширину кадра, при котором у правой грани
// вылезает голова из соседней колонки.
const окна = [
  ['портрет, козёл', '#mantisIndicator', окноПортрет, 'слева сверху'],
  ['портрет, воробей', '#goatIndicator', окноПортрет, 'слева снизу'],
  ['горизонталь, козёл', 'html.is-board-landscape #mantisIndicator', окноГориз, 'справа снизу'],
  ['горизонталь, воробей', 'html.is-board-landscape #goatIndicator', окноГориз, 'справа сверху'],
];

for(const [имя, селектор, окно, чья] of окна){
  const тело = правило(селектор);
  // Портретные правила задают вертикаль через top элемента, а не через
  // background-position: там окно высотой в половину кадра, и лист прижат
  // ключевым словом. Разбор один и тот же.
  const в = вырез(тело, окно);
  const своя = головы[чья];

  assert(в.x0 <= своя.x0 && в.y0 <= своя.y0 && в.x1 >= своя.x1 && в.y1 >= своя.y1,
    `3 (${имя}): окно показывает лист ${JSON.stringify(в)}, а своя голова лежит в `
    + `${JSON.stringify(своя)} — часть головы срезана`);

  for(const [где, чужая] of Object.entries(головы)){
    if(где === чья) continue;
    const пересеклись = в.x0 < чужая.x1 && в.x1 > чужая.x0 && в.y0 < чужая.y1 && в.y1 > чужая.y0;
    assert(!пересеклись,
      `3b (${имя}): в окно ${JSON.stringify(в)} попадает голова «${где}» `
      + `${JSON.stringify(чужая)} — рядом со своей мордой вылезет чужая`);
  }

  // И ничего постороннего: не только чужих голов, но и любых заметных точек.
  const внутри = рамка(лист, Math.max(0, в.x0), Math.max(0, в.y0),
    Math.min(лист.width, в.x1), Math.min(лист.height, в.y1));
  assert(внутри && внутри.x0 === своя.x0 && внутри.y0 === своя.y0
    && внутри.x1 === своя.x1 && внутри.y1 === своя.y1,
    `3c (${имя}): видимое в окне ${JSON.stringify(внутри)} не совпадает со своей головой `
    + `${JSON.stringify(своя)} — в вырез затесалось что-то ещё`);
}

// === 4. Отражена ровно одна горизонтальная морда, и это воробей ===
//
// Правая колонка уложена на лист в одну сторону, а углы у морд противоположные —
// значит одну из двух обязательно надо отразить. Отражают ту, чей угол смотрит
// против листа: воробья в левом нижнем. Отразить обеих или ни одной — это морда,
// глядящая из поля наружу.
{
  const козёл = правило('html.is-board-landscape #mantisIndicator');
  const воробей = правило('html.is-board-landscape #goatIndicator');
  assert(/rotate\(-90deg\)/.test(козёл) && /rotate\(-90deg\)/.test(воробей),
    '4: встречный поворот пропал — морды лягут набок вместе с кадром');
  assert(!/scaleX\(-1\)/.test(козёл),
    '4b: козла в горизонтали снова отражают — но правая колонка листа уже нарисована '
    + 'смотрящей влево, а в правом верхнем углу влево и значит «внутрь поля»');
  assert(/scaleX\(-1\)/.test(воробей),
    '4c: воробья в горизонтали перестали отражать — в левом нижнем углу он смотрит наружу поля');
}

// === 5. Старого листа в проекте не осталось ===
//
// Он лежит рядом под похожим именем: сослаться на него по привычке ничего не стоит,
// а увидеть подмену можно только в игре.
{
  assert(!/goat and sparrow\.png/.test(styles) && !/goat and sparrow\.png/.test(source),
    '5: где-то остался старый лист «goat and sparrow.png»');
  assert(source.includes(`"${ЛИСТ}"`),
    '5b: новый лист не в списке предзагрузки — морды моргнут при первом показе');
}

console.log('smoke-mascot-sheet: OK');
