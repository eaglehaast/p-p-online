#!/usr/bin/env node
'use strict';

// Smoke test: морда стоит при своей половине поля и вырезана с листа целиком.
//
// Лист goat_and_sparrow.png 460x800 несёт головы по углам. Колонки — это два ВИДА
// ДОСКИ, а не две ориентации:
//
//                  левая колонка            правая колонка
//                  (свой край как обычно)   (свой край снизу)
//    сверху        козёл, синий             воробей, зелёный
//    снизу         воробей, зелёный         козёл, синий
//
// И пятая, между ними в правой колонке: козёл с поднятой головой — поза раздумья,
// которую жест подставляет вместо спокойной. Она нарисована отдельно, а не получена
// поворотом: площадь у неё 74% от спокойной, главные оси расходятся всего на 2.7°.
//
// При перевороте половины поля меняются местами, и морда обязана уехать за своей
// половиной: синий козёл вниз, зелёный воробей наверх. Голова, свисающая с верхнего
// угла, и голова, поднимающаяся из нижнего — разные рисунки, отражением друг из
// друга они не получаются, поэтому пара и нарисована отдельно.
//
// Правую колонку уложили на лист отражённой по горизонтали, чтобы обе её головы
// смотрели туда же, куда левые. В игре это отражение снимается (--mascot-flip), а в
// горизонтали к нему добавляется второе — под угол экрана (--corner-flip).
//
// Замер листа (порог альфы 16): слева сверху (0,0)-(45,93), слева снизу
// (0,722)-(50,800), справа сверху (411,0)-(460,92), поза раздумья (416,585)-(460,672),
// справа снизу (405,709)-(460,800). Вне голов в окнах максимальная альфа 4 из 255 —
// невидимый мусор, отсюда и порог.
//
// Ловится тут два разных вида поломки. Первый: морда осталась при чужой половине —
// это видно только глазами и только если специально переключить край. Второй: вырез
// съехал, и рядом со своей мордой вылезает кусок соседней или срезается своя. Поэтому
// тест читает НАСТОЯЩИЙ png, находит головы по альфе и проверяет каждое окно: две
// ориентации на два края на две морды плюс поза раздумья.

const fs = require('fs');
const { читатьАльфу, рамка: рамкаЛиста, полосы: полосыЛиста, ПОРОГ_АЛЬФЫ: ПОРОГ } =
  require('./sprite-alpha-utils.js');

function assert(condition, message){
  if(!condition) throw new Error(message);
}

const styles = fs.readFileSync('styles.css', 'utf8');
const source = fs.readFileSync('script.js', 'utf8');
const ЛИСТ = 'ui_gamescreen/gamescreen_outside/goat_and_sparrow.png';

// Чтение png и замеры — общие с проверкой листов жестов, см. sprite-alpha-utils.
const лист = читатьАльфу(ЛИСТ);

// === 1. Лист на месте и головы лежат по углам ===
assert(лист.width === 460 && лист.height === 800,
  `1: лист морд стал ${лист.width}x${лист.height} — все вырезы в стилях считаны от 460x800`);

// Головы ищутся ПОЛОСАМИ непустых строк, а не по четвертям: в правой колонке их три, и
// деление пополам склеило бы позу раздумья со спокойной головой в одну рамку.
const рамка = (x0, y0, x1, y1) => рамкаЛиста(лист, x0, y0, x1, y1);
const слева = полосыЛиста(лист, 0, 230);
const справа = полосыЛиста(лист, 230, 460);
assert(слева.length === 2,
  `1b: в левой колонке ${слева.length} голов вместо двух — лист перерисован, вырезы устарели`);
assert(справа.length === 3,
  `1c: в правой колонке ${справа.length} голов вместо трёх (воробей, поза раздумья, козёл) — `
  + 'лист перерисован, вырезы устарели');

const головы = {
  'слева сверху': слева[0],
  'слева снизу': слева[1],
  'справа сверху': справа[0],
  'поза раздумья': справа[1],
  'справа снизу': справа[2],
};

// === 2. Разбор правил ===
function правило(селектор){
  const re = new RegExp(`^${селектор.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\{`, 'm');
  const m = re.exec(styles);
  assert(m, `не найдено правило: ${селектор}`);
  const open = styles.indexOf('{', m.index);
  const close = styles.indexOf('}', open);
  return styles.slice(open + 1, close);
}

function свойство(тело, имя){
  const m = new RegExp(`(?:^|;|\\n)\\s*${имя}:\\s*([^;\\n]+)`).exec(тело);
  return m ? m[1].trim() : null;
}
function число(тело, имя){
  const v = свойство(тело, имя);
  if(v === null) return null;
  // Ноль в стилях пишут без единиц, остальное — в точках.
  const m = /^(-?[\d.]+)(?:px)?$/.exec(v);
  return m ? Number(m[1]) : null;
}

// background-position задаёт, где лежит ЛЕВЫЙ ВЕРХНИЙ угол листа внутри окна.
// Ключевые слова разворачиваются в те же смещения: right — это (окно - лист). Именно
// поэтому в стилях стоят они, а не числа: одно и то же слово даёт разный сдвиг для
// окна в 400 точек (портрет) и в 104 (горизонталь), и подгонять руками нечего.
function вырез(тело, окно){
  const v = свойство(тело, 'background-position');
  assert(v, 'в правиле нет background-position');
  // calc(...) считается одним значением: пробелы внутри него не разделители.
  const [сx, сy] = v.match(/calc\([^)]*\)|\S+/g) || [];
  assert(сy !== undefined, `background-position: «${v}» — тест ждёт два значения`);
  const разбор = (t, размерОкна, размерЛиста) => {
    if(t === 'left' || t === 'top') return 0;
    if(t === 'right' || t === 'bottom') return размерОкна - размерЛиста;
    if(t === 'center') return (размерОкна - размерЛиста) / 2;
    // Проценты в background-position считаются от (окно минус лист) — именно поэтому
    // одно и то же calc работает в окнах разной высоты.
    const c = /^calc\(\s*([\d.]+)%\s*([+-])\s*([\d.]+)px\s*\)$/.exec(t);
    if(c) return (размерОкна - размерЛиста) * Number(c[1]) / 100 + (c[2] === '-' ? -1 : 1) * Number(c[3]);
    const пр = /^([\d.]+)%$/.exec(t);
    if(пр) return (размерОкна - размерЛиста) * Number(пр[1]) / 100;
    const m = /^(-?[\d.]+)(px)?$/.exec(t);
    assert(m, `непонятное значение background-position: «${t}»`);
    return Number(m[1]);
  };
  const x = разбор(сx, окно.w, лист.width);
  const y = разбор(сy, окно.h, лист.height);
  return { x0: -x, y0: -y, x1: -x + окно.w, y1: -y + окно.h };
}

const базовое = правило('.turn-indicator');
assert(new RegExp(`background-image:\\s*url\\("${ЛИСТ}"\\)`).test(базовое),
  `2: .turn-indicator берёт не ${ЛИСТ}`);
assert(/background-size:\s*460px 800px/.test(базовое),
  '2b: background-size разошёлся с размером листа — все вырезы посчитаны от 460x800');

const окноПортрет = { w: число(базовое, 'width'), h: число(базовое, 'height') };
const горизБаза = правило('html.is-board-landscape .turn-indicator');
const окноГориз = { w: число(горизБаза, 'width'), h: число(горизБаза, 'height') };
assert(окноПортрет.w > 0 && окноПортрет.h > 0 && окноГориз.w > 0 && окноГориз.h > 0,
  '2c: размеры окон морд не читаются из стилей — проверка устарела');

// Голова в обеих ориентациях одна: вырез задан один раз, в правилах по краю.
const вырезы = {
  'обычный край, козёл': { тело: правило('#mantisIndicator'), голова: 'слева сверху' },
  'обычный край, воробей': { тело: правило('#goatIndicator'), голова: 'слева снизу' },
  'свой край снизу, козёл': { тело: правило('html.is-board-flipped #mantisIndicator'), голова: 'справа снизу' },
  'свой край снизу, воробей': { тело: правило('html.is-board-flipped #goatIndicator'), голова: 'справа сверху' },
  'поза раздумья': { тело: правило('html.is-board-flipped #mantisIndicator.is-thinking'), голова: 'поза раздумья' },
};

// === 3. ГЛАВНОЕ: морда стоит при СВОЕЙ половине поля ===
//
// Козёл синий, воробей зелёный. В портрете кадр делится пополам: синяя половина
// сверху, при своём крае снизу — снизу. Морда обязана переехать вместе с ней,
// иначе окажется над чужим полем.
{
  // Морда прижата к своей грани кадра: верхняя стоит на нуле, нижняя — на (высота кадра
  // минус окно). Кадр и лист одного размера, 460x800, поэтому высоту берём у листа.
  const низ = лист.height - окноПортрет.h;
  const обычныйКозёл = число(вырезы['обычный край, козёл'].тело, 'top');
  const обычныйВоробей = число(вырезы['обычный край, воробей'].тело, 'top');
  const свойКозёл = число(вырезы['свой край снизу, козёл'].тело, 'top');
  const свойВоробей = число(вырезы['свой край снизу, воробей'].тело, 'top');

  assert(обычныйКозёл === 0 && обычныйВоробей === низ,
    `3: на обычном крае козёл должен стоять на 0, воробей на ${низ}, а стоят на `
    + `${обычныйКозёл} и ${обычныйВоробей} — изменилась игра, в которую уже играли`);
  assert(свойКозёл === низ && свойВоробей === 0,
    `3b: при своём крае снизу козёл должен уехать на ${низ}, а воробей наверх, но `
    + `стоят на ${свойКозёл} и ${свойВоробей} — морда осталась над чужой половиной`);
}

// === 4. Каждое окно показывает ровно свою голову ===
//
// «Целиком своя и ни куска чужой» — весь смысл вырезов. Проверяется в обеих
// ориентациях: окна разной высоты, а background-position один, и разойтись они могут
// молча — ключевые слова подстроятся, числа нет.
for(const [имя, { тело, голова }] of Object.entries(вырезы)){
  for(const [ориентация, окно] of [['портрет', окноПортрет], ['горизонталь', окноГориз]]){
    const в = вырез(тело, окно);
    const своя = головы[голова];
    const где = `${имя}, ${ориентация}`;

    assert(в.x0 <= своя.x0 && в.y0 <= своя.y0 && в.x1 >= своя.x1 && в.y1 >= своя.y1,
      `4 (${где}): окно показывает лист ${JSON.stringify(в)}, а своя голова лежит в `
      + `${JSON.stringify(своя)} — часть головы срезана`);

    for(const [чужоеИмя, чужая] of Object.entries(головы)){
      if(чужоеИмя === голова) continue;
      const пересеклись = в.x0 < чужая.x1 && в.x1 > чужая.x0 && в.y0 < чужая.y1 && в.y1 > чужая.y0;
      assert(!пересеклись,
        `4b (${где}): в окно ${JSON.stringify(в)} попадает голова «${чужоеИмя}» `
        + `${JSON.stringify(чужая)} — рядом со своей мордой вылезет чужая`);
    }

    const внутри = рамка(Math.max(0, в.x0), Math.max(0, в.y0),
      Math.min(лист.width, в.x1), Math.min(лист.height, в.y1));
    assert(внутри && внутри.x0 === своя.x0 && внутри.y0 === своя.y0
      && внутри.x1 === своя.x1 && внутри.y1 === своя.y1,
      `4c (${где}): видимое в окне ${JSON.stringify(внутри)} не совпадает со своей головой `
      + `${JSON.stringify(своя)} — в вырез затесалось что-то ещё`);
  }
}

// === 4d. Поза раздумья встаёт ТУДА ЖЕ, где стояла спокойная ===
//
// Жест подставляет второй рисунок той же морды. Если он встанет хоть на точку иначе,
// голова будет дёргаться при каждом появлении копыта — а появляется оно раз в десять
// секунд, так что дёрганье будет видно всем.
//
// Держится это на двух вещах, и обе тут проверяются: по горизонтали вырез не меняется
// вовсе (обе головы прижаты на листе к одной вертикали), а по вертикали сдвиг ровно
// такой, чтобы НИЗ головы остался на нижней грани кадра.
{
  for(const [ориентация, окно] of [['портрет', окноПортрет], ['горизонталь', окноГориз]]){
    const спокойный = вырез(вырезы['свой край снизу, козёл'].тело, окно);
    const думающий = вырез(вырезы['поза раздумья'].тело, окно);

    assert(спокойный.x0 === думающий.x0 && спокойный.x1 === думающий.x1,
      `4d (${ориентация}): вырез позы раздумья съехал по горизонтали (${думающий.x0} против `
      + `${спокойный.x0}) — при появлении копыта голова прыгнет вбок`);

    const низСпокойной = спокойный.y1 - головы['справа снизу'].y1;
    const низДумающей = думающий.y1 - головы['поза раздумья'].y1;
    assert(низСпокойной === низДумающей,
      `4e (${ориентация}): низ спокойной головы стоит в ${низСпокойной} от края окна, а низ `
      + `думающей — в ${низДумающей}. Голова подпрыгнет на ${низДумающей - низСпокойной} точек `
      + 'ровно в тот момент, когда вылезает копыто');
  }
}

// === 5. Отражения: два независимых множителя, и оба на месте ===
//
// --mascot-flip снимает зеркальную укладку правой колонки листа. Он принадлежит
// КОЛОНКЕ, то есть краю, а не углу: обе морды правой колонки отражены, обе левой нет.
{
  const множитель = (тело) => свойство(тело, '--mascot-flip');
  assert(множитель(вырезы['обычный край, козёл'].тело) === null
    && множитель(вырезы['обычный край, воробей'].тело) === null,
    '5: левую колонку листа зачем-то отражают — она нарисована как надо');
  for(const имя of ['свой край снизу, козёл', 'свой край снизу, воробей']){
    assert(множитель(вырезы[имя].тело) === '-1',
      `5b (${имя}): правую колонку перестали отражать — она уложена на лист зеркально, `
      + 'и морда будет смотреть наружу поля');
  }
  assert(/scaleX\(calc\(var\(--mascot-flip\) \* var\(--corner-flip\)\)\)/.test(базовое),
    '5c: множители отражения перестали перемножаться в одном месте — где-то появится второе '
    + 'отражение, и оно молча отменит первое');
}

// === 6. Углы в горизонтали: морды в разных углах, отражён тот, кто в верхнем ===
//
// Угол кадра (0,0) — это правый верхний угол ЭКРАНА, и «внутрь поля» там влево, тогда
// как все головы на листе смотрят вправо. Значит морда в этом углу отражается всегда,
// чья бы она ни была — и наоборот. Это уже про УГОЛ, а не про колонку.
{
  const углы = {
    'обычный край': {
      козёл: правило('html.is-board-landscape #mantisIndicator'),
      воробей: правило('html.is-board-landscape #goatIndicator'),
    },
    'свой край снизу': {
      козёл: правило('html.is-board-flipped.is-board-landscape #mantisIndicator'),
      воробей: правило('html.is-board-flipped.is-board-landscape #goatIndicator'),
    },
  };

  const угол = (тело) => {
    const верх = свойство(тело, 'top') === '0' || число(тело, 'top') === 0;
    const лево = свойство(тело, 'left') === '0' || число(тело, 'left') === 0;
    const низ = свойство(тело, 'bottom') === '0' || число(тело, 'bottom') === 0;
    const право = свойство(тело, 'right') === '0' || число(тело, 'right') === 0;
    if(верх && лево) return 'верхнем';
    if(низ && право) return 'нижнем';
    return null;
  };

  for(const [край, пара] of Object.entries(углы)){
    const угКозёл = угол(пара.козёл);
    const угВоробей = угол(пара.воробей);
    assert(угКозёл && угВоробей,
      `6 (${край}): морда в горизонтали прижата не к углу кадра — её место не читается`);
    assert(угКозёл !== угВоробей,
      `6b (${край}): обе морды уехали в один угол`);

    for(const [кто, тело] of Object.entries(пара)){
      const нужно = угол(тело) === 'верхнем' ? '-1' : '1';
      const есть = свойство(тело, '--corner-flip') ?? '1';
      assert(есть === нужно,
        `6c (${край}, ${кто}): морда стоит в ${угол(тело)} углу кадра, значит --corner-flip `
        + `обязан быть ${нужно}, а стоит ${есть} — голова смотрит наружу поля`);
    }
  }

  // Верхний угол кадра при разных краях занимают РАЗНЫЕ морды: в этом вся суть
  // переворота, и без этой проверки можно оставить обе на прежних местах.
  assert(угол(углы['обычный край'].козёл) !== угол(углы['свой край снизу'].козёл),
    '6d: при перевороте козёл в горизонтали остался в прежнем углу — он должен уехать за '
    + 'своей половиной');

  for(const [край, пара] of Object.entries(углы)){
    for(const кто of ['козёл', 'воробей']){
      const тело = пара[кто] + правило(`html.is-board-landscape #${кто === 'козёл' ? 'mantis' : 'goat'}Indicator`);
      assert(/--turn:\s*-90deg/.test(тело),
        `6e (${край}, ${кто}): встречный поворот пропал — морда ляжет набок вместе с кадром`);
    }
  }
}

// === 7. Старого листа в проекте не осталось ===
//
// Он лежал рядом под похожим именем: сослаться на него по привычке ничего не стоит,
// а увидеть подмену можно только в игре.
{
  assert(!/goat and sparrow\.png/.test(styles) && !/goat and sparrow\.png/.test(source),
    '7: где-то остался старый лист «goat and sparrow.png»');
  assert(source.includes(`"${ЛИСТ}"`),
    '7b: новый лист не в списке предзагрузки — морды моргнут при первом показе');
}

console.log('smoke-mascot-sheet: OK');
